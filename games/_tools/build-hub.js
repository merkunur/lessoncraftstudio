#!/usr/bin/env node
/* build-hub.js — regenerates games/index.html, the local hub the operator opens to test games.
 *
 *   node games/_tools/build-hub.js
 *
 * One card per catalogue row: BUILT games (a games/<slug>/index.html exists) get eleven locale links
 * and, if games/_qa/<slug>/704-en-start.png exists, a thumbnail; unbuilt games are listed greyed with
 * their spec number so the operator can see what is next. Direction A styling, inline CSS, no deps.
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const LOCALES = ["en", "de", "fr", "it", "es", "pt", "nl", "sv", "da", "no", "fi"];
const cat = fs.readFileSync(path.join(ROOT, "design", "catalogue", "CATALOGUE.md"), "utf8").split(/\r?\n/);
const rows = [];
for (const line of cat) {
  const m = line.match(/^\|\s*(\d{3})\s*\|(.*)\|\s*$/); if (!m) continue;
  const c = m[2].split("|").map((s) => s.trim()); if (c.length < 8) continue;
  rows.push({ n: m[1], slug: c[0].replace(/`/g, ""), title: c[1], subject: c[2], topic: c[3], band: c[4].replace(/`/g, ""), pattern: (c[5].match(/P\d+/) || [c[5]])[0] });
}
const built = rows.filter((r) => fs.existsSync(path.join(ROOT, r.slug, "index.html")));
const order = (() => { try { const log = fs.readFileSync(path.join(ROOT, "BUILD-LOG.md"), "utf8"); const m = log.match(/^NEXT:\s*(\d{3})/m); return m ? m[1] : null; } catch (e) { return null; } })();
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;");
const card = (r) => {
  const isBuilt = built.includes(r);
  const thumb = path.join(ROOT, "_qa", r.slug, "704-en-start.png");
  const img = isBuilt && fs.existsSync(thumb) ? `<img src="_qa/${r.slug}/704-en-start.png" alt="">` : `<div class="ph">${isBuilt ? "no screenshot yet" : "not built"}</div>`;
  const links = isBuilt ? LOCALES.map((l) => `<a href="${r.slug}/index.html?lang=${l}">${l}</a>`).join("") : "";
  return `<article class="card ${isBuilt ? "built" : "todo"} ${r.n === order ? "next" : ""}">${img}<h3><span class="n">${r.n}</span> ${esc(r.title)}</h3><p>${esc(r.subject)} · ${esc(r.band)} · ${esc(r.pattern)} · ${esc(r.topic)}</p><div class="links">${links || (r.n === order ? "<em>next to build</em>" : "")}</div><a class="spec" href="design/specs/${r.n}-${r.slug}.md">spec</a></article>`;
};
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>LessonCraft games — local hub</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Baloo+2:wght@600;700&family=Nunito:wght@400;600&display=swap">
<style>
body{margin:0;background:#FBF3E4;color:#2A2A35;font-family:"Nunito",system-ui,sans-serif}
header{padding:28px 32px 8px}h1{font-family:"Baloo 2","Trebuchet MS",sans-serif;color:#146B5E;margin:0;font-size:34px}
header p{color:#6B6B78;margin:6px 0 0}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:18px;padding:20px 32px 48px}
.card{background:#fff;border:1px solid #E7DCC8;border-radius:18px;padding:14px;box-shadow:0 6px 22px rgba(20,107,94,.10),0 1px 3px rgba(0,0,0,.06);display:flex;flex-direction:column;gap:8px}
.card img{width:100%;aspect-ratio:9/7;object-fit:cover;border-radius:12px;background:#FBF6EE}
.ph{aspect-ratio:9/7;border-radius:12px;background:#FBF6EE;color:#6B6B78;display:flex;align-items:center;justify-content:center;font-size:14px}
.card h3{font-family:"Baloo 2",sans-serif;font-size:19px;margin:0;color:#146B5E}.n{color:#F2784B;margin-right:6px}
.card p{margin:0;font-size:13px;color:#6B6B78}.todo{opacity:.55}.next{outline:3px solid #F2784B;opacity:1}
.links{display:flex;flex-wrap:wrap;gap:6px}.links a{display:inline-block;min-width:44px;text-align:center;padding:8px 6px;border-radius:10px;background:#E2F0EC;color:#146B5E;text-decoration:none;font-weight:600;font-size:14px}
.links a:hover{background:#146B5E;color:#FBF3E4}.spec{font-size:12px;color:#6B6B78}
</style></head><body>
<header><h1>LessonCraft games — local hub</h1><p>${built.length} built · ${rows.length - built.length} to go · every built game runs in 11 languages via ?lang=. Regenerated by _tools/build-hub.js${order ? " · next to build: " + order : ""}.</p></header>
<section class="grid">${rows.map(card).join("\n")}</section>
</body></html>`;
fs.writeFileSync(path.join(ROOT, "index.html"), html);
console.log("hub written: " + built.length + " built, " + (rows.length - built.length) + " unbuilt" + (order ? ", NEXT " + order : ""));
