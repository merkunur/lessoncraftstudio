/**
 * SEO Keyword Map — Reference/Audit File
 *
 * This file documents the intended keyword strategy for every English page.
 * It is NOT imported at runtime — the actual content files are the source of truth.
 * Use this file for SEO audits, keyword cannibalization checks, and planning.
 *
 * Three-tier keyword strategy:
 *   Tier 1: "Maker/Generator" keywords (high volume, medium intent) — app pages
 *   Tier 2: "Sell Printables" keywords (medium volume, high intent) — guide/start pages
 *   Tier 3: "Free Printable" keywords (very high volume, low intent) — blog/tool pages
 */

export interface PageKeywordConfig {
  /** Page path, e.g., "/en/apps/word-search-worksheets" */
  path: string;

  /** Page type */
  type: 'APP' | 'GUIDE' | 'BLOG' | 'LANDING' | 'TOOL';

  /** Which keyword tier this page primarily targets */
  primaryTier: 1 | 2 | 3;

  /** The single most important keyword this page should rank for */
  primaryKeyword: string;

  /** 3-5 secondary keywords (long-tail variations, related terms) */
  secondaryKeywords: string[];

  /** LSI (Latent Semantic Indexing) terms to naturally include in content */
  lsiTerms: string[];

  /** New meta title (max 60 chars) */
  metaTitle: string;

  /** New meta description (max 155 chars) */
  metaDescription: string;

  /** New H1 heading (if it needs to change) */
  h1?: string;

  /** URL slug suggestion (only if current slug is suboptimal) */
  suggestedSlug?: string;

  /** Search intent this page serves */
  searchIntent: 'informational' | 'commercial' | 'transactional' | 'navigational';

  /** Internal pages to link TO from this page */
  internalLinksTo: string[];

  /** Internal pages that should link TO this page */
  internalLinksFrom: string[];
}

