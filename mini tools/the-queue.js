      var n = this.n(s), i;
      /* ⚠⚠ EVERYTHING EXCEPT THE WALKER. An `innerHTML=''` here is what
         made the travel unobservable — see the note in `_build`. */
      var walker = this._walker, svg = this._svg;
      [].slice.call(svg.childNodes).forEach(function (c) { if (c !== walker) svg.removeChild(c); });

      /* the platform line */
