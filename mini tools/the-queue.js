    pickEnd: function (st, e) {
      var s = this._st(st);
      if (e !== 'a' && e !== 'b') return null;
      if (s.end === e) return null;
      /* choosing an end always restarts the count — a half-walked count
         carried across a reversal would be a different question */
      return { members: s.members.slice(), end: e, k: 0 };
    },

    step: function (st) {
      var s = this._st(st);
      if (!s.end) return null;                 /* nothing to count from */
      if (s.k >= this.n(s)) return null;       /* the platform ends */
      return { members: s.members.slice(), end: s.end, k: s.k + 1 };
    },

    /* ⚠⚠ ONE AT A TIME, NOT TWO. "The first two" preserves parity, which
       makes the self-same member structurally unreachable — the pitch
       specified a rule that hides the tool's own best moment. */
    board: function (st) {
      var s = this._st(st);
      if (!s.end) return null;
      if (this.n(s) <= GEO.MIN) return null;
      var m = s.members.slice();
      if (s.end === 'a') m.shift(); else m.pop();
      return { members: m, end: s.end, k: 0 };
    },

