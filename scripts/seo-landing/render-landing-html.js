function metaDescription(l) {
  const s = l.p1.replace(/\s+/g, ' ').trim();
  if (s.length <= 158) return s;
  return s.slice(0, 155).replace(/\s+\S*$/, '') + '…';
}
function typeHubSlug(l, locale) { return getAxisSlug('exercise-type', l.coordinate.type, locale) || l.coordinate.type; }
function themeHubSlug(l, locale) { return getAxisSlug('theme', l.coordinate.theme, locale) || l.coordinate.theme; }
function cap(s) { return s.replace(/_/g, ' ').replace(/\b\w/g, (m) => m.toUpperCase()); }

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}
function jsonLd(obj) {
  // Match Next's dangerouslySetInnerHTML safety: escape < to stop </script> breakout.
  return JSON.stringify(obj).replace(/</g, '\\u003c');
}

