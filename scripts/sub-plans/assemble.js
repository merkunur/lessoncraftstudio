#!/usr/bin/env node
/**
 * Assembles the sub packs of one language (Daily Teaching System, Parts 3 and 5).
 *
 * A sub pack is one school day of REVIEW for one grade: a list of blocks, each with one worksheet type of one
 * teaching point. Every page comes from the published catalogue; the only writing is the guest teacher's script of
 * each teaching point (frontend/content/sub-plans/scripts/<loc>.json: say, first, stuck) and the pack's own forms
 * (ui.<loc>.json).
 *
 *   reads   frontend/content/sub-plans/defs/<loc>.json, scripts/<loc>.json, the content graph, the worksheet titles,
 *           out/teaching-graph/decks.tsv (the published pages)
 *   writes  frontend/content/sub-plans/packs.<loc>.json     GENERATED
 *
 *   node scripts/sub-plans/assemble.js --loc=en [--check]
 *
 * A block needs a published core page of its type; where the type also has a harder page it becomes the page for
 * early finishers, and an easier page the page for children who need one. A pack with fewer than five blocks or
 * with no reading, writing and math block fails.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { pagesOf, REPO } = require('../units/catalog.js');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : d; };
const has = (k) => process.argv.includes('--' + k);
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const MUST = ['reading', 'writing', 'math'];
const BLOCKS = ['morning', 'reading', 'phonics', 'writing', 'math', 'problems', 'logic', 'closing'];

function assemble(loc, opt = {}) {
  const problems = [];
  const bad = (m) => problems.push(m);
  const S = path.join(REPO, 'frontend', 'content', 'sub-plans');
  const defs = readJson(path.join(S, 'defs', loc + '.json')).packs;
  const scripts = readJson(path.join(S, 'scripts', loc + '.json')).points;
  const points = new Map(readJson(path.join(REPO, 'frontend', 'content', 'teaching-graph', 'points.json')).points.map((p) => [p.id, p]));
  const strings = readJson(path.join(REPO, 'scripts', 'worksheet-gen', 'i18n', 'strings.' + loc + '.json'));
  const pages = pagesOf(loc, opt.decksText);
  const packs = [], seen = new Set();
  for (const d of defs) {
    const where = loc + ' pack ' + d.id;
    if (seen.has(d.id) || seen.has('/' + d.slug)) bad(where + ': id or slug used twice');
    seen.add(d.id); seen.add('/' + d.slug);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(d.slug || '')) bad(where + ': slug "' + d.slug + '" is not url-safe');
    for (const k of ['title', 'metaTitle', 'metaDescription', 'grade', 'position']) if (!d[k]) bad(where + ': no ' + k);
    const used = new Set(), blocks = [];
    for (const b of d.blocks) {
      const bw = where + ' block ' + b.key;
      if (!BLOCKS.includes(b.key)) { bad(bw + ': unknown kind of block'); continue; }
      const p = points.get(b.point);
      if (!p) { bad(bw + ': no such teaching point ' + b.point); continue; }
      // a day of review: nothing from a later grade than the pack's
      if ('K123'.indexOf(p.grade) > 'K123'.indexOf(String(d.grade))) bad(bw + ': the teaching point is of grade ' + p.grade + ', later than the pack\'s grade');
      if (!p.types.includes(b.type)) { bad(bw + ': type ' + b.type + ' does not belong to ' + b.point); continue; }
      // the point's script, with the sentences that are true of this worksheet type only
      const base = scripts[b.point];
      const sc = base ? Object.assign({}, base, (base.byType || {})[b.type] || {}) : null;
      if (!sc || !sc.say || !sc.first || !sc.stuck) { bad(bw + ': the point has no full script (say, first, stuck) in scripts/' + loc + '.json'); continue; }
      const pg = pages.get(b.type), s = strings[b.type];
      if (!pg || !pg.core.length || !s || !s.title || !s.instruction) { bad(bw + ': type ' + b.type + ' has no published core page, title or instruction in this language'); continue; }
      const pick = (r) => { const x = pg[r].find((y) => !used.has(y.slug)); if (x) used.add(x.slug); return x ? x.slug : null; };
      const block = { key: b.key, minutes: b.minutes, point: b.point, type: b.type, title: s.printTitle || s.title, instruction: s.instruction, core: pick('core') };
      const hard = pick('hard'), easy = pick('easy');
      if (hard) block.hard = hard;
      if (easy) block.easy = easy;
      block.script = { say: sc.say, first: sc.first, stuck: sc.stuck };
      blocks.push(block);
    }
    if (blocks.length < 5) bad(where + ': ' + blocks.length + ' blocks (at least 5)');
    for (const m of MUST) if (!blocks.some((b) => b.key === m)) bad(where + ': no ' + m + ' block');
    packs.push({ id: d.id, slug: d.slug, status: d.status || 'pilot', grade: d.grade, position: d.position, title: d.title, metaTitle: d.metaTitle, metaDescription: d.metaDescription, minutes: blocks.reduce((n, b) => n + b.minutes, 0), blocks });
  }
  return { file: { $comment: 'GENERATED by scripts/sub-plans/assemble.js from defs/' + loc + '.json, scripts/' + loc + '.json, the content graph and the published catalogue. Do not edit by hand.', locale: loc, packs }, problems };
}
const fileText = (f) => JSON.stringify(f, null, 1) + '\n';

if (require.main === module) {
  const loc = arg('loc', 'en');
  const { file, problems } = assemble(loc);
  for (const p of problems) console.log('FAIL  ' + p);
  if (problems.length) { console.log(problems.length + ' problem(s); nothing written'); process.exit(1); }
  const out = path.join(REPO, 'frontend', 'content', 'sub-plans', 'packs.' + loc + '.json');
  if (has('check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== fileText(file)) { console.log('FAIL  ' + path.relative(REPO, out) + ' is not what assemble.js writes'); process.exit(1); }
    console.log(loc + ': sub packs file is current');
  } else {
    fs.writeFileSync(out, fileText(file));
    console.log(loc + ': ' + file.packs.length + ' pack(s), ' + file.packs.reduce((n, p) => n + p.blocks.length, 0) + ' blocks → ' + path.relative(REPO, out));
  }
}
module.exports = { assemble, fileText };
