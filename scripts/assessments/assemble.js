#!/usr/bin/env node
/**
 * Writes what the site shows of the unit checks of a language (Daily Teaching System, Part 7.1):
 * frontend/content/assessments/checks.<loc>.json, from what build-checks.js built (out/assessments/<loc>/checks.json).
 *
 * A check on the site is: its unit, its parts (the lesson each belongs to and how many tasks it has), the lessons
 * that are not in it, the page count of its forms, and a fingerprint of every card of both forms (so the gate can
 * prove on any machine that no card of form A is a card of form B). The PDFs are not in the repository: they are
 * built by build-checks.js and build-teacher-pages.js and uploaded with the Teacher-only files.
 *
 *   node scripts/assessments/assemble.js --loc=en [--check]
 */
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.join(__dirname, '..', '..');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : d; };
const loc = arg('loc', 'en');
const src = path.join(REPO, 'out', 'assessments', loc, 'checks.json');
const out = path.join(REPO, 'frontend', 'content', 'assessments', 'checks.' + loc + '.json');
if (!fs.existsSync(src)) { console.error('no ' + path.relative(REPO, src) + ' (run build-checks.js first; the PC builds, the server only reads the committed file)'); process.exit(1); }
const built = JSON.parse(fs.readFileSync(src, 'utf8')).checks;
const before = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, 'utf8')).checks : [];
const checks = built.map((c) => ({
  unit: c.unit, slug: c.slug, status: (before.find((x) => x.unit === c.unit) || {}).status || 'pilot',
  parts: c.sections.map((s) => ({ part: s.part, lesson: s.lesson, title: s.lessonTitle, type: s.type, tasks: s.cards })),
  notCovered: c.notCovered,
  forms: { A: { pages: c.forms.A.pages, cards: c.forms.A.sigs, pos: c.forms.A.pos }, B: { pages: c.forms.B.pages, cards: c.forms.B.sigs, pos: c.forms.B.pos } },
}));
const text = JSON.stringify({ $comment: 'GENERATED by scripts/assessments/assemble.js from the build of scripts/assessments/build-checks.js. Do not edit by hand; a check goes live by its status here (kept on a rebuild).', locale: loc, checks }, null, 1) + '\n';
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== text) { console.log('FAIL  ' + path.relative(REPO, out) + ' is not the build of today'); process.exit(1); }
  console.log(loc + ': checks file is current');
} else {
  fs.writeFileSync(out, text);
  console.log(loc + ': ' + checks.length + ' check(s) → ' + path.relative(REPO, out));
}
