/** the composer config a face resolves to (FINAL §3); `ppu` = the face's px/unit, `sep` the SEP_PX key */
function cfgFor(mode, d) {
  const floor = FLOORS[d.floor || BAND[mode]];
  const ppu = d.ppu || (d.layout === 'side' || d.layout === 'columns' ? 0.5 : d.layout === 'pairs' ? 1.0 : 0.59);
  const kinds = d.kinds === 'line-all' ? LINE_ALL : (d.kinds || KINDS[mode]);
  const cfg = {
    n: d.count, mode: d.render === 'colour' ? 'colour' : 'line', kinds, pxPerUnit: ppu,
    minRingPx: +(floor.ring * ppu).toFixed(2), minSepPx: d.minSepPx != null ? d.minSepPx : 27, minMovePx: +(floor.move * ppu).toFixed(2),
    minArea: Math.max(floor.area, d.minArea || 0), maxPerItem: 1,
  };
  if (d.heroProb != null) cfg.heroProb = d.heroProb;
  if (d.heroFront != null) cfg.heroFront = d.heroFront;
  if (d.needColour) cfg.needColour = true;
  if (d.minLumaDelta) cfg.minLumaDelta = d.minLumaDelta;
  if (d.noKindCap) cfg.noKindCap = true;
  if (d.distinctKinds) cfg.distinctKinds = true;
  if (d.spread) cfg.spread = d.spread;
  if (d.noSameKeySwap) cfg.noSameKeySwap = true;
  return cfg;
}

/** validator rules 1-11 of K-395 FINAL §5 that are checkable on a locale block (tools/validate-b7-draft.js + the gate) */
function validateBank(block, loc) {
  const errs = [];
  if (!block || typeof block !== 'object') return [`${loc}: no block`];
  const strs = block.strings || {};
  const sk = Object.keys(strs).sort().join(','), mk = MODES.slice().sort().join(',');
  if (sk !== mk) errs.push(`strings keys must be exactly the 11 modes (got ${sk})`);
  const titles = new Set();
  for (const mode of MODES) {
    const s = strs[mode];
    if (!s || !s.title || !s.instruction) { errs.push(`${mode}: strings.${mode} needs title + instruction`); continue; }
    const title = String(s.title).trim(), ins = String(s.instruction).trim();
    const resolved = title.replace(/\{UNIT\}/g, 'Dog in the Garden');
    if ([...resolved].length > 70) errs.push(`${mode}: title "${resolved}" > 70 chars`);
    if (WORKSHEET_WORD.test(title)) errs.push(`${mode}: title carries a worksheet-word`);
    if (titles.has(nfc(resolved))) errs.push(`${mode}: title repeats another face's`); titles.add(nfc(resolved));
    if (K061_HEADS.some((h) => nfc(resolved).includes(h))) errs.push(`${mode}: title "${resolved}" carries K-061's bare head`);
    if (/\{(?!UNIT\})/.test(title)) errs.push(`${mode}: an unknown token in the title`);
    // rule 2: the count in the title IS the mode's count (digit or the locale's number word); how-many carries none
    const want = TITLE_COUNT[mode], ds = digitsOf(title), nw = block.numberWords || {};
    const wordHit = Object.entries(nw).filter(([, w]) => w && new RegExp('(?<!\\p{L})' + String(w).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?!\\p{L})', 'iu').test(title)).map(([n]) => +n);
    if (mode === 'how-many') { if (ds.length || wordHit.length) errs.push('how-many: the title must carry no digit and no number word'); }
    else if (TITLE_COUNT[mode] != null) {
      const hits = [...ds, ...wordHit];
      if (!hits.length) errs.push(`${mode}: the title must carry its count ${want} (a digit or the locale's number word)`);
      else if (hits.some((x) => x !== want)) errs.push(`${mode}: the title carries ${hits.join('/')} but the count is ${want}`);
    } else if (ds.length || wordHit.length) errs.push(`${mode}: the title carries a count on a face that has none`);
    if ((mode === 'base' || mode === 'three-big') && !/\{UNIT\}/.test(title)) errs.push(`${mode}: the title must carry {UNIT}`);
    if (!['base', 'three-big'].includes(mode) && /\{UNIT\}/.test(title)) errs.push(`${mode}: {UNIT} on a face whose title has no scene name`);
    // rule 3: the instruction
    if ([...ins].length > 150) errs.push(`${mode}: instruction > 150 chars`);
    if (!/[.!?…]$/u.test(ins) || /[.!?](?=\s+\p{Lu})/u.test(ins.slice(0, -1))) errs.push(`${mode}: instruction is not ONE sentence ending in a mark`);
    if (FORBIDDEN_VERB[loc] && FORBIDDEN_VERB[loc].test(ins)) errs.push(`${mode}: the instruction says draw / colour in / sort`);
    if (mode === 'how-many' && (digitsOf(ins).some((x) => x !== 2) || Object.values(nw).some((w) => w && new RegExp('(?<!\\p{L})' + w + '(?!\\p{L})', 'iu').test(ins)))) errs.push('how-many: the instruction carries a count');
    for (const t of [title, ins]) if (KEY_PROMISE.test(t)) errs.push(`${mode}: a string promises a key or a screen`);
  }
  // rule 4
  if (!block.starter || /\{/.test(block.starter) || digitsOf(block.starter).some((x) => x !== 2)) errs.push('starter: non-empty, no {slot}, no digit but 2');
  const cw = block.changeWords;
  if (!Array.isArray(cw) || cw.length < 4 || cw.length > 8 || new Set(cw.map(nfc)).size !== cw.length) errs.push('changeWords: 4-8 distinct literals');
  // rule 5
  const tap = block.tap || {};
  for (const k of ['fd-tap', 'fd-tapCount', 'fd-tapMirror', 'fd-tapMissing', 'fd-tapPairs', 'fd-tapWords']) { if (!tap[k]) errs.push(`tap.${k} missing`); else if ([...tap[k]].length > 150) errs.push(`tap.${k} > 150 chars`); }
  // rule 6
  if (!block.strandNames || !block.strandNames['Visual Perception']) errs.push("strandNames['Visual Perception'] missing");
  if (!block.rail || !/^[a-z0-9-]+$/.test(block.rail.slug || '')) errs.push('rail.slug must be ASCII a-z 0-9 -');
  if (block.rail && block.rail.name && K061_HEADS.includes(nfc(block.rail.name))) errs.push('rail.name is a K-061 title');
  // rule 7 + 9: every mode has a pinned unit, the pinned units exist, pairs share a theme, the bases are distinct
  for (const mode of MODES) if (!UNITS[mode] && !(block.unitOverrides || {})[mode]) errs.push(`${mode}: no pinned unit in UNITS`);
  const bases = new Set();
  for (const [mode, u] of Object.entries({ ...UNITS, ...(block.unitOverrides || {}) })) {
    const list = Array.isArray(u) ? u : [u];
    if (!MODES.includes(mode)) { errs.push(`unitOverrides.${mode} is not a face`); continue; }
    const sc = [];
    for (const id of list) { try { sc.push(loadScene(id)); } catch (e) { errs.push(`${mode}: ${e.message}`); } }
    if (sc.length === list.length) {
      if (list.length === 2 && (sc[0].theme !== sc[1].theme || baseIdOf(list[0]) === baseIdOf(list[1]))) errs.push(`${mode}: the pair must share a theme and differ in base id`);
      for (const id of list) { const b = baseIdOf(id); if (bases.has(b)) errs.push(`${mode}: scene base ${b} is pinned on two faces`); bases.add(b); try { sceneName(id, loc); } catch (e) { errs.push(e.message); } }
      if (mode === 'what-changed' || mode === 'write') {
        const keys = new Set(sc[0].items.map((l) => vocabKeyOf(l.src)));
        if (keys.size > 6) errs.push(`${mode}: ${list[0]} has ${keys.size} distinct nouns (≤ 6)`);
        if (cw && cw.some((w) => [...keys].includes(nfc(w)))) errs.push(`${mode}: a change word equals a vocab key of ${list[0]}`);
      }
    }
  }
  // rule 10
  if (KINDS['what-changed'].includes('add')) errs.push('what-changed kinds include add');
  if (KINDS.missing.join() !== 'remove') errs.push('missing kinds must be remove only');
  for (const [k, v] of Object.entries(block.refusals || {})) if (!v || v.length < 12) errs.push(`refusals.${k}: a reason ≥ 12 chars`);
  return errs;
}

/** scene-level rule 8 over data/fd/*.json (the gate runs it; a build never writes) */
function validateScenes(ids) {
  const errs = [];
  for (const id of ids) {
    let s; try { s = loadScene(id); } catch (e) { errs.push(e.message); continue; }
    const seen = new Set();
    for (const c of s.cands || []) {
      if (!c.bbox || !c.diff || !(c.area >= 260)) errs.push(`${id}: a candidate without bbox/diff or area < 260`);
      if (Math.min(c.bbox[2] - c.bbox[0], c.bbox[3] - c.bbox[1]) < 16) errs.push(`${id}: a candidate under 16 units`);
      if (c.bbox[0] < 8 || c.bbox[1] < 8 || c.bbox[2] > 592 || c.bbox[3] > 552) errs.push(`${id}: a candidate on the frame`);
      if (!['any', 'colour'].includes(c.mode)) errs.push(`${id}: candidate mode ${c.mode}`);
      const key = [c.kind, c.item, c.region, c.src, c.s, c.dx, c.colour].join('|');
      if (seen.has(key)) errs.push(`${id}: a duplicate candidate ${key}`); seen.add(key);
    }
    for (const l of s.items || []) if (/nature bw\/bird$/i.test(l.src) && l.bbox[3] < s.hy) errs.push(`${id}: the standing bird sits in the sky`);
  }
  return errs;
}

