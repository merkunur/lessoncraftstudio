/* Weave the wardrobe: harvest a LARGE bank of real long-tail phrasings.
 *
 * The mistake this replaces
 * -------------------------
 * The operator listed a few example angles (theme, age, vocabulary, practice,
 * interactivity, puzzle, fun activity, second-language). I treated those eight
 * as THE taxonomy, probed ONE phrasing each, and declared several angles dead.
 * "giraffe orangutan word search" returns nothing — but that is not how anyone
 * phrases the vocabulary angle; "animal word search for kids" returns a full
 * set. The angle was fine; my sentence was not.
 *
 * So: generate MANY phrasings per idea, ask Google about all of them, and keep
 * whatever is real. Breadth is the point — a tailor's wardrobe, not a uniform.
 * A pattern earns its place by returning suggestions, never by my judgement of
 * whether it sounds like a search.
 *
 * Usage:
 *   node scripts/seo-per-page/harvest-angles.js --locale=en [--delay=160]
 *   node scripts/seo-per-page/harvest-angles.js --locale=en --dry-run   # print seeds only
 */
