#!/usr/bin/env node
/**
 * hmx-text.js — writes data/hmx/text/<loc>.js: the printed words of every Maze Puzzles Level Set scene in one locale
 * (2026-10-12), from data/hmx/text-src/<loc>.js — the locale's own NOUN FORMS (written out, never derived by a guessed
 * rule) and its FACE TEMPLATES (modelled on the locale's published face strings, i18n/strings.<loc>.json).
 *
 *   node tools/level-set/hmx-text.js <loc>[,<loc>…]
 * Checks: every scene has title ≤ 70, printTitle, instruction ≤ 150 (≤ 2 sentences), tap; only the letter hop may carry
 * a token ({LAST}); every noun the scene names has forms; titles unique within the locale.
 */
'use strict';
const fs = require('fs'); const path = require('path');
const { allSkins } = require('../../lib/hmx.js');
const { N } = require('./hmx-en-text.js');
const { validateBank } = require('../../qa/verify-b8-maze-puzzles.js');
const { EN_CHROME } = require('../../data/b8/maze-puzzles.js');

const locs = String(process.argv[2] || '').split(',').filter(Boolean);
if (!locs.length) { console.error('usage: hmx-text.js <loc>[,<loc>…]'); process.exit(2); }
let bad = 0;
for (const loc of locs) {
  const src = require('../../data/hmx/text-src/' + loc + '.js');
  const out = {}; const errs = []; const titles = new Map();
  for (const sk of allSkins()) {
    let t;
    try { t = src.build(sk, N[sk.id] || [], loc); } catch (e) { errs.push(sk.id + ': ' + e.message); continue; }
    if (src.override && src.override[sk.id]) t = { ...t, ...src.override[sk.id] };
    for (const k of ['title', 'printTitle', 'instruction', 'tap']) if (!t[k] || /undefined|null|NaN/.test(t[k])) errs.push(sk.id + ': bad ' + k + ' "' + t[k] + '"');
    if (sk.face === 'collect' && !t.missed) errs.push(sk.id + ': no missed sentence');
    if (t.title && t.title.length > 70) errs.push(sk.id + ': title ' + t.title.length + ' > 70 "' + t.title + '"');
    if (t.instruction && t.instruction.length > 150) errs.push(sk.id + ': instruction ' + t.instruction.length + ' > 150');
    if (t.instruction && (t.instruction.match(/[.!?](\s|$)/g) || []).length > 2) errs.push(sk.id + ': instruction has more than two sentences');
    if (sk.face !== 'letter-hop' && /\{[A-Z]+\}/.test(JSON.stringify(t))) errs.push(sk.id + ': unfilled token');
    if (sk.face === 'letter-hop' && !t.instruction.includes('{LAST}')) errs.push(sk.id + ': letter hop must name {LAST}');
    if (t.title && titles.has(t.title)) errs.push(sk.id + ': title also on ' + titles.get(t.title)); titles.set(t.title, sk.id);
    if (/ {2}|\s[,.]/.test(Object.values(t).join(' '))) errs.push(sk.id + ': double space / space before punctuation');
    // the family gate's word rules (free claim, worksheet word, soft hyphen, tap ≤ 150, final mark, the crane bird)
    for (const e of validateBank({ strings: { [sk.face]: t }, chrome: EN_CHROME }, loc)) errs.push(sk.id + ': ' + e);
    out[sk.id] = t;
  }
  if (errs.length) { bad++; errs.forEach((e) => console.error(loc + ' - ' + e)); }
  const body = Object.entries(out).map(([k, v]) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',').join('\n');
  fs.writeFileSync(path.join(__dirname, '..', '..', 'data', 'hmx', 'text', loc + '.js'),
    `/** data/hmx/text/${loc}.js — GENERATED by tools/level-set/hmx-text.js from data/hmx/text-src/${loc}.js (edit there). */\n'use strict';\nmodule.exports = {\n` + body + '\n};\n');
  console.log(loc + ': ' + Object.keys(out).length + ' scenes' + (errs.length ? ' (' + errs.length + ' errors)' : ''));
}
process.exit(bad ? 1 : 0);
