    _paint: function () {
      var s = this.st, api = this.api, t = api.t.bind(api), i;
      var vals = this.values(s), stage = this.stageOf(s);
      var cap = this.cap(api.settings.band);

      this._stand.setAttribute('data-shape', s.shape);
      this._stand.setAttribute('data-linked', s.linked ? '1' : '0');
      this._stand.setAttribute('data-stage', stage == null ? 'off' : String(stage));
      this._stand.setAttribute('data-dir', this._dir === 'back' ? 'back' : 'fwd');

      /* the lattice geometry comes from the BAND, never from the value.
         ⚠ ONLY the row count is a variable — the ten columns are a fixed
         template because the five-break needs a WIDER SIXTH TRACK, and a
         `--mqu-cols` that nothing read would be a law with nothing
         behind it, which is the defect this file's own header condemns
         in the build it replaces. */
      this._card.style.setProperty('--mqu-rows', String(Math.ceil(cap / GEO.LAT_COLS)));

      for (i = 0; i < 3; i++) {
        var state = 'empty';
        if (i === s.ask) state = s.counted ? 'resolved' : (this.toldCount(s) === 2 && s.linked ? 'ask' : (s.linked ? 'marked' : 'empty'));
        else if (s.told[i]) state = (i === SUM_AT[s.shape]) ? 'between' : 'filled';
        else if (s.linked) state = 'marked';
        this._niche[i].setAttribute('data-state', state);
        this._niche[i].setAttribute('data-i', String(i));

        /* ⚠⚠ THE ANSWER MUST NOT EXIST ANYWHERE IN THE DOM BEFORE IT IS
           COUNTED — not in text, not in an attribute, not in aria. The
           slip is written ONLY for a niche that has been told. */
        this._slip[i].textContent = (i !== s.ask && s.told[i]) ? String(vals[i]) : '';

        var label = t('ariaNiche' + i) + ': ';
        if (i === s.ask && s.counted) label += String(vals[i]);
        else if (i === s.ask && state === 'ask') label += t('ariaAsk');
        else if (i !== s.ask && s.told[i]) label += String(vals[i]);
        else label += t('ariaEmpty');
        this._niche[i].setAttribute('aria-label', label);
        this._niche[i].setAttribute('aria-pressed', String(i !== s.ask && !!s.told[i]));
      }

      /* ⚠⚠ GATE EVERY CONTROL ON ITS OWN MOVE, NOT ON A FLAG. #54's
         controls looked live while the model refused them, and only the
         live page could show it. */
      this._off(this._btn.link, !this.link(null));
      this._btn.link.querySelector('.mqu-label').textContent = s.linked ? t('unlink') : t('link');
      this._btn.link.setAttribute('aria-pressed', String(!!s.linked));
      for (i = 0; i < 3; i++) {
        var b = this._btn['tell' + i];
        this._off(b, !this.tell(null, i));
        b.querySelector('.mqu-label').textContent = s.told[i] ? t('untell' + i) : t('tell' + i);
        b.setAttribute('aria-pressed', String(!!s.told[i]));
        this._off(this._askBtn[i], !this.setAsk(null, i));
        this._askBtn[i].setAttribute('aria-pressed', String(s.ask === i));
      }
      this._off(this._btn.count, !this.count(null));
      this._btn.count.querySelector('.mqu-label').textContent = s.counted ? t('uncount') : t('count');
      this._btn.count.setAttribute('aria-pressed', String(!!s.counted));
      this._off(this._btn.recount, !s.counted);
      this._off(this._btn.totalUp, !this.setTotal(null, s.w + 1, api.settings.band));
      this._off(this._btn.totalDown, !this.setTotal(null, s.w - 1, api.settings.band));

      /* ⚠ visibility, NEVER display. A collapsing group shifts a control
         under the teacher's finger mid-lesson — `doubling-mirror.js:2000`
         records a class's tray being wiped exactly that way. Control
         positions must be identical at every stage. */
      this._here(this._g.setup, stage === 0);
      this._here(this._g.tell, stage === 1 || stage === 2);
      this._here(this._g.ask, stage === 3 || stage === 4);
      this._here(this._g.paper, false);

      /* the counting strip: the stamp follows the question, the wells
         follow the BAND, and only OCCUPANCY follows the value */
      this._strip.setAttribute('data-on', s.counted ? '1' : '0');
      if (this._stripStamp._i !== s.ask) {
        this._stripStamp.innerHTML = '';
        this._stripStamp.appendChild(this._stamp(s.ask));
        this._stripStamp._i = s.ask;
      }
      this._fillLattice(s.counted ? vals[s.ask] : 0, cap);
      this._strip.setAttribute('aria-hidden', s.counted ? 'false' : 'true');
      /* ⚠ THE COUNT REACHES A SCREEN-READER USER AT THE SAME MOMENT IT
         REACHES THE ROOM. A lattice of spans is silent, and silence here
         is the sighted-only reveal defect, not discretion. */
      this._strip.setAttribute('role', 'img');
      this._strip.setAttribute('aria-label', s.counted
        ? this._fmt(t('ariaCounted'), { n: vals[s.ask] }) : '');

      /* at most one recommendation, and NEVER one that hands the class
         its question: at stage 2 the tool has no opinion about which of
         the two remaining facts is told next. */
      this._now(null);
      if (stage === 0) this._now(this._btn.link);
      else if (stage === 3) this._now(this._btn.count);

      var told = this.toldCount(s);
      var rest = stage === 4 ? this._fmt(t('ariaCounted'), { n: vals[s.ask] })
        : (stage === 3 ? t('ariaAsking')
          : (s.linked ? t('ariaLinked') : t('ariaNothing')));
      this._stand.setAttribute('aria-label', this._fmt(t('ariaStand'), { told: told, rest: rest }));
    },

