    endOf: function (st) { return this._st(st).end; },

    /* ⭐ the index the walker is standing on, or null. Counting k from
       end 'a' lands on index k-1; from end 'b' it lands on n-k. */
    landedIndex: function (st) {
      var s = this._st(st);
      if (!s.end || s.k < 1) return null;
      return s.end === 'a' ? s.k - 1 : this.n(s) - s.k;
    },

    /* ⭐⭐ THE EXACT ARITHMETIC THAT IS THE TOOL: counting k from one end
       lands on the member that is (n + 1 - k) from the other. The two
       coincide iff k === (n+1)/2, which exists only for ODD n — so the
       self-same member is a reachable, countable event, never a fluke. */
    mirrorK: function (st, k) { return this.n(st) + 1 - k; },

    isSelfSame: function (st, k) {
      var n = this.n(st);
      return n % 2 === 1 && k === (n + 1) / 2;
    },

