#!/usr/bin/env node
/**
 * gen-b6var-specs.js — nt5-F (b6) variation faces: emits the thin variation spec
 * modules for the LAST batch of 20 printable types (bases shipped 2026-09-14).
 *
 * Same shape as gen-b2var-specs.js (each emitted file spreads its base spec and
 * overrides {id, slug, difficulty, i18n} + declared extras only), with two
 * differences bought by this batch's scale:
 *
 *   1. ROWS live in ONE MODULE PER FAMILY under tools/b6var-rows/<key>.js, so the
 *      twenty face builders never write the same file. Each module exports
 *        ROWS        — [dir, id, fileSlug, baseFile, srcLevel, overrides, enTitle, enInstruction, extra?]
 *        HANDWRITTEN — [{id, dir, file}] specs written by hand (a factory instance,
 *                      a face whose extra needs a function value); emitted by nobody,
 *                      pruned by nobody, but listed so the waves + gates see them.
 *      Families are concatenated in README id order (FAMILIES below).
 *   2. Ids are FIXED by docs/worksheet-gen/b6-designs/_records/b6var-id-allocation.json
 *      (tools/alloc-b6var-ids.js) — a row whose id is not the allocation's id for that
 *      (family, face) REFUSES, so a builder cannot drift onto a sibling's block.
 *
 * CODE faces are rows too: the base spec carries an additive knob (`layout` / `mode`
 * / `steps` …) that its build + verify read, stamped only when declared, and the row
 * merely sets it in the difficulty override. That keeps the base byte-identical for
 * the waves it already publishes (tools/b6-baseline.js is the proof).
 *
 * Idempotent: re-running overwrites exactly its own files; pruneStale removes a file
 * this generator emitted under a since-renamed slug (the duplicate-id trap of nt20-B).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const ROWS_DIR = path.join(__dirname, 'b6var-rows');
const ALLOC = path.join(ROOT, '..', '..', 'docs', 'worksheet-gen', 'b6-designs', '_records', 'b6var-id-allocation.json');

// README id order — key = the family key (= the rows module name)
const FAMILIES = [['K-379', 'story-sequencing'], ['K-380', 'healthy-habits'], ['G1-398', 'habitats'], ['G1-399', 'sink-or-float'], ['G2-377', 'cursive-writing']];

function loadRows() {
  const alloc = JSON.parse(fs.readFileSync(ALLOC, 'utf8')).faces;
  const rows = [], hand = [], missing = [];
  for (const [fam, key] of FAMILIES) {
    const mod = path.join(ROWS_DIR, key + '.js');
    if (!fs.existsSync(mod)) { missing.push(key); continue; }
    const m = require(mod);
    const allowed = new Set(alloc.filter((a) => a.family === fam).map((a) => a.id));
    for (const r of m.ROWS || []) {
      if (!allowed.has(r[1])) throw new Error(`b6var-rows/${key}.js: id ${r[1]} is not in ${fam}'s allocation (${[...allowed].join(' ')})`);
      rows.push(r);
    }
    for (const h of m.HANDWRITTEN || []) {
      if (!allowed.has(h.id)) throw new Error(`b6var-rows/${key}.js: handwritten id ${h.id} is not in ${fam}'s allocation`);
      if (!fs.existsSync(path.join(ROOT, 'types', h.dir, h.file))) throw new Error(`b6var-rows/${key}.js: handwritten spec missing on disk: types/${h.dir}/${h.file}`);
      hand.push(h);
    }
  }
  return { rows, hand, missing };
}

function emit(row) {
  const [dir, id, slug, baseFile, src, over, title, instr, extra] = row;
  const baseId = baseFile.replace(/^([A-Z0-9]+-[0-9]+)-.*$/, '$1');
  const baseDir = { K: 'k', G1: 'g1', G2: 'g2', G3: 'g3' }[baseId.split('-')[0]];
  if (!baseDir) throw new Error('gen-b6var-specs: cannot resolve band dir for base ' + baseId);
  if (!fs.existsSync(path.join(ROOT, 'types', baseDir, baseFile))) throw new Error(id + ': base spec missing on disk: types/' + baseDir + '/' + baseFile);
  const rel = baseDir === dir ? './' + baseFile : '../' + baseDir + '/' + baseFile;
  const lines = [];
  lines.push('/** ' + id + ' — ' + title + '. nt5-F variation of ' + baseId + ' (generated by tools/gen-b6var-specs.js from tools/b6var-rows/). */');
  lines.push("'use strict';");
  lines.push("const base = require('" + rel + "');");
  lines.push('// One object for all three levels: the waves ship d2 only, so a face must');
  lines.push('// render identically whichever level is asked for. Spreading the base entry');
  lines.push('// (not a JSON literal) carries function-valued params through intact.');
  lines.push('const D = { ...base.difficulty[' + src + '], ...' + JSON.stringify(over || {}) + ' };');
  lines.push('module.exports = {');
  lines.push('  ...base,');
  lines.push("  id: '" + id + "',");
  lines.push("  slug: '" + slug + "',");
  lines.push('  difficulty: { 1: D, 2: D, 3: D },');
  const ins = instr === null ? '' : ', instruction: ' + JSON.stringify(instr);
  lines.push('  i18n: { en: { title: ' + JSON.stringify(title) + ins + ' } },');
  if (extra) for (const k of Object.keys(extra)) lines.push('  ' + k + ': ' + JSON.stringify(extra[k]) + ',');
  lines.push('};');
  const file = path.join(ROOT, 'types', dir, id + '-' + slug + '.js');
  fs.writeFileSync(file, lines.join('\n') + '\n');
  return file;
}

function pruneStale(rows, hand) {
  const want = new Map(rows.map((r) => [r[1], r[0] + '/' + r[1] + '-' + r[2] + '.js']));
  for (const h of hand) want.set(h.id, h.dir + '/' + h.file);
  let removed = 0;
  for (const dir of ['k', 'g1', 'g2', 'g3']) {
    const abs = path.join(ROOT, 'types', dir);
    for (const f of fs.readdirSync(abs)) {
      const m = /^([A-Z0-9]+-[0-9]+)-/.exec(f);
      if (!m || !want.has(m[1])) continue;
      if (want.get(m[1]) !== dir + '/' + f) { fs.unlinkSync(path.join(abs, f)); removed++; }
    }
  }
  return removed;
}

function main() {
  const { rows, hand, missing } = loadRows();
  const ids = new Set(), slugs = new Set();
  for (const r of rows) {
    if (ids.has(r[1])) throw new Error('duplicate id ' + r[1]);
    if (slugs.has(r[2])) throw new Error('duplicate slug ' + r[2]);
    ids.add(r[1]); slugs.add(r[2]);
  }
  for (const h of hand) { if (ids.has(h.id)) throw new Error('handwritten id also in ROWS: ' + h.id); ids.add(h.id); }
  const pruned = pruneStale(rows, hand);
  for (const r of rows) emit(r);
  console.log('gen-b6var-specs: emitted ' + rows.length + ' variation specs + ' + hand.length + ' handwritten (' + ids.size + ' faces from ' +
    (FAMILIES.length - missing.length) + '/' + FAMILIES.length + ' families' + (missing.length ? '; no rows yet: ' + missing.join(', ') : '') + ')' +
    (pruned ? ' (pruned ' + pruned + ' stale file(s) from a slug rename)' : ''));
  return { rows, hand };
}

if (require.main === module) main();
module.exports = { FAMILIES, loadRows, ROWS_DIR };
