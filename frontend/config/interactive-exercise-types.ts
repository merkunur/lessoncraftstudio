/**
 * interactive-exercise-types.ts — which worksheet types run in a browser.
 *
 * WHY THIS EXISTS
 * ---------------
 * Until this file, the codebase had NO print-only concept at all: not on
 * `Landing`, not on `model Deck` (`htmlUrl` is non-null for printables too — it
 * points at a *static* preview page), and not in `topics-taxonomy.json`. The
 * manifest flag `printable_only` is validated at publish
 * (`scripts/publish-cli/bundle.js:71`) and then dropped at the DB boundary. So
 * every browse surface and every landing page advertised a "Play interactive"
 * button and an "Answer key" for worksheets that have neither — you cannot trace
 * a letter with a mouse, and a tracing sheet ships no answer key.
 *
 * WHY A COMMITTED SET RATHER THAN A DB LOOKUP
 * -------------------------------------------
 * Interactivity is a property of the GENERATOR, not of an individual sheet, and
 * two of the three consumers cannot reach a database:
 *   - `scripts/seo-landing/render-landing-html.js` runs at deploy time and
 *     writes the ~32,700 static landing pages users actually see;
 *   - `app/[locale]/worksheets/[slug]/page.tsx` runs zero Prisma queries today
 *     and should keep it that way;
 *   - the hub's Interactive tab must filter even when the DB read fails.
 * A pure constant answers all three. `Deck.answerKeyUrl` remains the per-deck
 * signal for whether to render an Answer key link (see `canonicalDeckAssets`),
 * which is a different question at a different grain.
 *
 * HOW THE SET WAS DERIVED (measured, not asserted)
 * ------------------------------------------------
 * `groupBy(exerciseType)` over all 44,981 published monolingual decks in
 * production, 2026-09-03: 95 exercise types, 30 in which EVERY deck has an
 * answer key, 65 in which NO deck has one, and **0 mixed**. The 30 are exactly
 * the canonical 29 worksheet-generator apps (CLAUDE.md §14.10) plus
 * `picture-trail`, the en-locale axis key for the `picture-path` app. Two
 * independent signals — "was generated by one of the 29 apps" and "has an answer
 * key" — agree on all 44,981 rows with zero disagreement.
 *
 * `scripts/audit-worksheet-formats.js` re-runs that reconciliation and fails if
 * any type becomes mixed or this set drifts from the database. Run it after any
 * new generator ships.
 *
 * SAFETY RULE: an UNKNOWN type is treated as print-only. A missing Play button
 * on an interactive sheet is a small loss; a Play button that opens a static
 * page is the defect this file exists to remove.
 */

/**
 * The 29 canonical apps (§14.10) + `picture-trail`.
 *
 * `picture-trail` is not an app — it is the en-locale exercise-type axis key
 * for the `picture-path` app (other locales keep `picture-path`). Both are
 * listed because `Landing.coordinate.type` and `Deck.exerciseType` carry the
 * axis key, not the app name.
 */
export const INTERACTIVE_EXERCISE_TYPES: ReadonlySet<string> = new Set([
  'addition',
  'alphabet-train',
  'big-small',
  'bingo',
  'chart-count',
  'code-addition',
  'crossword',
  'cryptogram',
  'find-and-count',
  'find-objects',
  'grid-match',
  'matching',
  'math-puzzle',
  'math-worksheet',
  'missing-pieces',
  'more-less',
  'odd-one-out',
  'pattern-train',
  'pattern-worksheet',
  'picture-path',
  'picture-sort',
  'picture-trail',
  'prepositions',
  'shadow-match',
  'subtraction',
  'sudoku',
  'treasure-hunt',
  'word-guess',
  'word-scramble',
  'wordsearch',
]);

/** True when this worksheet type has a browser-playable version. */
export function isInteractiveType(exerciseType: string | null | undefined): boolean {
  return !!exerciseType && INTERACTIVE_EXERCISE_TYPES.has(exerciseType);
}

/** True when this worksheet type is a printable PDF only — the badged case. */
export function isPrintOnlyType(exerciseType: string | null | undefined): boolean {
  return !isInteractiveType(exerciseType);
}
