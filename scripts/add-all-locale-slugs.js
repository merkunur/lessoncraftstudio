const newLocales = ['fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];

function processFile(filePath, slugMap, idField) {
  console.log(`\nProcessing: ${path.basename(filePath)}`);
  let content = fs.readFileSync(filePath, 'utf8');

  let count = 0;
  let missing = 0;

  // For each entry in the slug map, find the matching slugs object and add locales
  for (const [id, locales] of Object.entries(slugMap)) {
    // Find the pattern: idField: 'id',\n    slugs: { en: '...', de: '...' },
    // We need to match the slugs line for this specific entry
    // Strategy: find the id, then find the next "slugs: {" and add locales before the closing "}"

    // Build regex to find the entry block
    const idEscaped = id.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');

    // Match: idField: 'id',\n    slugs: { ... },
    const blockRegex = new RegExp(
      `(${idField}:\\s*'${idEscaped}',\\s*\\n\\s*slugs:\\s*\\{[^}]*)(\\})`,
      's'
    );

    const match = content.match(blockRegex);
    if (!match) {
      console.log(`  WARNING: Could not find entry for '${id}'`);
      missing++;
      continue;
    }

    // Check if locales already exist
    if (match[1].includes("fr:")) {
      // Already has locales, skip
      continue;
    }

    // Build the locale additions
    const additions = newLocales.map(locale => {
      const slug = locales[locale];
      if (!slug) {
        console.log(`  WARNING: No ${locale} slug for '${id}'`);
        return null;
      }
      return `${locale}: '${slug}'`;
    }).filter(Boolean).join(', ');

    // Replace: add locales before closing brace
    const replacement = match[1] + ', ' + additions + ' }';
    content = content.replace(blockRegex, replacement);
    count++;
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`  Updated ${count} entries (${missing} missing)`);
}

