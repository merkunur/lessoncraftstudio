#!/usr/bin/env node
/**
 * Writes docs/daily-teaching-system/curricula/STATUS.md from the committed registries (Daily Teaching System, Part 2):
 * for each registry its documents (with what each builder checked), the number of nodes, and what the crosswalk says
 * of the 306 teaching points — by subject, how many have a "teaches" row, only "prepares"/"extends" rows, or nothing.
 *
 *   node scripts/curricula/report.js            writes the file
 *   node scripts/curricula/report.js --check    exit 1 when the committed file is not what this would write
 */
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.join(__dirname, '..', '..');
const ROOT = path.join(REPO, 'frontend', 'content', 'curricula');
const OUT = path.join(REPO, 'docs', 'daily-teaching-system', 'curricula', 'STATUS.md');
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const points = readJson(path.join(REPO, 'frontend', 'content', 'teaching-graph', 'points.json')).points;
const display = readJson(path.join(ROOT, 'display.json'));
const SUBJECTS = ['math', 'literacy', 'science', 'social', 'health', 'arts', 'thinking', 'sel'];
const ORDER = ['en', 'en-tx', 'de', 'de-by', 'de-nw', 'de-sn', 'sv', 'es', 'pt', 'fr', 'nl', 'fi', 'no', 'da', 'it'];

let md = '# The curriculum registries: status\n\nGENERATED by `node scripts/curricula/report.js` from the committed registries. Do not edit by hand.\n\n';
md += 'A teaching point counts as **taught** when at least one of its rows says `teaches`; as **near** when it has rows but none says `teaches` (it prepares or extends an objective); as **none** when the curriculum has no counterpart.\n\n';
md += '| Registry | Documents | Nodes | Taught | Near | None |\n|---|---:|---:|---:|---:|---:|\n';
const detail = [];
const regs = fs.readdirSync(ROOT).filter((r) => fs.existsSync(path.join(ROOT, r, 'framework.json'))).sort((a, b) => (ORDER.indexOf(a) + 100) % 100 - (ORDER.indexOf(b) + 100) % 100);
for (const r of regs) {
  const fw = readJson(path.join(ROOT, r, 'framework.json'));
  const cwFile = path.join(ROOT, r, 'crosswalk.json');
  const name = (display.registries[r] || {}).name || r;
  if (!fs.existsSync(cwFile)) { md += '| `' + r + '` ' + name + ' | ' + fw.frameworks.length + ' | ' + fw.nodes.length + ' | — | — | — |\n'; continue; }
  const cw = readJson(cwFile).points;
  const by = {};
  let taught = 0, near = 0, none = 0;
  for (const p of points) {
    const e = cw[p.id] || {};
    const k = (e.rows || []).some((x) => x.rel === 'teaches') ? 'taught' : (e.rows || []).length ? 'near' : 'none';
    by[p.subject] = by[p.subject] || { taught: 0, near: 0, none: 0, n: 0 };
    by[p.subject][k]++; by[p.subject].n++;
    if (k === 'taught') taught++; else if (k === 'near') near++; else none++;
  }
  md += '| `' + r + '` ' + name + ' | ' + fw.frameworks.length + ' | ' + fw.nodes.length + ' | ' + taught + ' | ' + near + ' | ' + none + ' |\n';
  let d = '\n## `' + r + '` — ' + name + '\n\n';
  for (const f of fw.frameworks) d += '- **' + f.title + '** (' + f.publisher + ', ' + f.year + '). ' + (f.version || '') + '. Read from ' + String(f.readFrom).split(' ')[0] + (String(f.readFrom).includes(' ') ? ' and ' + (String(f.readFrom).split(' ').length - 1) + ' more' : '') + ' on ' + f.accessed + '. Checked: ' + f.checkedAgainstPdf + '.\n';
  d += '\n| Subject | Points | Taught | Near | None |\n|---|---:|---:|---:|---:|\n';
  for (const s of SUBJECTS) if (by[s]) d += '| ' + s + ' | ' + by[s].n + ' | ' + by[s].taught + ' | ' + by[s].near + ' | ' + by[s].none + ' |\n';
  detail.push(d);
}
md += detail.join('');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== md) { console.log('FAIL  ' + path.relative(REPO, OUT) + ' is not what report.js writes'); process.exit(1); }
  console.log('STATUS.md is current');
} else { fs.writeFileSync(OUT, md); console.log('wrote ' + path.relative(REPO, OUT) + ' (' + regs.length + ' registries)'); }
