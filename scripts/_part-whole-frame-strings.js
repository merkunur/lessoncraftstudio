/* =====================================================================
   _part-whole-frame-strings.js — the SoT for the Number Bonds Board
   strings block. Applied to the tool by
   scripts/apply-part-whole-frame-locales.js, which REFUSES to write
   rather than ship a defect.
   ---------------------------------------------------------------------
   Every non-EN block below was authored by a THREE-PERSON NATIVE PANEL
   (linguist + primary maths teacher + product editor) that read the
   MODEL as well as the copy, and that was handed the English as a
   SOURCE TO AUDIT rather than a target to translate. Between them the
   panels found seven model bugs and two dozen copy defects — including
   two the whole gate suite was blind to: the colour picker shipping
   three BLANK chips, and a free visitor's Ctrl+P printing nothing.

   Rulings worth keeping, because the obvious edit will undo them:
     · de / it / pt / nl name the tool by the ACTION, not the furniture,
       because every container noun in those languages is already the
       title of a sibling: `Marco`, `Quadro`, `cadre`, `telaio`, `ram`,
       `ramme` all belong to the ten-frame or the rekenrek.
     · sv / da / no DROPPED their cloth noun for a VERB PAIR. sv `duken`
       is also the projection screen; sv `ramen` is also the noodle dish;
       da/no `klæder`/`klær` means *clothes*. Only fi keeps a cloth noun
       (`liina`), which the house already ships in number-balance.
     · `notationFam` is NEVER "the four operations" in it/pt — that phrase
       means addition/subtraction/multiplication/division, and these are
       four members of ONE fact family. Both panels vetoed it separately.
     · es `splitFrame` uses `son`, not `es`: the plural copula is the
       canonical Spanish arithmetic form and is what place-value-core
       already ships.
     · fr avoids `part` (fraction-kitchen owns it, and in French primary
       maths *une part* is an EQUAL share — the misconception this tool
       exists to break) and avoids `du tout`, which reads as *pas du tout*.
     · fi distinguishes `luku` (the number) from `lukumäärä` (the count) —
       the honest fix for a setting label English blurs.
     · the Nordic plan name is `Premium`, measured 58:11 across the shipped
       tools and matching each locale's own `billing.tiers` name.
     · de uses `Lehrkraft-Abo`, the name on the pricing page the button
       actually opens; nl uses `Leerkracht-abonnement` for the same reason.
       ⚠ Both are inconsistent with other shipped tools, which want the
       same sweep — recorded, not silently diverged from.
   ===================================================================== */
