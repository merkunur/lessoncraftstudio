#!/usr/bin/env node
/**
 * The maker screen's own words (buttons, labels, sentences) — ARCHITECTURE §12.
 *
 * Source of truth: frontend/messages/makers/<locale>.json, one file per language (en = American English, es = Mexican
 * Spanish, pt = Brazilian Portuguese). This script checks them and writes the one script the screen loads:
 *   out/makers/ui-strings.js   → window.LCS_MAKER_UI = { en: {...}, de: {...}, ... }
 *
 * Refuses (exit 1) when:
 *   - a language lacks a key English has, or has a key English does not (key parity, both ways);
 *   - a value is empty;
 *   - a non-English value is the English text word for word (an untranslated string), except the few that are the same
 *     in every language on purpose (SAME_EVERYWHERE: "A4", the maker names that are product names, …).
 *
 *   node scripts/makers/build-ui-strings.js            build (build-bundles.js calls it)
 *   node scripts/makers/build-ui-strings.js --poison   each rule must fire on a broken copy
 */
'use strict';
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');
const SRC = path.join(REPO, 'frontend', 'messages', 'makers');
const OUT = path.join(REPO, 'out', 'makers', 'ui-strings.js');
const LOCALES = ['en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
// the same as English on purpose: in every language (paper names), or in one language where the word is the same
const SAME_EVERYWHERE = new Set(['a4', 'letter', 'makers.tangram']);   // Tangram is the puzzle's name in every one of the 11 languages
const SAME_IN = { fr: new Set(['page', 'border_double', 'ink_orange']), es: new Set(['color']), de: new Set(['ink_orange']), sv: new Set(['ink_orange']), da: new Set(['ink_orange']) };
// Bingo is the game's name in de pt it nl sv da no fi — what those languages' bingo pages call it (es Lotería, fr Loto)
for (const l of ['de', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi']) (SAME_IN[l] = SAME_IN[l] || new Set()).add('makers.bingo');

const flat = (o, pre = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, pre + k + '.') : [[pre + k, v]]));

function check(all) {
  const fails = [];
  const en = new Map(flat(all.en));
  for (const loc of LOCALES) {
    const m = new Map(flat(all[loc] || {}));
    for (const k of en.keys()) if (!m.has(k)) fails.push(`${loc}: missing "${k}"`);
    for (const k of m.keys()) if (!en.has(k)) fails.push(`${loc}: "${k}" is not an English key`);
    for (const [k, v] of m) {
      if (typeof v !== 'string' || !v.trim()) fails.push(`${loc}: "${k}" is empty`);
      else if (loc !== 'en' && v === en.get(k) && !SAME_EVERYWHERE.has(k) && !(SAME_IN[loc] && SAME_IN[loc].has(k)) && !/^[A-Z0-9 ]{1,9}$/.test(v)) fails.push(`${loc}: "${k}" is the English text ("${v}")`);
    }
  }
  return fails;
}

function load() {
  const all = {};
  for (const loc of LOCALES) all[loc] = JSON.parse(fs.readFileSync(path.join(SRC, loc + '.json'), 'utf8'));
  return all;
}

function build() {
  const all = load();
  const fails = check(all);
  if (fails.length) { fails.slice(0, 20).forEach((f) => console.error('FAIL ' + f)); throw new Error(`ui strings: ${fails.length} problems`); }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `// generated by scripts/makers/build-ui-strings.js from frontend/messages/makers/<locale>.json — do not edit\nwindow.LCS_MAKER_UI = ${JSON.stringify(all)};\n`);
  return { keys: flat(all.en).length, locales: LOCALES.length };
}

module.exports = { build, check };

if (require.main === module) {
  if (process.argv.includes('--poison')) {
    const base = load();
    const clone = () => JSON.parse(JSON.stringify(base));
    const cases = [
      ['missing key', (a) => { delete a.fi.print; }],
      ['extra key', (a) => { a.de.extraKey = 'x'; }],
      ['empty value', (a) => { a.sv.close = ' '; }],
      ['untranslated', (a) => { a.it.print = a.en.print; }],
    ];
    let ok = check(base).length === 0;
    console.log((ok ? 'ok   ' : 'FAIL ') + 'the real strings pass');
    for (const [name, mut] of cases) { const a = clone(); mut(a); const f = check(a); console.log((f.length ? 'ok   ' : 'FAIL ') + name + ' is refused'); if (!f.length) ok = false; }
    if (!ok) process.exitCode = 1;
  } else {
    const r = build();
    console.log(`ui strings: ${r.keys} keys × ${r.locales} languages → ${path.relative(REPO, OUT)}`);
  }
}
