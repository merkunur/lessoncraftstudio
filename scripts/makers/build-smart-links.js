#!/usr/bin/env node
/**
 * The old landings' smart-link table (ARCHITECTURE §13): old app → the new maker + the template its landing opens,
 * written from scripts/makers/topic-map.js (`oldApps` / `oldAppTemplates`) to
 *
 *     frontend/lib/makers/smart-links.json
 *
 * a COMMITTED file the website reads (frontend/lib/makers/smart-link.ts) — the website never imports the build
 * scripts. Re-run after any change to oldApps / oldAppTemplates; the registration gate fails when the file drifts.
 *
 *   node scripts/makers/build-smart-links.js            write
 *   node scripts/makers/build-smart-links.js --check    exit 1 when the committed file differs (the gate's call)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.join(__dirname, '..', '..');
const FILE = path.join(REPO, 'frontend', 'lib', 'makers', 'smart-links.json');

function build() {
  const { MAKERS } = require('./topic-map.js');
  const links = {};
  for (const m of MAKERS) {
    for (const app of m.oldApps || []) {
      if (links[app] && !(app === 'writing')) throw new Error(`old app ${app} is listed by two makers (${links[app].maker}, ${m.id})`);
      if (links[app]) continue; // 'writing' is shared by design (old-landings.js note); the first maker keeps the landing
      const t = (m.oldAppTemplates && m.oldAppTemplates[app]) || null;
      links[app] = { maker: m.id, template: t };
    }
  }
  const sorted = Object.fromEntries(Object.keys(links).sort().map((k) => [k, links[k]]));
  return JSON.stringify({ source: 'scripts/makers/topic-map.js (oldApps, oldAppTemplates) — generated by scripts/makers/build-smart-links.js; do not edit', links: sorted }, null, 1) + '\n';
}

if (require.main === module) {
  const want = build();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
    if (have !== want) { console.log('FAIL smart-links.json differs from topic-map.js — run node scripts/makers/build-smart-links.js'); process.exit(1); }
    console.log('smart-links.json is in sync with topic-map.js');
  } else {
    fs.writeFileSync(FILE, want);
    console.log('wrote ' + path.relative(REPO, FILE) + ' (' + Object.keys(JSON.parse(want).links).length + ' old apps)');
  }
}
module.exports = { build, FILE };
