    /* ⭐⭐ THE AMBIGUITY PREDICATE. A frame is worth showing only if
       different questions about it have DIFFERENT answers. b=c makes
       "how many stayed" and "how many left" the same number; c=2b or
       b=2c makes the difference equal to one of the parts; a zero part
       makes a question vacuous. Measured over a=3..16: 102 legal of 119.
       ⚠ (4,2,2) is the frame a naive generator emits most often and it
       gives EVERY question the answer 2. */
    legal: function (b, c) {
      if (!(b > 0) || !(c > 0)) return false;
      if (b !== Math.round(b) || c !== Math.round(c)) return false;
      if (b === c) return false;
      if (c === 2 * b) return false;
      if (b === 2 * c) return false;
      return true;
    },

    /* every legal frame at a given total, in a fixed order */
    framesFor: function (a) {
      var out = [], b;
      for (b = 1; b < a; b++) if (this.legal(b, a - b)) out.push({ a: a, b: b, c: a - b });
      return out;
    },

    cap: function (range) { return range === 'sixteen' ? GEO.CAP : 10; },

    newState: function (range, pick) {
      var cap = this.cap(range), all = [], a;
      for (a = GEO.FLOOR; a <= cap; a++) all = all.concat(this.framesFor(a));
      /* ⚠ `all` is never empty: a=4 gives (1,3) and (3,1) at every cap. */
      var f = all[(pick == null ? Math.floor(Math.random() * all.length) : pick) % all.length];
      return { a: f.a, b: f.b, c: f.c, ledge: false, air: false, tally: false };
    },

    _st: function (st) { return st || this.st; },

    /* how many shutters are down */
    hidden: function (st) {
      var s = this._st(st);
      return (s.ledge ? 1 : 0) + (s.air ? 1 : 0);
    },

    /* ⭐⭐ THE ENUMERATION. Every pair still consistent with what can be
       seen. With one shutter down the visible part fixes the other, so
       there is exactly one; with both down every decomposition of `a`
       into two non-zero parts survives — and THAT is K.OA.A.3.
       ⚠ It is derived from the VISIBLE state, never from the frame the
       tool happens to be holding, so it cannot leak the answer. */
    consistent: function (st) {
      var s = this._st(st), out = [], b;
      if (!s.ledge && !s.air) return out;
      if (s.ledge && !s.air) return [{ b: s.a - s.c, c: s.c }];
      if (!s.ledge && s.air) return [{ b: s.b, c: s.a - s.b }];
      for (b = 1; b < s.a; b++) out.push({ b: b, c: s.a - b });
      return out;
    },

    /* ---- the moves. Each returns a NEW state, or null for a refusal.
       ⚠ null is the single refusal channel: the paint gates every
       control on its own move returning non-null, so a control can
       never LOOK live while the model refuses it. #54 shipped exactly
       that defect and only the live page could see it. */

    shut: function (st, which) {
      var s = this._st(st);
      if (which !== 'ledge' && which !== 'air') return null;
      var n = { a: s.a, b: s.b, c: s.c, ledge: s.ledge, air: s.air, tally: s.tally };
      n[which] = !n[which];
      /* ⚠ opening the last shutter must put the tally away with it, or
         a tally sits on screen describing a frame nobody is hiding. */
      if (!n.ledge && !n.air) n.tally = false;
      return n;
    },

    showTally: function (st, on) {
      var s = this._st(st);
      /* ⚠⚠ THE ANSWER MUST NOT EXIST BEFORE THE QUESTION DOES. With no
         shutter down there is nothing hidden, so there is nothing to
         enumerate — and a tally that appeared anyway would be the tool
         asking its own question. */
      if (on && this.hidden(s) === 0) return null;
      if (!!s.tally === !!on) return null;
      return { a: s.a, b: s.b, c: s.c, ledge: s.ledge, air: s.air, tally: !!on };
    },

    deal: function (st, range, pick) {
      return this.newState(range, pick);
    },

