// Integrate the All About Me new-question design + the 11 native panels into the data banks. Idempotent.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const D = require('./design.js');
const m = require(path.join(ROOT, 'image-cache/resolve.js')).manifest();
const LOCS = ['en', 'de', 'es', 'fr', 'it', 'pt', 'nl', 'sv', 'da', 'no', 'fi'];
const EXCLUDE = { fi: ['crab', 'pancake'], da: ['cereal'], sv: ['coat'], no: ['coat'] };
const JUMPROPE = { en: 'I can jump rope', da: 'Jeg kan sjippe' };
const vk = (t, n) => { const e = m.themes[t] && m.themes[t].nouns[n]; if (!e) throw new Error('no picture ' + t + '/' + n); return e.vocabKey; };

// the locale-neutral seed additions (only options with a vocab key)
const categories = Object.entries(D.categories).map(([id, [theme, nouns]]) => ({
  id, options: nouns.filter((n) => vk(theme, n)).map((n) => ({ theme, noun: n, picOpened: true })),
}));
const actions = Object.entries(D.newActions).map(([id, [theme, noun]]) => ({ id, cue: { theme, noun }, picOpened: true, levelSetOnly: true }));
actions.push({ id: 'jumprope', cue: { theme: 'activities', noun: 'jumping' }, picOpened: true, levelSetOnly: true });
actions.push({ id: 'iceskate', cue: { theme: 'activities', noun: 'skating' }, picOpened: true, levelSetOnly: true });
const domains = JSON.parse(JSON.stringify(D.domains));
domains.move = domains.move.map((id) => (id === 'skip' ? 'jumprope' : id));
domains.outdoors = domains.outdoors.map((id) => (id === 'skate' ? 'iceskate' : id));
// de: the shipped "Ich kann Schlittschuh laufen" needs 3 lines in the domain column (measured)
const ICESKATE = { de: 'Ich kann Eis laufen' };

function words(loc) {
  const ow = require('./optionwords-' + loc + '.json');
  const out = {};
  for (const c of categories) for (const o of c.options) {
    const w = ow[c.id] && ow[c.id][o.theme + '/' + o.noun];
    if (typeof w === 'string' && w.trim()) out[vk(o.theme, o.noun)] = w;
  }
  return out;
}
function localeBlock(loc, shippedSkip, shippedSkate) {
  const p = require('./panel-' + loc + '.json');
  const can = { ...p.can, jumprope: p.can.jumprope || JUMPROPE[loc] || shippedSkip, iceskate: p.can.iceskate || ICESKATE[loc] || shippedSkate };
  for (const [k, v] of Object.entries(can)) if (typeof v !== 'string' || !v.trim() || /[{\d]/.test(v) || [...v].length > 34) throw new Error(`${loc} can.${k} bad: ${v}`);
  for (const c of Object.keys(D.categories)) if (!p.favHeading[c]) throw new Error(`${loc} favHeading.${c} missing`);
  return { favHeading: p.favHeading, can, optionWords: words(loc), excludeOptions: EXCLUDE[loc] || [] };
}

// en: a marked block appended to the JS module
const enPath = path.join(ROOT, 'data/b3/all-about-me.js');
let src = fs.readFileSync(enPath, 'utf8');
src = src.replace(/\n\/\/ >>> LEVEL SET[\s\S]*?\/\/ <<< LEVEL SET\n/, '\n');
const { ALL_ABOUT_ME } = require(enPath);
const en = localeBlock('en', ALL_ABOUT_ME.en.can.skip, ALL_ABOUT_ME.en.can.skate);
const block = `
// >>> LEVEL SET 2026-09-27 — generated by tools/level-set-aam/integrate.js (design.js + the 11 native panels beside it).
// Copies ask NEW questions: favourite sets per copy (sets[0] = the published animal/food/colour) and
// "I can" pages by area of life (domains). levelSetOnly actions never enter the published mixed pool.
Object.assign(ALL_ABOUT_ME_PICTURES, { sets: ${JSON.stringify(D.sets)}, domains: ${JSON.stringify(domains)} });
ALL_ABOUT_ME_PICTURES.categories.push(...${JSON.stringify(categories)});
ALL_ABOUT_ME_PICTURES.actions.push(...${JSON.stringify(actions)});
Object.assign(ALL_ABOUT_ME.en.labels.favHeading, ${JSON.stringify(en.favHeading)});
Object.assign(ALL_ABOUT_ME.en.can, ${JSON.stringify(en.can)});
Object.assign(ALL_ABOUT_ME.en.optionWords, ${JSON.stringify(en.optionWords)});
ALL_ABOUT_ME.en.excludeOptions = ${JSON.stringify(en.excludeOptions)};
// <<< LEVEL SET
`;
src = src.replace(/\nmodule\.exports = \{ ALL_ABOUT_ME, ALL_ABOUT_ME_PICTURES \};/, block + '\nmodule.exports = { ALL_ABOUT_ME, ALL_ABOUT_ME_PICTURES };');
fs.writeFileSync(enPath, src);

for (const loc of LOCS.slice(1)) {
  const f = path.join(ROOT, 'data/b3/locales/all-about-me.' + loc + '.json');
  const b = JSON.parse(fs.readFileSync(f, 'utf8'));
  // SHIPPED = the committed bank before the Level Set; its keys are never overwritten (the published
  // pages stay byte-identical). Every other key is ours and is rewritten on each run.
  const shipped = JSON.parse(require('child_process').execSync('git show 53b03115:scripts/worksheet-gen/data/b3/locales/all-about-me.' + loc + '.json', { cwd: ROOT, encoding: 'utf8' }));
  const x = localeBlock(loc, shipped.can.skip, shipped.can.skate);
  for (const [k, v] of Object.entries(x.favHeading)) if (!(k in shipped.labels.favHeading)) b.labels.favHeading[k] = v;
  for (const [k, v] of Object.entries(x.can)) if (!(k in shipped.can)) b.can[k] = v;
  b.optionWords = b.optionWords || {};
  for (const [k, v] of Object.entries(x.optionWords)) if (!(k in (shipped.optionWords || {}))) b.optionWords[k] = v;
  b.excludeOptions = x.excludeOptions;
  fs.writeFileSync(f, JSON.stringify(b, null, 2) + '\n');
}
console.log('integrated', categories.map((c) => c.id + ':' + c.options.length).join(' '), 'actions+' + actions.length);
