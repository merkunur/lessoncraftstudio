export function getStats(niches: NicheEntry[] = NICHES) {
  const total = niches.length;
  const hotOpportunities = niches.filter((n) => n.opportunityScore >= 4).length;
  const lowCompetitionGems = niches.filter((n) => n.competitionLevel <= 2).length;
  const uniqueLanguages = new Set<string>();
  niches.forEach((n) => n.languages.forEach((l) => uniqueLanguages.add(l)));
  return {
    total,
    hotOpportunities,
    lowCompetitionGems,
    languageCount: uniqueLanguages.size,
  };
}

export function getAllLanguages(niches: NicheEntry[] = NICHES): string[] {
  const set = new Set<string>();
  niches.forEach((n) => n.languages.forEach((l) => set.add(l)));
  return Array.from(set).sort();
}

export function getTopOpportunities(niches: NicheEntry[] = NICHES, limit = 12): NicheEntry[] {
  return [...niches]
    .sort((a, b) => {
      if (b.opportunityScore !== a.opportunityScore) {
        return b.opportunityScore - a.opportunityScore;
      }
      return b.demandLevel - a.demandLevel;
    })
    .slice(0, limit);
}
