    defaults: { shape: 'bracket', band: 'ten' },

    premium: false,

    /* ================= THE MODEL ===================================
       Pure, total, and it knows nothing about the DOM. Every function
       takes an optional state so the gate can drive it directly — but
       ⚠ the gate must ALSO reach these states BY BUTTON, because #54's
       headline branch was unreachable under a 626-assertion gate that
       only ever called the model.

       STATE
         shape  : 'change' | 'bracket' | 'compare'
         w      : the SUM. Teacher-set. ⚠ THE TEACHER SETS THE TOTAL AND
                  NEVER THE PARTS — setting parts directly reopens the
                  degenerate frames where every question has the same
                  answer.
         p      : one addend. The other is DERIVED, so the model cannot
                  be internally inconsistent — there is no third slot to
                  corrupt.
         ask    : 0 | 1 | 2 — which niche is the one to work out.
         linked : has the relation been shown?
         told   : [bool, bool, bool] — which niches have been said.
                  ⚠ told[ask] is ALWAYS false, enforced on every write.
         counted: has the missing one been counted out?
       ============================================================== */

    cap: function (band) { return GEO.BANDS[band] || GEO.BANDS.ten; },

    /* every value the three niches hold, derived from (w, p, shape) */
    values: function (st) {
      var s = this._st(st), sum = SUM_AT[s.shape], out = [];
      var i, other = [];
      for (i = 0; i < 3; i++) if (i !== sum) other.push(i);
      out[sum] = s.w;
      out[other[0]] = s.p;
      out[other[1]] = s.w - s.p;
      return out;
    },

    /* ⚠ a frame is worth showing only if different questions about it
       have DIFFERENT answers. Equal parts make two of the three
       questions the same question. */
    legal: function (w, p) {
      if (!(w >= GEO.FLOOR)) return false;
      if (w !== Math.round(w) || p !== Math.round(p)) return false;
      if (!(p > 0) || !(w - p > 0)) return false;
      if (p === w - p) return false;
      return true;
    },

    newState: function (shape, band, pick) {
      var cap = this.cap(band), all = [], w, p;
      for (w = GEO.FLOOR; w <= cap; w++) {
        for (p = 1; p < w; p++) if (this.legal(w, p)) all.push({ w: w, p: p });
      }
      /* ⚠ `all` is never empty: w=3 gives (3,1) and (3,2) at every cap. */
      var f = all[(pick == null ? Math.floor(Math.random() * all.length) : pick) % all.length];
      return {
        shape: SHAPES.indexOf(shape) >= 0 ? shape : 'bracket',
        w: f.w, p: f.p,
        ask: SUM_AT[SHAPES.indexOf(shape) >= 0 ? shape : 'bracket'],
        linked: false, told: [false, false, false], counted: false
      };
    },

    _st: function (st) { return st || this.st; },
    _copy: function (s) {
      return { shape: s.shape, w: s.w, p: s.p, ask: s.ask,
        linked: s.linked, told: [s.told[0], s.told[1], s.told[2]], counted: s.counted };
    },

    /* how many of the two tellable niches have been said */
    toldCount: function (st) {
      var s = this._st(st), i, n = 0;
      for (i = 0; i < 3; i++) if (i !== s.ask && s.told[i]) n++;
      return n;
    },

    /* ⭐⭐ THE PATH, NOT A STATE MACHINE. This DERIVES where the class
       is; nothing stores it. `null` means the teacher has stepped off
       the rehearsed sequence, which is allowed and is not an error. */
    stageOf: function (st) {
      var s = this._st(st), n = this.toldCount(s);
      if (s.counted) return (s.linked && n === 2) ? 4 : null;
      if (!s.linked) return n === 0 ? 0 : null;
      if (n === 0) return 1;
      if (n === 1) return 2;
      return 3;
    },

    /* ---- the moves. Each returns a NEW state, or null for a refusal.
       ⚠ null is the single refusal channel: the paint gates every
       control on its own move returning non-null, so a control can never
       LOOK live while the model refuses it. #54 shipped exactly that
       defect and only the live page could see it. */

    link: function (st, on) {
      var s = this._st(st), want = (on == null) ? !s.linked : !!on;
      if (want === !!s.linked) return null;
      var n = this._copy(s);
      n.linked = want;
      /* ⚠ un-showing the relation takes the question with it: a counted
         answer under no visible relation is a claim with nothing behind
         it. */
      if (!want) { n.told = [false, false, false]; n.counted = false; }
      return n;
    },

    tell: function (st, i, on) {
      var s = this._st(st);
      if (!(i === 0 || i === 1 || i === 2)) return null;
      if (i === s.ask) return null;                 /* that IS the question */
      if (!s.linked) return null;                   /* nothing to reason from */
      var want = (on == null) ? !s.told[i] : !!on;
      if (want === !!s.told[i]) return null;
      var n = this._copy(s);
      n.told[i] = want;
      if (!want) n.counted = false;
      return n;
    },

    count: function (st, on) {
      var s = this._st(st), want = (on == null) ? !s.counted : !!on;
      if (want === !!s.counted) return null;
      /* ⚠⚠ THE ANSWER MUST NOT EXIST BEFORE THE QUESTION DOES. Counting
         out the missing one before both knowns are said would be the
         tool answering a question nobody asked. */
      if (want && !(s.linked && this.toldCount(s) === 2)) return null;
      var n = this._copy(s);
      n.counted = want;
      return n;
    },

    setAsk: function (st, i) {
      var s = this._st(st);
      if (!(i === 0 || i === 1 || i === 2)) return null;
      if (i === s.ask) return null;
      var n = this._copy(s);
      n.ask = i;
      n.told[i] = false;          /* the question is never already said */
      n.counted = false;
      return n;
    },

    /* ⭐ INVENTION 2. The told slips STAY in their niches; only the
       arrangement and the linkage change — and the answer is different.
       ⚠ `counted` MUST clear: carrying a resolved count across an
       arrangement change would render a false situation, and this tool's
       one non-negotiable is that it never asserts something untrue. */
    setShape: function (st, shape) {
      var s = this._st(st);
      if (SHAPES.indexOf(shape) < 0) return null;
      if (shape === s.shape) return null;
      var n = this._copy(s);
      n.shape = shape;
      n.counted = false;
      /* the question follows the family's third quantity unless the
         teacher had already moved it somewhere still tellable */
      if (n.told[n.ask]) n.told[n.ask] = false;
      return n;
    },

    setTotal: function (st, w, band) {
      var s = this._st(st), cap = this.cap(band);
      if (w > cap) return null;
      if (w < GEO.FLOOR) return null;
      /* keep the split legal: nudge p until it is */
      var p = Math.min(s.p, w - 1), guard = 0;
      while (!this.legal(w, p) && guard++ < 40) p = p > 1 ? p - 1 : p + 1;
      if (!this.legal(w, p)) return null;
      var n = this._copy(s);
      n.w = w; n.p = p; n.counted = false;
      return n;
    },

    deal: function (st, shape, band, pick) {
      var n = this.newState(shape, band, pick);
      return n;
    },

