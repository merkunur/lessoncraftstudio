#!/usr/bin/env node
/**
 * tools/build-spelling-rivals.js — the real words that would spoil a Spelling page (2026-11-02, the Spelling maker's
 * native review: "shore" as the scramble of horse, "whole" as a misspelling of whale). Our picture vocabulary is far too
 * small to know every word of a language, so this tool reads a large word list per language (one word per line, the
 * word first: the OpenSubtitles 50k frequency lists of hermitdave/FrequencyWords, content CC BY-SA 4.0) and keeps, for
 * every picture word of the vocabulary, only the real words that conflict with it:
 *   - its anagrams (G1-517 Word Scramble must never print one)
 *   - its one-change spellings of the kinds G2-492 makes (a vowel swapped, a letter dropped / doubled / made single, two
 *     letters swapped) — never offered as "the wrong spelling"
 * (A blank pattern — G1-518, G1-520 — is checked against the picture vocabulary only: there the picture decides between
 * fillings, and a 50k list of subtitle words would make almost every pattern ambiguous.)
 * A rival that is itself a picture word is left out (spelling-words.js checks the vocabulary anyway); each list is one
 * space-separated string (the file ships in the Spelling maker's browser bundle: keep it small).
 * Output: data/spelling/rivals.js { <loc>: { <picture word, lower case>: [real words] } } — read by
 * types/_shared/spelling-words.js (browser-safe, small). Re-run when the vocabulary changes:
 *   node tools/build-spelling-rivals.js <dir with en.txt … fi.txt>
 */
'use strict';
const fs = require('fs'), path = require('path');
const { vocab } = require('../lib/b2-common.js');

const LOCS = ['en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
// the vowels G2-492 swaps (types/g2/G2-492-circle-the-right-spelling.js BASE)
const BASE = { en: 'aeiou', de: 'aeiou', fr: 'aeiou', es: 'aeiou', pt: 'aeiou', it: 'aeiou', nl: 'aeiou', sv: 'aeiouyåäö', da: 'aeiouyæøå', no: 'aeiouyæøå', fi: 'aeiouyäö' };
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-spelling-rivals.js <dir of <loc>.txt word lists>'); process.exit(2); }

// every wrong spelling G2-492 can print (types/_shared/spelling-words.js misspellings, the per-language rules) plus the
// generic one-letter changes (drop / double / swap / vowel), so the list stays a superset if the rules widen
const SW = require('../types/_shared/spelling-words.js');
function edits(w, L) {
  const ch = [...w], n = ch.length, out = new Set(SW.misspellings(w, L).map((x) => x.s.toLocaleLowerCase(L)));
  for (let i = 1; i < n; i++) {
    out.add([...ch.slice(0, i), ...ch.slice(i + 1)].join(''));                                    // drop
    out.add([...ch.slice(0, i + 1), ch[i], ...ch.slice(i + 1)].join(''));                         // double
    if (i + 1 < n) out.add([...ch.slice(0, i), ch[i + 1], ch[i], ...ch.slice(i + 2)].join(''));    // swap
    if (BASE[L].includes(ch[i])) for (const v of BASE[L]) if (v !== ch[i]) out.add([...ch.slice(0, i), v, ...ch.slice(i + 1)].join(''));
  }
  out.delete(w);
  return out;
}

const result = {};
for (const L of LOCS) {
  const f = path.join(dir, `${L}.txt`);
  const dict = new Set();
  for (const line of fs.readFileSync(f, 'utf8').split(/\r?\n/)) {
    const w = line.split(' ')[0].trim().toLocaleLowerCase(L).normalize('NFC');
    if (w && /^\p{L}+$/u.test(w)) dict.add(w);
  }
  const own = new Map();                 // a picture word → its own forms (never its own rival)
  for (const e of Object.values(vocab())) {
    const x = e && e[L];
    if (!x || !x[0]) continue;
    const s = String(x[0]).toLocaleLowerCase(L).trim(), p = String(x[1] || '').toLocaleLowerCase(L).trim();
    if (/^\p{L}+$/u.test(s)) own.set(s, new Set([s, p].filter(Boolean)));
  }
  const bySorted = new Map();
  for (const w of dict) {
    const k = [...w].sort().join('');
    (bySorted.get(k) || bySorted.set(k, []).get(k)).push(w);
  }
  const out = {};
  let total = 0;
  for (const [w, forms] of own) {
    const ch = [...w], n = ch.length;
    if (n < 3 || n > 12) continue;
    const rivals = new Set();
    for (const a of bySorted.get([...ch].sort().join('')) || []) rivals.add(a);
    for (const e of edits(w, L)) if (dict.has(e)) rivals.add(e);
    for (const f2 of forms) rivals.delete(f2);
    for (const r of [...rivals]) if (own.has(r)) rivals.delete(r);
    if (rivals.size) { out[w] = [...rivals].sort().join(' '); total += rivals.size; }
  }
  result[L] = out;
  console.log(L, 'dict', dict.size, 'picture words with rivals', Object.keys(out).length, 'rivals', total);
}
const file = path.join(__dirname, '..', 'data', 'spelling', 'rivals.js');
const head = '/**\n * data/spelling/rivals.js — GENERATED by tools/build-spelling-rivals.js (2026-11-02); never hand-edit. For every picture\n * word: the real words of its language that would spoil a Spelling page (its anagrams, its one-change spellings, the\n * words that fit its blank patterns). Source of the real words: hermitdave/FrequencyWords (OpenSubtitles 2018, 50k per\n * language, content CC BY-SA 4.0) + the picture vocabulary.\n */\n\'use strict\';\n';
fs.writeFileSync(file, head + 'module.exports = ' + JSON.stringify(result) + ';\n');
console.log('wrote', file, Math.round(fs.statSync(file).size / 1024), 'KB');
