#!/usr/bin/env node
/**
 * The unit gap report of one language (Daily Teaching System, Part 4.1): what the units do not have yet, and what
 * would fill it. Part 10 (the remaining activities) reads it.
 *
 *   node scripts/units/gap-report.js --loc=en      → docs/daily-teaching-system/units/GAPS.<loc>.md
 *   node scripts/units/gap-report.js --loc=en --check     exit 1 when the committed report is not today's
 *
 * Sections, all generated from committed files (the assembled units and the content graph):
 *   1. Teaching points in no unit, for every subject that has a unit: no page is published; or the point cannot make
 *      a lesson (a lesson needs two real assets: worksheet types, a tool, practice on screen that is not the
 *      handed-out page); or it could and no unit takes it.
 *   2. Lessons with no practice on screen, with the planned activities of the point (their numbers in the activity
 *      build order, docs/activities-rebuild/ORDER.md).
 *   3. Lessons whose screen practice is a worksheet page and whose point has a planned activity (the activity will
 *      take the slot when it ships; the unit's title and address do not move).
 *   4. Lessons with no classroom tool.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.join(__dirname, '..', '..');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : d; };
const loc = arg('loc', 'en');
const CHECK = process.argv.includes('--check');
const C = path.join(REPO, 'frontend', 'content');
const read = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const points = read(path.join(C, 'teaching-graph', 'points.json')).points;
const byId = new Map(points.map((p) => [p.id, p]));
const assets = read(path.join(C, 'teaching-graph', 'assets', loc + '.json'));
const toolPoints = read(path.join(C, 'teaching-graph', 'tools.json')).tools;
const toolContent = read(path.join(REPO, 'frontend', 'messages', 'tool-content', loc + '.json'));
const units = read(path.join(C, 'units', 'units.' + loc + '.json')).units;
const subjects = [...new Set(units.map((u) => u.subject))];
const inUnit = new Map();
for (const u of units) for (const l of u.lessons) inUnit.set(l.point, u);
const pagesOf = (p) => p.types.filter((t) => assets.types[t] && assets.types[t].p.some((n) => n > 0));
const GRADES = ['K', '1', '2', '3'];
const planned = (p) => (p.planned && p.planned.length ? 'planned activity ' + p.planned.map((n) => '#' + n).join(', ') : 'no activity planned');
/** could the point make a lesson? an upper bound from the index: its types, a tool, a live activity, or a second page with a screen */
const assetCount = (p) => {
  const pg = pagesOf(p);
  const tool = Object.keys(toolPoints).some((k) => (toolPoints[k].points || []).includes(p.id) && toolContent[k] && toolContent[k].slug && toolContent[k].name);
  const act = (p.activities || []).some((a) => assets.activities[a]);
  const screenCopy = pg.some((t) => assets.types[t].s[1] > 0 && assets.types[t].p[1] > 1);
  return pg.length + (tool ? 1 : 0) + (act || screenCopy ? 1 : 0);
};

let md = '# Unit gaps, language `' + loc + '`\n\nGENERATED by `scripts/units/gap-report.js` from the assembled units and the content graph. Do not edit by hand.\n\n'
  + units.length + ' units, ' + units.reduce((n, u) => n + u.lessons.length, 0) + ' lessons. Subjects with a unit: ' + (subjects.join(', ') || 'none') + '.\n';

md += '\n## 1. Teaching points in no unit\n';
for (const subject of subjects) {
  const rows = { thin: [], nopage: [], free: [] };
  for (const p of points.filter((x) => x.subject === subject).sort((a, b) => GRADES.indexOf(a.grade) - GRADES.indexOf(b.grade) || a.order - b.order)) {
    if (inUnit.has(p.id)) continue;
    const pg = pagesOf(p);
    const line = '- `' + p.id + '` (grade ' + p.grade + ') ' + p.skill.slice(0, 110) + ' — ' + planned(p);
    if (!pg.length) rows.nopage.push(line);
    else if (assetCount(p) < 2) rows.thin.push(line + '; pages: ' + pg.join(' '));
    else rows.free.push(line + '; pages: ' + pg.join(' '));
  }
  md += '\n### ' + subject + '\n';
  md += '\n**Cannot make a lesson yet: one worksheet type and nothing beside it (' + rows.thin.length + ').** A tool, an activity or a second page with a Check button brings the lesson in.\n\n' + (rows.thin.join('\n') || '- none') + '\n';
  md += '\n**No published page in this language (' + rows.nopage.length + ').** These wait for their worksheets.\n\n' + (rows.nopage.join('\n') || '- none') + '\n';
  md += '\n**Could make a lesson and is in no unit (' + rows.free.length + ').** Left out by choice (the reason is in the part\'s record) or not placed yet.\n\n' + (rows.free.join('\n') || '- none') + '\n';
}

const lessons = [];
for (const u of units) for (const l of u.lessons) lessons.push({ u, l, p: byId.get(l.point) });
const row = (x) => '- `' + x.u.id + ' / lesson ' + x.l.n + '` ' + x.l.title + ' (`' + x.l.point + '`)';
const noScreen = lessons.filter((x) => !x.l.screen);
md += '\n## 2. Lessons with no practice on screen (' + noScreen.length + ')\n\n' + (noScreen.map((x) => row(x) + ' — ' + planned(x.p)).join('\n') || '- none') + '\n';
const pageScreen = lessons.filter((x) => x.l.screen && x.l.screen.kind === 'page' && x.p.planned && x.p.planned.length);
md += '\n## 3. Lessons whose screen practice is a worksheet page and whose point has a planned activity (' + pageScreen.length + ')\n\n' + (pageScreen.map((x) => row(x) + ' — ' + planned(x.p)).join('\n') || '- none') + '\n';
const noTool = lessons.filter((x) => !x.l.tool);
md += '\n## 4. Lessons with no classroom tool (' + noTool.length + ' of ' + lessons.length + ')\n\n' + (noTool.map((x) => row(x)).join('\n') || '- none') + '\n';

const out = path.join(REPO, 'docs', 'daily-teaching-system', 'units', 'GAPS.' + loc + '.md');
if (CHECK) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== md) { console.log('STALE  ' + path.relative(REPO, out) + ': run node scripts/units/gap-report.js --loc=' + loc); process.exit(1); }
  console.log('unit gap report (' + loc + ') is current');
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, md);
  console.log(path.relative(REPO, out) + ': ' + noScreen.length + ' lessons without screen practice, ' + pageScreen.length + ' waiting for a planned activity, ' + noTool.length + ' without a tool');
}
