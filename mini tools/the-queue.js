      var bar = document.createElementNS(ns, 'rect');
      bar.setAttribute('x', '20'); bar.setAttribute('y', '96');
      bar.setAttribute('width', '360'); bar.setAttribute('height', '7');
      bar.setAttribute('rx', '3.5'); bar.setAttribute('class', 'que-bar');
