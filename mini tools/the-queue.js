      var step = 360 / (n + 1);
      var landed = this.landedIndex(s);
      for (i = 0; i < n; i++) {
        var cx = 20 + step * (i + 1);
        var g = this._shape(FORMS[s.members[i]], cx, 90, GEO.AREA);
        if (landed === i) g.setAttribute('class', 'que-member is-landed');
        svg.insertBefore(g, walker);
      }

      /* ⭐ THE WALKER IS PARKED OFF THE PLATFORM UNTIL AN END IS CHOSEN.
         There is no home end, and its absence is the thesis.
         ⚠ It is HIDDEN rather than removed — removal is what destroyed the
         travel. `display:none` also gives it no before-change style, so its
         first appearance correctly does not slide in from nowhere. */
