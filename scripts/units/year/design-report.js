#!/usr/bin/env node
/**
 * Writes the YEAR DESIGN as a page to read (Daily Teaching System, Part 12.1): the school year of each grade week by
 * week (the non-teaching weeks where the teacher-reviewer put them, each unit in the school weeks its class days
 * fill), and the WORK LIST of Part 12.2: every new lesson by where its page comes from.
 *
 *   node scripts/units/year/design-report.js --loc=en [--subject=math] [--check]
 *     reads   scripts/units/year/design.<loc>.<subject>.json  (checked first: scripts/units/year/check-design.js)
 *     writes  docs/daily-teaching-system/year/YEAR-DESIGN.<loc>.<subject>.md
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const REPO = path.join(__dirname, '..', '..', '..');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : d; };
const loc = arg('loc', 'en'), subject = arg('subject', 'math');
const check = process.argv.includes('--check');
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const chk = spawnSync('node', [path.join(__dirname, 'check-design.js'), '--loc=' + loc, '--subject=' + subject], { encoding: 'utf8' });
if (chk.status !== 0) { console.log(chk.stdout.trim().split('\n').slice(-6).join('\n')); console.error('the design does not pass its check: no report is written from it'); process.exit(1); }
const design = readJson(path.join(__dirname, 'design.' + loc + '.' + subject + '.json'));
const unitsFile = readJson(path.join(REPO, 'frontend', 'content', 'units', 'units.' + loc + '.json'));
const byKey = new Map(); for (const u of unitsFile.units) for (const l of u.lessons) byKey.set(u.id + '#' + l.n, { unit: u, lesson: l });
const titleOf = new Map(unitsFile.units.map((u) => [u.id, u.title]));
const GRADE = { en: { K: 'Kindergarten', 1: 'Grade 1', 2: 'Grade 2', 3: 'Grade 3' }, de: { 1: 'Klasse 1', 2: 'Klasse 2', 3: 'Klasse 3' }, sv: { K: 'Förskoleklass', 1: 'Årskurs 1', 2: 'Årskurs 2', 3: 'Årskurs 3' } }[loc];
const YEAR_WEEKS = (design.pacing && design.pacing.yearWeeks) || 36;
const gradeEntries = ['K', '1', '2', '3'].filter((g) => design[g]).map((g) => [g, design[g]]);
const SOURCE = { point: 'worksheets exist today (a teaching point no unit uses)', reuse: 'a page type that exists, with new numbers', new: 'a NEW worksheet type', 'teacher-led': 'the teacher leads it, no page' };
const kind = (s) => (String(s).startsWith('point:') ? 'point' : String(s).startsWith('reuse:') ? 'reuse' : s);

const L = ['# The school year, designed: ' + subject + ' (' + loc + ')', '',
  'GENERATED by `scripts/units/year/design-report.js` from `scripts/units/year/design.' + loc + '.' + subject + '.json`, the teacher-reviewer\'s design of each year (checked by `check-design.js`). It is the specification of Part 12.2: the units in the order of the year and every lesson that has to be written.', ''];
const work = { point: [], reuse: [], new: [], 'teacher-led': [] };
const totals = [];
for (const [grade, g] of gradeEntries) {
  const off = new Map(); for (const n of g.nonTeachingWeeks) { const m = /^(\d+)(?:-(\d+))?$/.exec(n.weeks); for (let k = +m[1]; k <= +(m[2] || m[1]); k++) off.set(k, n.what); }
  const teaching = []; for (let k = 1; k <= YEAR_WEEKS; k++) if (!off.has(k)) teaching.push(k);
  const perWeek = ((design.pacing || {}).daysPerWeek || {})[grade] || 5;
  let day = 0; const rows = []; let newN = 0, oldN = 0;
  for (const u of g.units) {
    const start = day;
    for (const l of u.lessons) { if (l.existing) { day += byKey.get(l.existing).lesson.days || 2; oldN++; } else { day += l.days; newN++; work[kind(l.source)].push({ grade, unit: u.title, l }); } }
    day += 3;
    const w0 = teaching[Math.min(teaching.length - 1, Math.floor(start / perWeek))], w1 = teaching[Math.min(teaching.length - 1, Math.ceil(day / perWeek) - 1)];
    rows.push({ u, w0, w1, days: day - start });
  }
  totals.push({ grade, units: g.units.length, oldN, newN, days: g.totalDays, of: teaching.length * perWeek });
  L.push('## ' + GRADE[grade], '', g.units.length + ' units, ' + oldN + ' lessons of today and ' + newN + ' new ones: ' + g.totalDays + ' of ' + teaching.length * perWeek + ' class days (' + teaching.length + ' teaching weeks of ' + YEAR_WEEKS + ').', '');
  L.push('**Weeks without mathematics teaching:** ' + g.nonTeachingWeeks.map((n) => 'week' + (/-/.test(n.weeks) ? 's ' : ' ') + n.weeks + ' (' + n.what + ')').join('; ') + '.', '');
  L.push('| School weeks | Unit | Class days | Lessons |', '|---|---|---|---|');
  for (const r of rows) L.push('| ' + (r.w0 === r.w1 ? r.w0 : r.w0 + ' to ' + r.w1) + ' | **' + r.u.title + '**' + (/^new:/.test(r.u.id) ? ' (new unit)' : '') + '<br>' + (r.u.why || '') + ' | ' + r.days + ' | ' + r.u.lessons.map((l, i) => (i + 1) + '. ' + (l.existing ? byKey.get(l.existing).lesson.title + (l.existing.split('#')[0] !== r.u.id ? ' (from ' + titleOf.get(l.existing.split('#')[0]) + ')' : '') : '**' + l.title + '** (new, ' + l.standard + ')')).join('<br>') + ' |');
  L.push('');
  if ((g.leftOut || []).length) { L.push('**Left out of the year, with the reason:**', ''); for (const x of g.leftOut) L.push('- ' + x.what + ': ' + x.why); L.push(''); }
}
L.push('## The work list of Part 12.2', '', '| Where the page comes from | Lessons |', '|---|---|');
for (const k of Object.keys(work)) L.push('| ' + SOURCE[k] + ' | ' + work[k].length + ' |');
L.push('| **All new lessons** | **' + Object.values(work).reduce((n, a) => n + a.length, 0) + '** |', '');
for (const k of Object.keys(work)) {
  if (!work[k].length) continue;
  L.push('### ' + SOURCE[k].charAt(0).toUpperCase() + SOURCE[k].slice(1) + ' (' + work[k].length + ')', '');
  for (const { grade, unit, l } of work[k]) L.push('- **' + GRADE[grade] + ', ' + unit + ': ' + l.title + '** (' + l.standard + ', ' + l.days + ' days' + (l.tool ? ', tool: ' + l.tool : '') + '). ' + l.objective + (k === 'point' || k === 'reuse' ? ' Source: `' + l.source + '`.' : '') + (l.page ? ' Page: ' + l.page : ''));
  L.push('');
}
const out = L.join('\n') + '\n';
const file = path.join(REPO, 'docs', 'daily-teaching-system', 'year', 'YEAR-DESIGN.' + loc + '.' + subject + '.md');
if (check) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) { console.log('year design ' + loc + ' ' + subject + ': the committed page is not what the script writes today'); process.exit(1); }
  console.log('year design ' + loc + ' ' + subject + ': current'); process.exit(0);
}
fs.writeFileSync(file, out);
for (const t of totals) console.log(GRADE[t.grade].padEnd(13) + String(t.units).padStart(2) + ' units  ' + String(t.oldN).padStart(2) + ' lessons of today  ' + String(t.newN).padStart(2) + ' new  ' + t.days + ' of ' + t.of + ' days');
console.log('new lessons by source: ' + Object.entries(work).map(([k, a]) => k + ' ' + a.length).join(', '));
console.log(path.relative(REPO, file));
