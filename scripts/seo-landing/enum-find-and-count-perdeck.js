#!/usr/bin/env node
/* Enumerate PER-DECK find-and-count landing coordinates (EN). RUNS ON HETZNER (reads
 * /var/www/lcs-media/decks/en/<slug>-v1/manifest.json). Read-only w.r.t. production.
 *
 * Splits the 379 EN find-and-count decks into TWO families by the EXERCISE DATA (NOT the
 * mislabeled manifest.exercise_mode field):
 *   - beginning-sounds  = exercises[0].isBeginningLetterMode === true (a selectedLetter +
 *     targetWords). Each deck = one target letter. -> "Beginning Sounds" (RF.K.3.a).
 *   - find-and-count    = by-object I-Spy (exercises[0].questions[] with circle/cross/
 *     square/count task types, no isBeginningLetterMode). -> "Find and Count" (readiness).
 *
 * Output: scripts/seo-landing/find-and-count-perdeck-coordinates.json (pulled back to repo).
 * Usage (on Hetzner): node enum-find-and-count-perdeck.js /var/www/lcs-media/decks/en /tmp/fac-perdeck.json
 */
const fs = require('fs');
const path = require('path');

const DECKS_DIR = process.argv[2] || '/var/www/lcs-media/decks/en';
const OUT = process.argv[3] || '/tmp/fac-perdeck.json';

function titleCase(s) {
  return String(s || '').trim().replace(/\b\w/g, (c) => c.toUpperCase());
}

const dirs = fs.readdirSync(DECKS_DIR)
  .filter((d) => /^find-and-count-.*-v1$/.test(d) || d === 'find-and-count-v1')
  .sort();

const letterSpotting = []; // {slug, theme, slugTheme, letter, targetWords[]}
const byObject = [];       // {slug, theme, slugTheme, tasks:[{verb,word}]}
const skipped = [];

for (const dir of dirs) {
  const slug = dir.replace(/-v1$/, '');
  const mpath = path.join(DECKS_DIR, dir, 'manifest.json');
  let m;
  try { m = JSON.parse(fs.readFileSync(mpath, 'utf8')); }
  catch (e) { skipped.push({ slug, why: 'no-manifest:' + e.message }); continue; }

  const theme = m.theme || null;
  const ex = (m.exercises && m.exercises[0]) || {};
  const slugTheme = (theme || '').replace(/_/g, '-');

  if (ex.isBeginningLetterMode === true || ex.selectedLetter) {
    const letter = String(ex.selectedLetter || '').trim().toUpperCase();
    let words = Array.isArray(ex.targetWords) ? ex.targetWords.slice() : [];
    // fallback: derive from gridData isTarget cells if targetWords missing
    if (!words.length && Array.isArray(ex.gridData)) {
      const set = [];
      for (const row of ex.gridData) for (const c of (row || [])) {
        if (c && c.isTarget && c.word && !set.includes(c.word.toLowerCase())) set.push(c.word.toLowerCase());
      }
      words = set;
    }
    words = words.map((w) => titleCase(w)).filter(Boolean);
    // dedupe + cap (the prose lists a few; keep all for the title/variety but cap display later)
    words = [...new Set(words)];
    if (!theme || !letter) { skipped.push({ slug, why: 'ls-missing-theme-or-letter' }); continue; }
    letterSpotting.push({ slug, theme, slugTheme, letter, targetWords: words });
  } else {
    // by-object: read questions[] (the printable's task list)
    const qs = Array.isArray(ex.questions) ? ex.questions : [];
    const VERB = { circle: 'circle', cross: 'cross out', square: 'draw a box around', count: 'count' };
    const tasks = qs
      .filter((q) => q && q.word && q.type && VERB[q.type])
      .map((q) => ({ verb: VERB[q.type], type: q.type, word: titleCase(q.word) }));
    if (!theme) { skipped.push({ slug, why: 'byobj-missing-theme' }); continue; }
    byObject.push({ slug, theme, slugTheme, tasks });
  }
}

// ----- dedupe by-object by theme: prefer the theme-named slug over the bare/generic `find-and-count`
const byThemeBO = {};
for (const r of byObject) {
  const cur = byThemeBO[r.theme];
  // prefer slug that literally ends with the slugTheme (find-and-count-animals) over generic `find-and-count`
  const isNamed = (x) => x.slug === 'find-and-count-' + x.slugTheme;
  if (!cur) byThemeBO[r.theme] = r;
  else if (isNamed(r) && !isNamed(cur)) byThemeBO[r.theme] = r;
}
const byObjectDedup = Object.values(byThemeBO).sort((a, b) => (a.theme < b.theme ? -1 : 1));
const byObjectDropped = byObject.filter((r) => byThemeBO[r.theme].slug !== r.slug);

// ----- letter-spotting: detect (theme, letter) collisions for ordinal disambiguation in the generator
letterSpotting.sort((a, b) => (a.theme < b.theme ? -1 : (a.theme > b.theme ? 1 : (a.letter < b.letter ? -1 : (a.slug < b.slug ? -1 : 1)))));

const out = {
  _note: 'PER-DECK find-and-count coordinates (EN). beginning-sounds = letter-spotting (RF.K.3.a), find-and-count = by-object (readiness). Generated by enum-find-and-count-perdeck.js on Hetzner.',
  counts: { letterSpotting: letterSpotting.length, byObject: byObjectDedup.length, byObjectDropped: byObjectDropped.length, skipped: skipped.length },
  byObjectDropped: byObjectDropped.map((r) => r.slug),
  skipped,
  letterSpotting,
  byObject: byObjectDedup,
};
fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
console.log('WROTE', OUT);
console.log('counts:', JSON.stringify(out.counts));
console.log('byObjectDropped (generic/dupe):', out.byObjectDropped.join(', ') || '(none)');
console.log('skipped:', JSON.stringify(skipped));
// quick letters-per-theme histogram
const hist = {};
for (const r of letterSpotting) (hist[r.theme] = hist[r.theme] || []).push(r.letter);
console.log('letters per theme:');
for (const t of Object.keys(hist).sort()) console.log('  ' + t + ' (' + hist[t].length + '): ' + hist[t].join(','));
