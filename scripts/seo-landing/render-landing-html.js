function buildBreadcrumbSchema(trail) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: trail.map((crumb, idx) => ({
      '@type': 'ListItem', position: idx + 1, name: crumb.name, item: canonicalUrl(crumb.path),
    })),
  };
}

