/* =====================================================================
   _dbm-fold-locales.js — fold the ten native panels' JSON into
   `_doubling-mirror-strings.js`, which `apply-doubling-mirror-locales.js`
   then validates and writes into the tool.
   Run: node scripts/_dbm-fold-locales.js [--dry-run]

   ⚠⚠ THE OLD TABLE IS STALE AND A GERMAN PANEL PROVED IT: every locale
   still authors `setStart`, `startSmall`, `startTen`, `sideLow`,
   `sideHigh`, `saidOddPlaced`, `sideNameNear` and `sideNameFar`, none of
   which the rebuilt tool reads — and the `de` block declares `saidNoOdd`,
   `sideNameNear` and `sideNameFar` TWICE inside one object literal,
   silently last-wins. So the fold DROPS anything the tool no longer
   reads and rebuilds each block from scratch rather than patching it.

   ⚠ A PANEL'S `corrections` OUTRANK ITS `strings`, because a correction
   is the panel's second, better reading of a key it had already seen.
   A `_withdrawn` / `__withdrawn__` / `withdrawn` marker is NOT a value —
   several panels used it to retract a round-1 correction, and folding
   the marker in as text would ship the word "WITHDRAWN" to a classroom.

   ⚠ EVERY KEY THE TOOL READS MUST END UP PRESENT. A missing key is a
   FAULT here, not a silent English fallback in eleven locales.
   ===================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const DRY = process.argv.indexOf('--dry-run') >= 0;
const TOOL = path.join(__dirname, '..', 'mini tools', 'doubling-mirror.js');
const OLD = path.join(__dirname, '_doubling-mirror-strings.js');
const PANELS = process.env.DBM_PANEL_DIR || path.join(
  process.env.TEMP || '/tmp', 'claude', 'C--Users-rkgen-lessoncraftstudio',
  'f666d094-0b99-46ab-acfe-859fd297d219', 'scratchpad', 'dbm-locales');

const LOCALES = ['de', 'fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
const T = require(TOOL);
const KEYS = Object.keys(T.strings);
const prev = require(OLD);

if (KEYS.length < 25) { console.log('FATAL: implausibly few keys in the tool'); process.exit(1); }

/* a retraction marker is not a translation */
const WITHDRAWN = /^(\s*[«"*]*\s*)?(WITHDRAWN|\*\*WITHDRAWN)/i;
function usable(v) {
  return typeof v === 'string' && v.length > 0 && !WITHDRAWN.test(v);
}

const out = {};
const faults = [];
let folded = 0, dropped = 0;

LOCALES.forEach(function (L) {
  const f = path.join(PANELS, L + '.json');
  if (!fs.existsSync(f)) { faults.push(L + ': no panel file at ' + f); return; }
  let j;
  try { j = JSON.parse(fs.readFileSync(f, 'utf8')); }
  catch (e) { faults.push(L + ': panel JSON does not parse — ' + e.message); return; }
  if (j.locale !== L) faults.push(L + ': panel file declares locale "' + j.locale + '"');

  const set = {};
  KEYS.forEach(function (k) {
    /* corrections outrank strings outrank the old table */
    const c = j.corrections && j.corrections[k];
    const s = j.strings && j.strings[k];
    const o = prev[L] && prev[L][k];
    const v = usable(c) ? c : usable(s) ? s : usable(o) ? o : null;
    if (v === null) faults.push(L + '.' + k + ': no usable value in panel or table');
    else set[k] = v;
  });
  /* anything the tool no longer reads is DROPPED, not carried */
  Object.keys(prev[L] || {}).forEach(function (k) {
    if (KEYS.indexOf(k) < 0) dropped++;
  });
  out[L] = set;
  folded++;
});

if (faults.length) {
  console.log('FAULTS (' + faults.length + '):');
  faults.slice(0, 30).forEach(f => console.log('  ✗ ' + f));
  process.exit(1);
}

console.log('folded ' + folded + ' locales × ' + KEYS.length + ' keys; dropped ' +
  dropped + ' stale key-instances the tool no longer reads');

if (DRY) { console.log('(dry run — nothing written)'); process.exit(0); }

const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
let src = '/* =====================================================================\n';
src += '   TOOL #54 — THE DOUBLING MIRROR — the ten non-English string sets\n';
src += '   =====================================================================\n';
src += '   ⚠ GENERATED by `scripts/_dbm-fold-locales.js` from the ten native\n';
src += '   panels\' JSON. Do not hand-edit: the next fold overwrites it.\n\n';
src += '   REVISION 3 — the rebuild. Every locale was re-authored by a native\n';
src += '   three-person panel reading the MODEL, not a brief, across two\n';
src += '   rounds. The panels found four defects no string diff could show —\n';
src += '   a refusal wired to two opposite causes, a shut-tray ceiling\n';
src += '   announced as a leaf ceiling, a reveal discipline that was\n';
src += '   sighted-only, and a print sheet whose instructions could not be\n';
src += '   carried out on paper — and all four were fixed in the model.\n\n';
src += '   The rev-2 keys `setStart`, `startSmall`, `startTen`, `sideLow`,\n';
src += '   `sideHigh`, `saidOddPlaced`, `sideNameNear`, `sideNameFar` and\n';
src += '   `saidFetchFull` are GONE: the side choice was cut (5-and-4 versus\n';
src += '   4-and-5 is one fact with the addends swapped), the `start` setting\n';
src += '   was retired for offering ten and delivering seven, and\n';
src += '   `saidFetchFull` was proved unreachable at both caps.\n';
src += '   ===================================================================== */\n';
src += "'use strict';\nmodule.exports = {\n";
LOCALES.forEach(function (L, li) {
  src += '  ' + L + ': {\n';
  KEYS.forEach(function (k, i) {
    src += '    ' + k + ': ' + q(out[L][k]) + (i === KEYS.length - 1 ? '' : ',') + '\n';
  });
  src += '  }' + (li === LOCALES.length - 1 ? '' : ',') + '\n';
});
src += '};\n';
fs.writeFileSync(OLD, src, 'utf8');
console.log('wrote ' + OLD);
