/* messages loader (learnPage namespace for cross-language landings) */
const _msgsCache = {};
function loadMessages(locale) {
  if (locale in _msgsCache) return _msgsCache[locale];
  const p = path.join(ROOT, 'frontend', 'messages', `${locale}.json`);
  _msgsCache[locale] = fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : null;
  return _msgsCache[locale];
}

/* ============================== CLI ============================== */

function parseArgs() {
  const args = { locales: LANDING_LOCALES, out: '/var/www/lcs-media/landings', slug: null, stdout: false, limit: 0 };
  for (const a of process.argv.slice(2)) {
    if (a.startsWith('--locales=')) args.locales = a.slice(10).split(',').map((s) => s.trim()).filter(Boolean);
    else if (a.startsWith('--locale=')) args.locales = [a.slice(9)];
    else if (a.startsWith('--out=')) args.out = a.slice(6);
    else if (a.startsWith('--slug=')) args.slug = a.slice(7);
    else if (a.startsWith('--limit=')) args.limit = parseInt(a.slice(8), 10) || 0;
    else if (a === '--stdout') args.stdout = true;
    else { console.error(`unknown arg: ${a}`); process.exit(2); }
  }
  return args;
}

function writeAtomic(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, file);
}

function main() {
  const args = parseArgs();
  const t0 = Date.now();
  let total = 0;

  if (args.slug) {
    const locale = args.locales[0];
    const l = getLandingBySlug(locale, args.slug);
    if (!l) { console.error(`landing not found: ${locale}/${args.slug}`); process.exit(1); }
    const html = renderLanding(locale, l);
    if (args.stdout) { process.stdout.write(html); return; }
    const file = path.join(args.out, locale, l.slug, 'index.html');
    writeAtomic(file, html);
    console.log(`wrote ${file}`);
    return;
  }

  for (const locale of args.locales) {
    const landings = getAllLandings(locale);
    if (!landings.length) { console.warn(`(no landings for ${locale} — skipped)`); continue; }
    let n = 0;
    for (const l of landings) {
      const html = renderLanding(locale, l);
      writeAtomic(path.join(args.out, locale, l.slug, 'index.html'), html);
      n++; total++;
      if (args.limit && n >= args.limit) break;
    }
    console.log(`${locale}: ${n} landings written`);
  }
  console.log(`DONE: ${total} pages in ${((Date.now() - t0) / 1000).toFixed(1)}s → ${args.out}`);
}

main();
