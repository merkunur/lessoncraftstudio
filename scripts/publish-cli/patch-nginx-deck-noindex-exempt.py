#!/usr/bin/env python3
"""
Make the deck.html `X-Robots-Tag` header CONDITIONAL, so landing-less decks are
no longer noindexed.

WHY (2026-07-30). `patch-nginx-deck-noindex.py` (2026-07-22) put a static
`noindex, indexifembedded` on THE deck.html location block. That block serves
every deck, so it also hit the ~13.2k decks that have NO /worksheets/ landing —
the very decks that sitemap shards 0/1 deliberately submit because, per the
2026-06-20 reasoning, deck.html is their ONLY indexable surface. The result was
9,752 sitemapped-but-noindexed URLs and 29% of the catalog with no indexable
surface at all ("Submitted URL marked 'noindex'" in GSC).

This turns the literal header value into the `$deck_robots` variable:

    map $deck_uri $deck_robots {
        default "noindex, indexifembedded";
        include /etc/nginx/deck-noindex-exempt.map;
    }

    location ~ ^/(en|de|...)/decks/(.+?)/$ {
        set $deck_uri $uri;                       # <- see WHY $deck_uri below
        ...
        add_header X-Robots-Tag $deck_robots always;

WHY `$deck_uri` AND NOT `$uri` (measured, not assumed). The deck block serves
its file with `try_files /deck.html`, which REWRITES `$uri` to `/deck.html`.
`add_header` evaluates its value lazily, in the header filter — i.e. AFTER
try_files — so a `map $uri` here is handed `/deck.html`, misses every key, and
silently falls through to the default. Verified live with a temporary
`add_header X-Debug-Uri "[$uri]"`, which returned `[/deck.html]`.

`set` runs in the REWRITE phase, before try_files (precontent), so `$deck_uri`
holds the real request path. (The neighbouring `map $uri $deck_redirect` is not
affected because it is read in an `if` at the TOP of the block, before
try_files runs — which is exactly why this trap is easy to miss.)

`$deck_uri` is empty on every non-deck request, which maps to the default; that
is harmless because `$deck_robots` is only ever used inside this one block.

The map body (generated by gen-deck-noindex-exempt-map.js) lists ONLY the
landing-less decks, each mapped to "". nginx omits add_header when the value is
an empty string, so an exempt deck serves no X-Robots-Tag at all while every
deck WITH a landing keeps `noindex, indexifembedded` from the default.

FAILS SAFE: the default is noindex, so a missing/stale/empty map leaves decks
noindexed. It can never accidentally un-noindex a deck that has a landing.

Does NOT touch the PDF blocks, the asset catch-all, or the /worksheets landing.
Idempotent. Backs up OUTSIDE sites-enabled/, runs `nginx -t`, reloads only if
the test passes (else restores the backup). Matches the patch-nginx-*.py
convention.

To REVERT: restore the printed backup, or re-run patch-nginx-deck-noindex.py
after removing the map block.

Usage:  sudo python3 patch-nginx-deck-noindex-exempt.py [--dry-run]
"""
import os
import re
import sys
import shutil
import subprocess
from datetime import datetime

CFG = os.path.realpath("/etc/nginx/sites-enabled/lessoncraftstudio")
MAP_FILE = "/etc/nginx/deck-noindex-exempt.map"
VAR = "$deck_robots"

# The deck.html block is the ONLY location whose body serves deck.html.
DECK_MARKER = "try_files /deck.html"
LOCATION = re.compile(r"^\s*location\b")
# The static header this replaces, in the exact shape patch-nginx-deck-noindex.py wrote.
STATIC_HEADER = re.compile(
    r'^(\s*)add_header\s+X-Robots-Tag\s+"noindex,\s*indexifembedded"\s+always;\s*$'
)
CONDITIONAL_HEADER = re.compile(
    r'^\s*add_header\s+X-Robots-Tag\s+\$deck_robots\s+always;\s*$'
)

SET_LINE = "        set $deck_uri $uri;   # capture before try_files rewrites $uri to /deck.html\n"
SET_RE = re.compile(r"^\s*set\s+\$deck_uri\s+\$uri;")
# An earlier revision of this script keyed the map on $uri, which silently never
# matched (see WHY above). Detect and upgrade that shape in place.
STALE_MAP_RE = re.compile(r"^(\s*)map\s+\$uri\s+\$deck_robots\s*\{")

MAP_BLOCK = (
    "# Deck robots policy (2026-07-30). Decks WITH a /worksheets/ landing are\n"
    "# noindexed so they don't compete with it; `indexifembedded` still lets\n"
    "# their content index as part of the landing that iframes them. Decks\n"
    "# WITHOUT a landing are self-canonical and are the ONLY indexable surface\n"
    "# for their content (they are what sitemap shards 0/1 submit), so they are\n"
    "# EXEMPTED to \"\" -- nginx omits add_header on an empty value.\n"
    "# Map body regenerated by scripts/publish-cli/gen-deck-noindex-exempt-map.js;\n"
    "# re-run it after any landing wave or the exempt set goes stale.\n"
    "# Default is noindex, so a missing/stale map fails SAFE.\n"
    "# Keyed on $deck_uri (set in the deck location) NOT $uri: try_files rewrites\n"
    "# $uri to /deck.html before add_header evaluates, so $uri would never match.\n"
    "map $deck_uri $deck_robots {\n"
    '    default "noindex, indexifembedded";\n'
    f"    include {MAP_FILE};\n"
    "}\n"
)


def has_map_block(text):
    """True when a $deck_robots map exists, keyed on ANY variable."""
    return re.search(r"^\s*map\s+\S+\s+\$deck_robots\s*\{", text, re.M) is not None


def upgrade_stale_map(lines):
    """Re-key an existing `map $uri $deck_robots` onto $deck_uri.

    Returns (lines, upgraded). See the WHY block at the top: the $uri form
    parses and reloads cleanly but never matches a single key, so it fails
    silently — every deck keeps the default noindex.
    """
    for idx, line in enumerate(lines):
        m = STALE_MAP_RE.match(line)
        if m:
            lines[idx] = f"{m.group(1)}map $deck_uri $deck_robots {{\n"
            return lines, True
    return lines, False


def insert_map_block(lines):
    """Insert the map block just before the first `server {`.

    nginx requires `map` at http{} level, and this file's existing maps
    ($deck_redirect, $pdf_canary_robots) all sit above the server blocks.
    """
    for idx, line in enumerate(lines):
        if re.match(r"^\s*server\s*\{", line):
            return lines[:idx] + [MAP_BLOCK, "\n"] + lines[idx:], True
    return lines, False


def swap_header(lines):
    """In the deck.html location: swap the static X-Robots-Tag for $deck_robots
    and make sure `set $deck_uri $uri;` is present.

    Only inside a location block whose body contains `try_files /deck.html`, so
    the PDF/asset blocks and their own X-Robots-Tag headers are untouched.
    Returns (new_lines, changed, already, set_added).
    """
    out = []
    i = 0
    n = len(lines)
    changed = 0
    already = 0
    set_added = 0
    while i < n:
        line = lines[i]
        if LOCATION.search(line):
            depth = line.count("{") - line.count("}")
            block = []
            j = i + 1
            has_deck_marker = DECK_MARKER in line
            while j < n and depth > 0:
                block.append(lines[j])
                if DECK_MARKER in lines[j]:
                    has_deck_marker = True
                depth += lines[j].count("{") - lines[j].count("}")
                j += 1
            out.append(line)
            if has_deck_marker:
                for k, bl in enumerate(block):
                    if CONDITIONAL_HEADER.match(bl):
                        already += 1
                        break
                    m = STATIC_HEADER.match(bl)
                    if m:
                        block[k] = f"{m.group(1)}add_header X-Robots-Tag {VAR} always;\n"
                        changed += 1
                        break
                # `set` is rewrite-phase, so it runs before try_files wherever it
                # sits textually; first line keeps it obvious to the next reader.
                if not any(SET_RE.match(bl) for bl in block):
                    block.insert(0, SET_LINE)
                    set_added += 1
            out.extend(block)
            i = j
            continue
        out.append(line)
        i += 1
    return out, changed, already, set_added


def main():
    dry = "--dry-run" in sys.argv[1:]

    if not os.path.exists(MAP_FILE):
        sys.stderr.write(
            f"FATAL: {MAP_FILE} does not exist. nginx will fail to start with a\n"
            f"       missing include. Run this first:\n"
            f"         node scripts/publish-cli/gen-deck-noindex-exempt-map.js\n"
        )
        sys.exit(1)

    with open(CFG) as f:
        lines = f.readlines()
    text = "".join(lines)

    map_added = False
    upgraded = False
    if has_map_block(text):
        lines, upgraded = upgrade_stale_map(lines)
        print("map $deck_robots: " + (
            "re-keyed from $uri to $deck_uri (the $uri form never matched)."
            if upgraded else "already present and correctly keyed."))
    else:
        lines, map_added = insert_map_block(lines)
        if not map_added:
            sys.stderr.write("FATAL: no `server {` found to anchor the map block.\n")
            sys.exit(1)
        print("map $deck_uri $deck_robots: will insert before the first server block.")

    lines, changed, already, set_added = swap_header(lines)
    print(f"deck.html blocks: {changed} header(s) to swap, {already} already conditional, "
          f"{set_added} `set $deck_uri` inserted.")

    if changed == 0 and not map_added and not upgraded and set_added == 0:
        print("Nothing to do.")
        return
    if dry:
        print("--dry-run: not writing.")
        return

    bk = f"/root/lcs-nginx-backup-decknoindexexempt-{datetime.now():%Y%m%d-%H%M%S}.conf"
    shutil.copy(CFG, bk)
    print(f"backup: {bk}")
    with open(CFG, "w") as f:
        f.writelines(lines)

    test = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
    sys.stderr.write(test.stderr)
    if test.returncode != 0:
        shutil.copy(bk, CFG)
        print("nginx -t FAILED -> restored backup; no reload.")
        sys.exit(1)
    subprocess.run(["systemctl", "reload", "nginx"], check=True)
    print(f"Swapped {changed} header(s), inserted {set_added} `set $deck_uri`, map block "
          f"{'inserted' if map_added else ('re-keyed' if upgraded else 'already present')}, "
          f"reloaded nginx.")
    print("Verify:")
    print("  curl -sI https://www.lessoncraftstudio.com/en/decks/<landing-less-slug>/ | grep -i x-robots   # expect NOTHING")
    print("  curl -sI https://www.lessoncraftstudio.com/en/decks/<with-landing-slug>/ | grep -i x-robots   # expect noindex, indexifembedded")


if __name__ == "__main__":
    main()
