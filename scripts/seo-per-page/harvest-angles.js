/* Distinguish "no suggestions" from "Google stopped answering".
 *
 * The first version returned [] for BOTH. Partway through a 9,625-seed run
 * Google began replying 403 "Sorry...", and the harvest sailed on recording
 * thousands of seeds as having no demand. That would have baked a confident,
 * entirely false "these angles are dead" into the wardrobe — the same shape of
 * bug as a swallowed regex error: the check keeps running and keeps lying.
 *
 * So a blocked response is now an explicit outcome, and the caller backs off or
 * aborts. Silence is never counted as evidence.
 */
function suggest(q) {
  const url = 'https://suggestqueries.google.com/complete/search?client=firefox&hl=en&gl=us&q='
    + encodeURIComponent(q);
  return new Promise((resolve) => {
    const req = https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' }, timeout: 10000 }, (res) => {
      let body = '';
      res.on('data', (c) => { body += c; });
      res.on('end', () => {
        if (res.statusCode !== 200) { resolve({ blocked: true, code: res.statusCode }); return; }
        try { resolve({ items: JSON.parse(body)[1] || [] }); }
        catch { resolve({ items: [] }); }
      });
    });
    req.on('error', (e) => resolve({ blocked: true, code: e.code || 'ERR' }));
    req.on('timeout', () => { req.destroy(); resolve({ blocked: true, code: 'TIMEOUT' }); });
  });
}

/* Intents a printable worksheet cannot honestly satisfy. Kept deliberately
 * short: this removes wrong PROMISES (apps, videos, courses), not phrasings I
 * personally find unlikely. Judging likelihood is Google's job here, not mine. */
const WRONG_INTENT = new RegExp([
  'duolingo', 'babbel', 'rosetta', 'busuu', 'khan academy', 'ixl', 'twinkl', 'teacherspayteachers',
  '\\bapps?\\b', 'youtube', 'netflix', '\\bmovies?\\b', '\\bcourse\\b', '\\bclasses\\b',
  'near me', '\\bjobs?\\b', '\\bsalary\\b', 'for adults', 'for teens', 'for grown ups',
].join('|'), 'i');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function run(locale, opts) {
  // real axis values for this locale, so seeds are measured not imagined
  const landings = JSON.parse(fs.readFileSync(
    path.join(ROOT, 'frontend', 'content', 'seo-landing', `${locale}.json`), 'utf8')).landings;

  /* Speak the way a person speaks.
   *
   * Raw slugs make nonsense seeds: `animals-vs-desserts and sweets addition for
   * kids`, or `big small` for what everyone calls "bigger or smaller". The
   * taxonomy already holds the human name for every theme, level and type, so
   * use it — and split the `-vs-` picture-sort keys into their real components
   * rather than seeding on a compound nobody would ever type. */
  const TAX = JSON.parse(fs.readFileSync(
    path.join(ROOT, 'frontend', 'config', 'topics-taxonomy.json'), 'utf8')).axes || {};
  const display = (axis, key) => {
    const e = (TAX[axis] || {})[key];
    const n = e && e.name && (e.name[locale] || e.name.en);
    const raw = n ? String(n).toLowerCase() : String(key).replace(/[-_]/g, ' ');
    // a trailing number is a duplicate marker, not part of the name (CLAUDE.md S20.5)
    return raw.replace(/\s+\d+$/, '').trim();
  };

  const themes = new Set(); const levels = new Set(); const types = new Set(); const langs = new Set();
  for (const l of landings) {
    const c = l.coordinate || {};
    if (c.theme) {
      for (const part of String(c.theme).split('-vs-')) themes.add(display('theme', part));
    }
    if (c.level) levels.add(display('educational-level', c.level));
    if (c.type) types.add(display('exercise-type', c.type));
    const m = /^([a-z]+)-/.exec(l.slug);
    if (m && ['danish', 'dutch', 'french', 'german', 'finnish', 'spanish', 'italian',
      'portuguese', 'swedish', 'norwegian'].includes(m[1])) langs.add(m[1]);
  }
  const AGES = ['3', '4', '5', '6', '7', '8'];
  const SKILLS = ['letter recognition', 'beginning sounds', 'counting', 'addition',
    'subtraction', 'spelling', 'vocabulary', 'patterns', 'shapes', 'telling time'];

  // build the seed list by filling each pattern from the real axis values
  const seeds = new Map();   // seed -> group
  const pick = (set, n) => [...set].sort().filter((_, i) => i % Math.max(1, Math.ceil(set.size / n)) === 0);
  const themeSample = pick(themes, 14);
  const levelSample = [...levels];
  const typeSample = pick(types, 14);
  const langSample = [...langs];

  for (const [group, pats] of Object.entries(PATTERNS)) {
    for (const pat of pats) {
      const slots = (pat.match(/\{(\w+)\}/g) || []).map((s) => s.slice(1, -1));
      const fillsFor = (slot) => ({
        theme: themeSample, level: levelSample, type: typeSample,
        age: AGES, skill: SKILLS, lang: langSample,
      }[slot] || []);
      if (!slots.length) { seeds.set(pat, group); continue; }
      // fill one slot at a time against a representative value for the others
      let combos = [pat];
      for (const slot of slots) {
        const vals = fillsFor(slot);
        if (!vals.length) { combos = []; break; }
        const next = [];
        for (const c of combos) for (const v of vals.slice(0, slots.length > 1 ? 6 : 14)) {
          next.push(c.replace(`{${slot}}`, v));
        }
        combos = next;
      }
      for (const c of combos) seeds.set(c, group);
    }
  }

  /* Cross the dimensions. This is where the breadth comes from: every noun a
   * K-3 adult might use, against every audience, qualifier, and the page's own
   * real axes. Google keeps what is real. */
  const add = (q, group) => {
    const t = q.replace(/\s+/g, ' ').trim();
    if (t.length > 6 && !seeds.has(t)) seeds.set(t, group);
  };
  for (const noun of NOUN) {
    for (const aud of AUDIENCE) {
      add(`${noun} ${aud}`, 'noun');
      for (const q of QUALIFIER) if (q) add(`${q} ${noun} ${aud}`, 'noun');
    }
    for (const th of themeSample) {
      add(`${th} ${noun} for kids`, 'subject');
      add(`${th} ${noun}`, 'subject');
    }
    for (const lv of levelSample) {
      add(`${noun} for ${lv}`, 'age');
      add(`free ${noun} for ${lv}`, 'age');
    }
    for (const ag of AGES) add(`${noun} for ${ag} year olds`, 'age');
    for (const sk of SKILLS) add(`${sk} ${noun} for kids`, 'skill');
    for (const lg of langSample) add(`${lg} ${noun} for kids`, 'language');
  }
  for (const v of VERB) {
    for (const sk of SKILLS) add(`${v} ${sk} for kids`, 'skill');
    for (const th of themeSample) add(`${v} about ${th} for kids`, 'subject');
    for (const lg of langSample) add(`${v} ${lg} for kids`, 'language');
  }

  console.log(`[${locale}] ${seeds.size} seeds`
    + ` (${NOUN.length} nouns x ${AUDIENCE.length} audiences x ${QUALIFIER.length} qualifiers,`
    + ` themes ${themes.size}, levels ${levels.size}, types ${types.size}, langs ${langs.size})`);
  if (opts.dryRun) {
    [...seeds.keys()].slice(0, 25).forEach((s) => console.log('   ' + s));
    return;
  }

  /* Checkpoint so a block costs minutes, not the whole run. */
  const ckptFile = path.join(OUT_DIR, `${locale}.progress.json`);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const bank = new Map();    // query -> {group, seeds:[]}
  const doneSeeds = new Set();
  if (opts.resume && fs.existsSync(ckptFile)) {
    const c = JSON.parse(fs.readFileSync(ckptFile, 'utf8'));
    for (const [q, m] of Object.entries(c.bank || {})) bank.set(q, m);
    for (const sd of (c.doneSeeds || [])) doneSeeds.add(sd);
    console.log(`   resumed: ${doneSeeds.size} seeds already asked, ${bank.size} phrases banked`);
  }
  const saveCkpt = () => {
    fs.writeFileSync(ckptFile, JSON.stringify({
      bank: Object.fromEntries(bank), doneSeeds: [...doneSeeds],
    }));
  };

  let asked = 0; let consecutiveBlocks = 0; let backoff = opts.delay;
  for (const [seed, group] of seeds) {
    if (doneSeeds.has(seed)) continue;
    const res = await suggest(seed);

    if (res.blocked) {
      consecutiveBlocks++;
      // Google is refusing. Wait longer and retry the SAME seed; never record it
      // as empty, which is what silently poisoned the previous run.
      if (consecutiveBlocks >= 6) {
        saveCkpt();
        console.log(`
   BLOCKED by ${res.code} after ${asked} seeds this run.`);
        console.log(`   ${bank.size} phrases saved to checkpoint. Re-run with --resume later.`);
        return { blocked: true, bank };
      }
      backoff = Math.min(backoff * 3, 60000);
      console.log(`   ${res.code} — backing off ${Math.round(backoff / 1000)}s (${consecutiveBlocks}/6)`);
      await sleep(backoff);
      continue;
    }

    consecutiveBlocks = 0;
    backoff = opts.delay;
    doneSeeds.add(seed);
    asked++;
    for (const s of res.items) {
      const q = String(s).toLowerCase().trim();
      if (WRONG_INTENT.test(q)) continue;
      if (q.length < 8) continue;
      if (!bank.has(q)) bank.set(q, { group, seeds: [] });
      if (bank.get(q).seeds.length < 3) bank.get(q).seeds.push(seed);
    }
    if (asked % 100 === 0) {
      console.log(`   ${asked}/${seeds.size} seeds, ${bank.size} real phrases`);
      saveCkpt();
    }
    await sleep(opts.delay);
  }
  saveCkpt();

  const byGroup = {};
  for (const [q, meta] of bank) (byGroup[meta.group] = byGroup[meta.group] || []).push(q);
  for (const g of Object.keys(byGroup)) byGroup[g].sort();

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, `${locale}.json`), JSON.stringify({
    locale, source: 'google autocomplete hl=en gl=us', seedsAsked: asked,
    total: bank.size, byGroup,
  }, null, 1));

  console.log(`\n[${locale}] ${bank.size} validated phrases from ${asked} seeds`);
  for (const g of Object.keys(byGroup).sort()) console.log(`   ${g.padEnd(11)} ${byGroup[g].length}`);
}

if (require.main === module) {
  const a = process.argv.slice(2);
  const locale = (a.find((x) => x.startsWith('--locale=')) || '').split('=')[1] || 'en';
  const delay = Number((a.find((x) => x.startsWith('--delay=')) || '').split('=')[1] || 600);
  run(locale, { delay, dryRun: a.includes('--dry-run'), resume: a.includes('--resume') }).catch((e) => {
    console.error(e.message); process.exitCode = 1;
  });
}

module.exports = { PATTERNS, WRONG_INTENT };
