// Load-time validation: symmetric by construction or it cannot ship.
for (const f of FIGURES) {
  const w = f.rows[0].length;
  if (w % 2 !== 1) throw new Error(`symmetry figure ${f.key}: width ${w} must be odd`);
  for (const r of f.rows) {
    if (r.length !== w) throw new Error(`symmetry figure ${f.key}: ragged row "${r}"`);
    if (r !== [...r].reverse().join('')) throw new Error(`symmetry figure ${f.key}: row not palindromic "${r}"`);
    if (!/^[.#]+$/.test(r)) throw new Error(`symmetry figure ${f.key}: bad chars "${r}"`);
  }
  if (!f.rows.some((r) => r.includes('#'))) throw new Error(`symmetry figure ${f.key}: empty`);
}

module.exports = { FIGURES };
