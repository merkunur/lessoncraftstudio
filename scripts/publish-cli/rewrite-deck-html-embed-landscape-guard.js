#!/usr/bin/env node
/**
 * Salvage retrofit: inject `window.parent !== window` guard into the embedded
 * fit() function inside published deck.html files. Prevents the phone-landscape
 * compact-fit CSS from triggering inside embed iframes (where the iframe
 * viewport can match the (max-width:1024px) AND (orientation:landscape) media
 * query when auto-resize shrinks the frame to wide-and-short during initial
 * load — the destructive width:100%+height:100%+object-fit:contain rules
 * create a circular height dependency, collapsing the worksheet image to
 * near-zero and stranding the iframe wide-and-short).
 *
 * Per CLAUDE.md §15.17 salvage scripts pattern. Mirrors the structure of
 * inject-deck-end-strip.js + rewrite-deck-html-title.js: in-place text
 * replacement on existing deck.html files. Atomic per-file write via .tmp
 * sibling + rename.
 *
 * Pipeline:
 *   1. Walk /var/www/lcs-media/decks/<locale>/<slug> symlinks
 *   2. Resolve to <slug>-v<N>/deck.html target
 *   3. Idempotency check (skip if guard already present)
 *   4. String-replace the lcs-worksheet-landscape class addition + insert guard
 *   5. Atomic write
 *
 * Idempotent: skips files that already contain the guard marker.
 *
 * Usage:
 *   node scripts/publish-cli/rewrite-deck-html-embed-landscape-guard.js [--dry-run] [--locale=<code>]
 */

'use strict';

var fs = require('fs');
var path = require('path');

var DECKS_ROOT = '/var/www/lcs-media/decks';
var ALL_LOCALES = ['en', 'de', 'es', 'nl', 'fr', 'it', 'pt', 'sv', 'da', 'no', 'fi'];

var argv = process.argv.slice(2);
var DRY_RUN = argv.includes('--dry-run');
var localeFlag = argv.find(function (a) { return a.indexOf('--locale=') === 0; });
var TARGET_LOCALE = localeFlag ? localeFlag.split('=')[1] : null;

// Source pattern: the exact 2-line block emitted by buildResponsiveFitSnippet
// before this commit's fix.
var OLD_PATTERN =
  '    var isLandscapeWs = img.naturalWidth > img.naturalHeight;\n' +
  '    if (isLandscapeWs) document.body.classList.add("lcs-worksheet-landscape");';

// Target pattern: same lines, with the new guard injected before isLandscapeWs.
// Marker: "(window.parent !== window)" inside the fit() block — used by
// idempotency check to skip already-retrofitted files.
var NEW_PATTERN =
  '    var isEmbedded = (window.parent !== window);\n' +
  '    if (isEmbedded) {\n' +
  '      document.body.classList.remove("lcs-worksheet-landscape");\n' +
  '      ws.style.width = ""; ws.style.height = "";\n' +
  '      ws.style.maxWidth = ""; ws.style.maxHeight = "";\n' +
  '      return;\n' +
  '    }\n' +
  '    var isLandscapeWs = img.naturalWidth > img.naturalHeight;\n' +
  '    if (isLandscapeWs) document.body.classList.add("lcs-worksheet-landscape");';

var IDEMPOTENCY_MARKER = 'var isEmbedded = (window.parent !== window);';

function processFile(filepath) {
  var content;
  try {
    content = fs.readFileSync(filepath, 'utf8');
  } catch (e) {
    return { ok: false, error: 'read failed: ' + e.message };
  }

  // Idempotency: already-retrofitted decks contain the marker.
  if (content.indexOf(IDEMPOTENCY_MARKER) !== -1) {
    return { ok: true, skipped: true, reason: 'already-applied' };
  }

  // Sanity: must contain the OLD pattern. If not, the deck was generated by
  // a code path we don't expect (older app source? hand-edited?). Skip + warn.
  if (content.indexOf(OLD_PATTERN) === -1) {
    return { ok: true, skipped: true, reason: 'no-match' };
  }

  var newContent = content.split(OLD_PATTERN).join(NEW_PATTERN);
  if (newContent === content) {
    return { ok: true, skipped: true, reason: 'no-change' };
  }

  if (DRY_RUN) {
    return { ok: true, wouldRewrite: true };
  }

  // Atomic write: .tmp sibling + rename.
  var tmpPath = filepath + '.tmp';
  try {
    fs.writeFileSync(tmpPath, newContent, 'utf8');
    fs.renameSync(tmpPath, filepath);
  } catch (e) {
    try { fs.unlinkSync(tmpPath); } catch (_) {}
    return { ok: false, error: 'write failed: ' + e.message };
  }
  return { ok: true, rewritten: true };
}

function processDeck(locale, slug) {
  var localeDir = path.join(DECKS_ROOT, locale);
  var symlinkPath = path.join(localeDir, slug);
  var stat;
  try {
    stat = fs.lstatSync(symlinkPath);
  } catch (e) {
    return { ok: false, error: 'lstat failed: ' + e.message };
  }
  if (!stat.isSymbolicLink()) {
    return { ok: false, error: 'not a symlink (skipped)' };
  }
  var target = fs.readlinkSync(symlinkPath);
  var targetDir = path.isAbsolute(target) ? target : path.join(localeDir, target);
  var deckHtmlPath = path.join(targetDir, 'deck.html');
  if (!fs.existsSync(deckHtmlPath)) {
    return { ok: false, error: 'deck.html not found at ' + deckHtmlPath };
  }
  return processFile(deckHtmlPath);
}

function main() {
  console.log('=== rewrite-deck-html-embed-landscape-guard ===');
  console.log('mode:    ' + (DRY_RUN ? 'DRY-RUN' : 'WRITE'));
  console.log('locale:  ' + (TARGET_LOCALE || 'all 11'));
  console.log('');

  var locales = TARGET_LOCALE ? [TARGET_LOCALE] : ALL_LOCALES;
  var totalProcessed = 0;
  var totalRewritten = 0;
  var totalAlreadyApplied = 0;
  var totalNoMatch = 0;
  var totalFailed = 0;
  var failures = [];
  var perLocaleStats = {};

  for (var li = 0; li < locales.length; li++) {
    var locale = locales[li];
    var localeDir = path.join(DECKS_ROOT, locale);
    if (!fs.existsSync(localeDir)) continue;
    var entries = fs.readdirSync(localeDir);
    var slugs = entries.filter(function (name) {
      if (name.startsWith('.')) return false;
      return !/-v\d+$/.test(name);
    });
    perLocaleStats[locale] = { total: slugs.length, rewritten: 0, alreadyApplied: 0, noMatch: 0, failed: 0 };
    console.log('[' + locale + '] ' + slugs.length + ' deck symlinks');
    for (var si = 0; si < slugs.length; si++) {
      var slug = slugs[si];
      totalProcessed++;
      var r = processDeck(locale, slug);
      if (!r.ok) {
        totalFailed++;
        perLocaleStats[locale].failed++;
        failures.push(locale + '/' + slug + ': ' + r.error);
      } else if (r.skipped) {
        if (r.reason === 'already-applied') {
          totalAlreadyApplied++;
          perLocaleStats[locale].alreadyApplied++;
        } else if (r.reason === 'no-match') {
          totalNoMatch++;
          perLocaleStats[locale].noMatch++;
        }
      } else if (r.wouldRewrite || r.rewritten) {
        totalRewritten++;
        perLocaleStats[locale].rewritten++;
      }
    }
  }

  console.log('');
  console.log('=== summary ===');
  console.log('  processed:           ' + totalProcessed);
  console.log('  ' + (DRY_RUN ? 'would-rewrite' : 'rewritten') + ':          ' + totalRewritten);
  console.log('  already-applied:     ' + totalAlreadyApplied);
  console.log('  no-match (skipped):  ' + totalNoMatch);
  console.log('  failed:              ' + totalFailed);
  console.log('');
  console.log('=== per-locale ===');
  Object.keys(perLocaleStats).forEach(function (loc) {
    var s = perLocaleStats[loc];
    console.log('  ' + loc + ':  total=' + s.total + ' ' + (DRY_RUN ? 'would' : 'rewritten') + '=' + s.rewritten +
      ' already=' + s.alreadyApplied + ' no-match=' + s.noMatch + ' failed=' + s.failed);
  });
  if (failures.length > 0) {
    console.log('');
    console.log('=== failures ===');
    failures.forEach(function (f) { console.log('  - ' + f); });
  }
  process.exit(failures.length > 0 ? 1 : 0);
}

if (require.main === module) {
  main();
}

module.exports = { processFile: processFile, processDeck: processDeck };
