#!/usr/bin/env node
/**
 * tools/build-nordic-definite.js — the definite singular of every picture noun in sv / da / no (2026-11-03, the One &
 * Many, Articles maker, NEW-TEMPLATES §42 T4 "A or The?": en hund → hunden, ett äpple → äpplet). The Nordic definite
 * is a SUFFIX, and the vocabulary stores only the singular, the plural and the gender, so the suffix form is never
 * computed at page time (sv djur → *djurna, kat → *katen, finger → *fingeret are the classic wrong forms): this tool
 * proposes each language's forms in its grammar's order and keeps the FIRST one a large real word list attests, or no
 * form at all (the noun is then refused by the page). Word list: the OpenSubtitles 50k frequency lists of
 * hermitdave/FrequencyWords (content CC BY-SA 4.0), one "word count" per line.
 *   sv  en-word: vowel → +n (flicka → flickan), unstressed -el/-er/-or/-ar → +n (fågel → fågeln, tiger → tigern), else
 *       +en (hund → hunden, kamel → kamelen); ett-word: one syllable → +et (bi → biet, hus → huset), vowel → +t (äpple →
 *       äpplet), -el/-er/-en → drop the e +et (finger → fingret, vatten → vattnet), else +et
 *   da  common: -e → +n (pige → pigen), else +en, else the final consonant doubled +en (kat → katten); -el/-er → drop
 *       the e +en (cykel → cyklen); neuter likewise with -t / -et (æble → æblet, hus → huset, lam → lammet, æsel → æslet)
 *   no  (bokmål) masculine: -e → +n (jente → jenten), else +en; neuter: -e → +t (eple → eplet), else +et, else doubled
 *       (hjul → hjulet); a feminine -a form (jenta, boka, kua) is kept as an ALTERNATIVE when the word list holds it at
 *       least a quarter as often (bokmål accepts both; the page prints the -en form)
 * Output: data/nouns-articles/definite-nordic.js { sv|da|no: { <vocab key>: [definite] | [definite, alt] } } plus
 * the refused keys, for the native review. Re-run when the vocabulary changes:
 *   node tools/build-nordic-definite.js <dir with sv.txt da.txt no.txt>
 */
'use strict';
const fs = require('fs'), path = require('path');
const { vocab } = require('../lib/b2-common.js');

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-nordic-definite.js <dir of sv.txt da.txt no.txt>'); process.exit(2); }
const V = 'aeiouyåäöæø';
const vowel = (c) => V.includes(c);
const syllables = (w) => (w.match(/[aeiouyåäöæø]+/g) || []).length;
const dropE = (w) => w.replace(/e([lnr])$/, '$1');   // finger → fingr, cykel → cykl, vatten → vattn

function candidates(w, L, g) {
  const last = w.slice(-1), c = [];
  if (L === 'sv') {
    if (g === 'n') {
      if (vowel(last)) c.push(w + 'n');
      if (/(el|er|or|ar)$/.test(w)) c.push(w + 'n');
      c.push(w + 'en');
    } else {
      if (syllables(w) === 1) c.push(w + 'et');
      if (vowel(last)) c.push(w + 't');
      if (/e[lnr]$/.test(w)) c.push(dropE(w) + 'et');
      c.push(w + 'et');
    }
  } else if (L === 'da') {
    const s = g === 'n' ? 'en' : 'et';
    if (last === 'e') c.push(w + s.slice(1));
    if (/e[lr]$/.test(w)) c.push(dropE(w) + s);
    c.push(w + s);
    if (!vowel(last)) c.push(w + last + s);
  } else if (L === 'no') {
    const s = g === 'n' ? 'et' : 'en';
    if (last === 'e') c.push(w + s.slice(1));
    c.push(w + s);
    if (!vowel(last)) c.push(w + last + s);
  }
  return [...new Set(c)];
}

const out = {}, refused = {};
for (const L of ['sv', 'da', 'no']) {
  const freq = new Map();
  for (const line of fs.readFileSync(path.join(dir, `${L}.txt`), 'utf8').split(/\r?\n/)) {
    const [w, n] = line.trim().split(' ');
    if (w) freq.set(w.toLocaleLowerCase(L).normalize('NFC'), +n || 0);
  }
  out[L] = {}; refused[L] = [];
  for (const [key, e] of Object.entries(vocab())) {
    const x = e && e[L];
    if (!x || !x[0] || !x[2]) continue;
    const w = String(x[0]).toLocaleLowerCase(L).trim();
    if (!/^\p{L}+$/u.test(w)) continue;
    const hit = candidates(w, L, x[2]).find((c) => freq.has(c));
    if (!hit) { refused[L].push(key); continue; }
    const forms = [hit];
    if (L === 'no' && x[2] !== 'n') {
      const a = (w.endsWith('e') ? w.slice(0, -1) : w) + 'a';
      if (a !== hit && (freq.get(a) || 0) >= 0.25 * (freq.get(hit) || 0)) forms.push(a);
    }
    out[L][key] = forms;
  }
  console.log(L, 'definite', Object.keys(out[L]).length, 'refused', refused[L].length);
}
const file = path.join(__dirname, '..', 'data', 'nouns-articles', 'definite-nordic.js');
fs.mkdirSync(path.dirname(file), { recursive: true });
const head = '/**\n * data/nouns-articles/definite-nordic.js — GENERATED by tools/build-nordic-definite.js; never hand-edit (native\n * corrections live in types/_shared/noun-forms.js DEFINITE_FIX, which wins). The definite singular of each picture noun in\n * sv / da / no, the first form of the language\'s grammar that the OpenSubtitles 50k word list attests\n * (hermitdave/FrequencyWords, content CC BY-SA 4.0); no: a second form is the accepted feminine -a. A noun missing here is\n * refused by the page.\n */\n\'use strict\';\n';
fs.writeFileSync(file, head + 'const DEFINITE = ' + JSON.stringify(out) + ';\nconst REFUSED = ' + JSON.stringify(refused) + ';\nmodule.exports = { DEFINITE, REFUSED };\n');
console.log('wrote', file, Math.round(fs.statSync(file).size / 1024), 'KB');
