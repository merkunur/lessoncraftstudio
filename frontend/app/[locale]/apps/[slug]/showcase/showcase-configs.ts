// Locale → alt text lookup
const altTextsByLocale: Record<string, Record<string, [string, string, string, string, string, string, string, string, string, string]>> = {
  de: deAltTexts, fr: frAltTexts, es: esAltTexts, pt: ptAltTexts, it: itAltTexts,
};

function localizeShowcase(
  config: ShowcaseConfig,
  appId: string,
  images: Record<string, { folder: string; imgs: string[]; answerKey: string }>,
  appText: Record<string, [string, string, string, string, string, string, string, string, string, string, string, string]>,
  locale: string,
): ShowcaseConfig | null {
  const gi = images[appId];
  const dt = appText[appId];
  if (!gi || !dt || !gi.imgs.length) return null;

  const [heroH, heroSub, tieredH, tieredSub, t1, t2, t3, trophy, spotH, spotTag, galH, galSub] = dt;
  const di = (filename: string) => imgUrl(gi.folder, filename, locale);

  // Localized alt text (falls back to English if not available)
  const alts = altTextsByLocale[locale]?.[appId];
  const a = (index: number, fallback: string) => alts?.[index] || fallback;

  return {
    hero: {
      ...config.hero,
      badge: t(config.hero.badge, locale),
      heading: heroH,
      subheading: heroSub,
      images: [
        { src: di(gi.imgs[0]), alt: a(0, config.hero.images[0]?.alt || '') },
        { src: di(gi.imgs[1]), alt: a(1, config.hero.images[1]?.alt || '') },
        { src: di(gi.imgs[2]), alt: a(2, config.hero.images[2]?.alt || '') },
      ],
      pills: tPills(config.hero.pills, locale),
    },
    tiered: {
      ...config.tiered,
      badge: t(config.tiered.badge, locale),
      heading: tieredH,
      subheading: tieredSub,
      tiers: config.tiered.tiers.map((tier, i) => ({
        ...tier,
        name: t(tier.name, locale),
        image: { src: di(gi.imgs[i]), alt: a(3 + i, tier.image.alt) },
        desc: [t1, t2, t3][i] || tier.desc,
      })) as [typeof config.tiered.tiers[0], typeof config.tiered.tiers[1], typeof config.tiered.tiers[2]],
      trophyText: trophy,
    },
    spotlight: {
      ...config.spotlight,
      heading: spotH,
      tagline: spotTag,
      image: { src: di(gi.imgs[3]), alt: a(6, config.spotlight.image.alt) },
      pills: tStringPills(config.spotlight.pills, locale),
    },
    gallery: {
      ...config.gallery,
      heading: galH,
      subheading: galSub,
      items: [
        { image: { src: di(gi.imgs[4]), alt: a(7, config.gallery.items[0]?.image.alt || '') }, label: t(config.gallery.items[0]?.label || '', locale) },
        { image: { src: di(gi.imgs[5] || gi.imgs[0]), alt: a(8, config.gallery.items[1]?.image.alt || '') }, label: t(config.gallery.items[1]?.label || '', locale) },
        { image: { src: di(gi.answerKey), alt: a(9, config.gallery.items[2]?.image.alt || '') }, label: t('Answer Key', locale) },
      ],
      pills: tStringPills(config.gallery.pills, locale),
    },
  };
}

/** Get showcase config for a given app ID and locale */
export function getLocalizedShowcaseConfig(appId: string, locale: string): ShowcaseConfig | null {
  const enConfig = showcaseConfigs[appId] ?? null;
  if (!enConfig) return null;
  if (locale === 'de') return localizeShowcase(enConfig, appId, germanImages, deAppText, 'de');
  if (locale === 'fr') return localizeShowcase(enConfig, appId, frenchImages, frAppText, 'fr');
  if (locale === 'es') return localizeShowcase(enConfig, appId, spanishImages, esAppText, 'es');
  if (locale === 'pt') return localizeShowcase(enConfig, appId, portugueseImages, ptAppText, 'pt');
  if (locale === 'it') return localizeShowcase(enConfig, appId, italianImages, itAppText, 'it');
  if (locale === 'nl') return localizeShowcase(enConfig, appId, dutchImages, nlAppText, 'nl');
  if (locale === 'sv') return localizeShowcase(enConfig, appId, swedishImages, svAppText, 'sv') ?? enConfig;
  if (locale === 'da') return localizeShowcase(enConfig, appId, danishImages, daAppText, 'da') ?? enConfig;
  return enConfig;
}
