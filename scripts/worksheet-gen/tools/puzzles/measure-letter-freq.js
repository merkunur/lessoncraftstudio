#!/usr/bin/env node
/**
 * tools/puzzles/measure-letter-freq.js — the filler letters of a word search, MEASURED per language (2026-11-03,
 * ENGINES Part 3 §A): the frequency of every letter over the picture vocabulary of that language (every singular and
 * plural, lower case, letters only). A letter the language's words never use (fi b c f q w x z) gets no weight, so a
 * Finnish grid never shows a q. Writes data/puzzles/letter-freq.js { <loc>: { <letter>: count } }.
 *   node tools/puzzles/measure-letter-freq.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const { vocab } = require('../../lib/b2-common.js');
const { COLLATION } = require('../../data/b2/collation.js');

const LOCS = ['en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
const out = {};
for (const L of LOCS) {
  const f = {};
  for (const e of Object.values(vocab())) {
    const x = e && e[L];
    if (!x) continue;
    for (const w of [x[0], x[1]]) for (const c of String(w || '').toLocaleLowerCase(L)) if (/\p{L}/u.test(c)) f[c] = (f[c] || 0) + 1;
  }
  // fillers are the language's own school letters (data/b2/collation.js strip: es ñ, sv å ä ö — never an accented vowel or
  // another language's letter), and a letter under 0.4 % of the words' letters is a loanword's (fi b c f z w): no filler
  // (+ the accented letters the language writes — de ä ö ü, fr é è ç: a grid whose only é sits in a hidden word gives it away)
  const own = new Set(COLLATION[L].strip.concat(Object.keys(COLLATION[L].fold).filter((c) => c.length === 1))), total = Object.values(f).reduce((a, b) => a + b, 0);
  for (const c of Object.keys(f)) if (!own.has(c) || f[c] < total * 0.004) delete f[c];
  out[L] = Object.fromEntries(Object.entries(f).sort((a, b) => b[1] - a[1]));
}
const file = path.join(__dirname, '..', '..', 'data', 'puzzles', 'letter-freq.js');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, '/** data/puzzles/letter-freq.js — GENERATED by tools/puzzles/measure-letter-freq.js (the picture vocabulary\'s letters per\n * language); never hand-edit. */\n\'use strict\';\nmodule.exports = { LETTER_FREQ: ' + JSON.stringify(out) + ' };\n');
console.log('wrote', file, LOCS.map((L) => L + ':' + Object.keys(out[L]).length).join(' '));
