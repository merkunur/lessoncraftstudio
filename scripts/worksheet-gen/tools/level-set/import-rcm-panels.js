/**
 * Reading Comprehension Level Set — import the native panels' halves (<loc>-A.json + <loc>-B.json) into
 * data/literacy/rc-levels/<loc>.json, validate the merged locale (every hard rule + completeness), and write the
 * level instructions (i18n/level-instructions.json G2-254/G2-269..273 levels 1 and 3) and the screen instruction
 * (i18n/interactive-instructions.json reading-comprehension.mc).
 *   node tools/level-set/import-rcm-panels.js <panelDir> <loc,loc,…>
 * Refuses the whole locale on any failure (nothing is written for it).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { validateLocale } = require('./rc-validate.js');

const DIR = process.argv[2];
const LOCS = (process.argv[3] || '').split(',').filter(Boolean);
const ROOT = path.join(__dirname, '..', '..');
const PAGES = ['G2-254', 'G2-269', 'G2-270', 'G2-271', 'G2-272', 'G2-273'];
const LI = path.join(ROOT, 'i18n', 'level-instructions.json');
const II = path.join(ROOT, 'i18n', 'interactive-instructions.json');
const li = JSON.parse(fs.readFileSync(LI, 'utf8'));
const ii = JSON.parse(fs.readFileSync(II, 'utf8'));
let bad = 0;
for (const loc of LOCS) {
  const A = JSON.parse(fs.readFileSync(path.join(DIR, `${loc}-A.json`), 'utf8'));
  const B = JSON.parse(fs.readFileSync(path.join(DIR, `${loc}-B.json`), 'utf8'));
  const d = {
    _note: `Reading Comprehension Level Set (2026-09-30), ${loc}: native panels, never translated. Generated by tools/level-set/import-rcm-panels.js.`,
    published: { ...A.published, ...B.published },
    pools: { ...A.pools, ...B.pools },
    levelInstr: A.levelInstr, sentenceChip: A.sentenceChip, screen: A.screen,
  };
  const f = validateLocale(d, loc, { requireAll: true });
  const fixes = { ...(A.publishedFixes || {}), ...(B.publishedFixes || {}) };
  if (Object.keys(fixes).length) console.log(`${loc}: ${Object.keys(fixes).length} PUBLISHED FIX(ES) proposed — apply by hand: ${Object.keys(fixes).join(', ')}`);
  if (f.length) { bad++; console.log(`${loc}: REFUSED (${f.length})`); f.slice(0, 30).forEach((x) => console.log('  ' + x)); continue; }
  fs.mkdirSync(path.join(ROOT, 'data', 'literacy', 'rc-levels'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'data', 'literacy', 'rc-levels', `${loc}.json`), JSON.stringify(d, null, 1) + '\n');
  for (const id of PAGES) for (const lv of ['1', '3']) {
    li[id] = li[id] || {}; li[id][lv] = li[id][lv] || {};
    li[id][lv][loc] = { instruction: d.levelInstr[lv] };
  }
  ii['reading-comprehension'] = ii['reading-comprehension'] || {};
  ii['reading-comprehension'].mc = ii['reading-comprehension'].mc || {};
  ii['reading-comprehension'].mc[loc] = d.screen.mc;
  const n = Object.values(d.pools).reduce((a, l) => a + l.length, 0);
  console.log(`${loc}: ok — ${Object.keys(d.published).length} published stories with level sets, ${n} new stories`);
}
fs.writeFileSync(LI, JSON.stringify(li, null, 1) + '\n');
fs.writeFileSync(II, JSON.stringify(ii, null, 1) + '\n');
process.exit(bad ? 1 : 0);
