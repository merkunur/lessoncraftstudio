/* =====================================================================
   _number-hotel-strings.js — TOOL #49's ten authored locales.
   Each was REBUILT by a three-person native panel with the English
   handed over as a SOURCE TO AUDIT, never as a target.

   ⚠ THE CORRIDOR NOUN WAS THE HARD PART, because floor / storey /
   building / tower / level / skyline are all formally owned by shipped
   siblings. What the panels found, and none of it was in my brief:
     de  der Flur   — `Gang` rejected: it collides with gear/gait in a
                      tool whose verb is walking. `Flur` is a homograph
                      (die Flur = an open field) so every use here is
                      masculine and the article disambiguates.
     fr  la galerie — ⚠ `couloir` is NOT free: `unroll-tape` owns it as
                      its measuring runway, six uses including its
                      tagline and metaDescription. `rangée` is out too.
     es  el pasillo — `corredor` rejected for the runner/broker sense in
                      a tool about someone walking.
     pt  o corredor — ⚠ and `andar` is BOTH "to walk" and the banned
                      noun "storey", so the walk VERB is unusable; pt
                      says "dar um passo" throughout. A homograph
                      English does not have.
     it  il corridoio — ⚠ `piano` is doubly dangerous: the banned
                      "floor" AND the plan name. It appears in the
                      Italian set exactly twice, both in "piano
                      Insegnante".
     nl  de gang    — safe (multiplication is *keer*), with one near
                      miss: `gang` is also a course of a meal, live in a
                      hotel. Never paired with food words.
     sv  korridoren — ⚠ `gång` rejected: definite `gången` = the
                      time/occasion.
     da  korridoren — ⚠⚠ `gang` is unusable: `at gange` = TO MULTIPLY,
                      `gangetabellen` = the times table. A head-on
                      collision inside a maths tool.
     no  korridoren — ⚠⚠ same: `ganger` = times.
     fi  käytävä    — clean. ⚠ And Finnish is the one locale that wants
                      "ON the corridor" (adessive `käytävällä`); Dutch
                      and the three Scandinavian languages want "IN".
                      This string must NOT be harmonised across locales.
   ⚠ NEVER ship a bare `Tal.` in Danish — it is the imperative "Speak!",
   the same family as the recorded "Ti." = "Be quiet" defect on #48.
   ===================================================================== */
