#!/usr/bin/env node
/**
 * build-maker-assets.js — generate the worksheet-maker redirect map + slug map
 * for SEO RESCUE Part 1 Phase 1b, from git ground-truth (commit 49b501b0^,
 * before the pivot deleted the slug configs).
 *
 * Emits:
 *   frontend/config/maker-redirects.ts  — 301 map /<loc>/apps/<x>-worksheets -> /<loc>/tools/<maker-slug>
 *   (stdout) makerSlugs JSON            — { makerKey: { locale: slug } } to feed content authoring
 *
 * Reading from git (not hand-transcribed) keeps the 363-entry map faithful and
 * auto-fixes the pilot's de buchstabensalat mis-map (it is the WORD-SCRAMBLE
 * /apps/ slug, so it now points to the word-scramble maker).
 *
 * Run from repo root: node scripts/seo-maker/build-maker-assets.js
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const REF = '49b501b0~1'; // parent of 49b501b0 (~1 not ^ — cmd.exe eats ^)
const LOCALES = ['en', 'de', 'fr', 'es', 'it', 'pt', 'nl', 'sv', 'da', 'no', 'fi'];

// 33 products.ts ALL_APPS keys (the canonical maker keys).
const MAKER_KEYS = [
  'addition', 'subtraction', 'code-addition', 'more-less', 'math-puzzle', 'math-worksheet',
  'alphabet-train', 'prepositions', 'word-guess', 'word-scramble', 'wordsearch', 'cryptogram', 'writing',
  'big-small', 'pattern-train', 'pattern-worksheet', 'draw-and-color', 'drawing-lines', 'coloring', 'chart-count',
  'matching', 'grid-match', 'shadow-match', 'bingo', 'picture-sort',
  'missing-pieces', 'odd-one-out', 'sudoku', 'picture-path',
  'find-and-count', 'find-objects', 'crossword', 'treasure-hunt',
];

// products-key -> tool-page-slugs.ts toolId (maker slug source). Default identity.
const TOOLID = { addition: 'image-addition', subtraction: 'image-subtraction', wordsearch: 'word-search' };
// products-key -> product-page-slugs.ts appId (/apps/ slug source). Default identity.
const APPID = {
  addition: 'image-addition', subtraction: 'subtraction', wordsearch: 'word-search',
  cryptogram: 'image-cryptogram', crossword: 'image-crossword', matching: 'matching-app',
  'big-small': 'big-small-app', bingo: 'picture-bingo', 'chart-count': 'chart-count-color', writing: 'writing-app',
};

function extractArray(tsSource, constName) {
  // Grab the [...] literal after `export const <name>...= ` up to the line `];`.
  const start = tsSource.indexOf(`export const ${constName}`);
  if (start < 0) throw new Error(`${constName} not found`);
  const eq = tsSource.indexOf('= [', start);
  const end = tsSource.indexOf('\n];', eq);
  if (eq < 0 || end < 0) throw new Error(`${constName} array bounds not found`);
  const literal = tsSource.slice(eq + 2, end + 2); // includes the closing ]
  // The literal is pure data (object/array literals with string values) — safe to eval.
  // eslint-disable-next-line no-eval
  return eval('(' + literal + ')');
}

const toolTs = execSync(`git show ${REF}:frontend/config/tool-page-slugs.ts`, { encoding: 'utf8', maxBuffer: 1 << 24 });
const prodTs = execSync(`git show ${REF}:frontend/config/product-page-slugs.ts`, { encoding: 'utf8', maxBuffer: 1 << 24 });

const toolPageSlugs = extractArray(toolTs, 'toolPageSlugs');
const productPageSlugs = extractArray(prodTs, 'productPageSlugs');

const toolByToolId = Object.fromEntries(toolPageSlugs.map((t) => [t.toolId, t.slugs]));
const appByAppId = Object.fromEntries(productPageSlugs.map((p) => [p.appId, p.slugs]));

const makerSlugs = {};
const redirects = {};
const warnings = [];

for (const key of MAKER_KEYS) {
  const toolId = TOOLID[key] || key;
  const appId = APPID[key] || key;
  const mSlugs = toolByToolId[toolId];
  const aSlugs = appByAppId[appId];
  if (!mSlugs) { warnings.push(`no maker slugs for ${key} (toolId ${toolId})`); continue; }
  makerSlugs[key] = {};
  for (const loc of LOCALES) {
    const mslug = mSlugs[loc];
    if (mslug) makerSlugs[key][loc] = mslug;
    const aslug = aSlugs && aSlugs[loc];
    if (mslug && aslug) redirects[`/${loc}/apps/${aslug}`] = `/${loc}/tools/${mslug}`;
  }
  const got = Object.keys(makerSlugs[key]).length;
  if (got !== LOCALES.length) warnings.push(`${key}: only ${got}/${LOCALES.length} maker slugs`);
}

// Emit maker-redirects.ts (sorted keys for stable diffs).
const sortedKeys = Object.keys(redirects).sort();
let out = `/**
 * 301 redirect map for the worksheet-maker SEO rescue (Part 1 Phase 1b).
 * AUTO-GENERATED by scripts/seo-maker/build-maker-assets.js from git ${REF}
 * (the pre-pivot slug configs). Do not hand-edit — re-run the generator.
 *
 * The pre-pivot site ranked BOTH /apps/<x>-worksheets and /tools/<x>-maker per
 * generator. We rebuild the canonical maker landing at /tools/<x>-maker and
 * 301 the /apps/ URL into it (recovers the equity the wholesale 410 discarded).
 * Keys are locale-prefixed pathnames WITHOUT trailing slash (middleware strips
 * one before lookup). Edge-runtime safe (plain object).
 */
export const MAKER_APPS_REDIRECTS: Record<string, string> = {
`;
for (const k of sortedKeys) out += `  ${JSON.stringify(k)}: ${JSON.stringify(redirects[k])},\n`;
out += `};\n`;

const outPath = path.join(__dirname, '..', '..', 'frontend', 'config', 'maker-redirects.ts');
fs.writeFileSync(outPath, out);

const slugsPath = path.join(__dirname, 'maker-slugs.json');
fs.writeFileSync(slugsPath, JSON.stringify(makerSlugs, null, 2) + '\n');

console.log(`Wrote ${outPath}`);
console.log(`Wrote ${slugsPath}`);
console.log(`redirects: ${sortedKeys.length}  makerKeys: ${Object.keys(makerSlugs).length}`);
if (warnings.length) { console.log('WARNINGS:'); warnings.forEach((w) => console.log('  - ' + w)); }
console.log('\n===MAKER_SLUGS_JSON===');
console.log(JSON.stringify(makerSlugs, null, 0));
