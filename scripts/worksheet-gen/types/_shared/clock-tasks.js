/** the three levels of a face: level 2 = D (the published config, untouched) */
function levelsFor(id, D, own) {
  const L = FACE_LEVELS[id];
  if (!L) throw new Error(`clock-tasks: no Level Set levels for ${id}`);
  const base = own || {};
  return { 1: { ...D, ...(base[1] || {}), ...L[1] }, 2: D, 3: L[3] ? { ...D, ...(base[3] || {}), ...L[3] } : D };
}

const hourAdd = (h, d) => ((((h - 1 + d) % 12) + 12) % 12) + 1;
/** the swapped-hands reading: the hour hand's place read as minutes, the minute hand's as the hour */
const swapOf = (h, m) => fmt(m === 0 ? 12 : Math.max(1, Math.min(12, Math.round(m / 5))), (h % 12) * 5);
/**
 * The wrong options of one clock (Level Set pages). Every candidate is a real misreading of THIS clock:
 *   adj   the hour before / after (the hour hand read from the wrong number)      adj2  two hours off
 *   far   an hour far away (level 1: an easy wrong answer)                         swap  the hands swapped
 *   oclock  the hour without its half (h:00 / next hour :00)                       half  the other half hour (m ± 30)
 *   min5 / min15  the minute hand read one mark (5 / 15 minutes) off               mirror  quarter past ↔ quarter to
 *   both  an hour AND a mark off (so the options sharing the right minutes / hour are not always the right one + one foil)
 * Of every set of (opts − 1) candidates, the builder keeps one where the right time sits at this card's DEALT rank
 * among the options (smallest … largest, as the numbers read — rankDeal spreads the ranks over the page; a fixed
 * "one hour later" foil made the right answer the smallest on every card), and that carries a `must` kind
 * (d.must, e.g. the swapped reading) on about half the cards. Random among the sets that qualify.
 */
function foilCandidates(h, m, d, rng) {
  const right = fmt(h, m), out = [];
  const add = (v, kind) => { if (v && v !== right && !out.some((o) => o.v === v)) out.push({ v, kind }); };
  const mm = (x) => (x >= 0 && x < 60 ? x : null);
  for (const k of d.foils) {
    if (k === 'adj') { add(fmt(hourAdd(h, -1), m), k); add(fmt(hourAdd(h, 1), m), k); }
    else if (k === 'adj2') { add(fmt(hourAdd(h, -2), m), k); add(fmt(hourAdd(h, 2), m), k); }
    else if (k === 'far') { for (const s of rng.shuffle([3, 4, 5, 6, 7, 8, 9]).slice(0, 4)) add(fmt(hourAdd(h, s), m), k); }
    else if (k === 'swap') add(swapOf(h, m), k);
    else if (k === 'oclock') { if (m !== 0) { add(fmt(h, 0), k); add(fmt(hourAdd(h, 1), 0), k); } }
    else if (k === 'half') add(fmt(h, (m + 30) % 60), k);
    else if (k === 'both') { for (const dh of [-1, 1]) for (const x of [m - 5, m + 5]) if (mm(x) !== null) add(fmt(hourAdd(h, dh), x), k); }
    else if (k === 'mirror') { if (m !== 0 && m !== 30) add(fmt(h, 60 - m), k); }
    else if (k === 'min5' || k === 'min15') { const st = k === 'min5' ? 5 : 15; for (const x of [m - st, m + st]) if (mm(x) !== null) add(fmt(h, x), k); }
    else throw new Error('clock-tasks: unknown foil ' + k);
  }
  return out;
}
function foilsFor(h, m, d, rng, wantRank) {
  const k = (d.opts || 3) - 1, right = fmt(h, m);
  const C = foilCandidates(h, m, d, rng);
  for (let s = 1; C.length < k && s < 12; s++) if (!C.some((o) => o.v === fmt(hourAdd(h, s), m))) C.push({ v: fmt(hourAdd(h, s), m), kind: 'fill' });
  const sets = [];
  const walk = (start, pick) => { if (pick.length === k) { sets.push(pick); return; } for (let i = start; i < C.length; i++) walk(i + 1, pick.concat([C[i]])); };
  walk(0, []);
  const mustHere = (d.must || []).length && rng.next() < 0.5;
  const pass = (set, useRank, useMust) => (!useRank || wantRank == null || rankOf(right, set.map((o) => o.v)) === wantRank)
    && (!useMust || !mustHere || set.some((o) => d.must.includes(o.kind)));
  for (const [r, mu] of [[true, true], [true, false], [false, true], [false, false]]) {
    const ok = sets.filter((set) => pass(set, r, mu));
    if (ok.length) return rng.pick(ok).map((o) => o.v);
  }
  throw new Error('clock-tasks: no foils for ' + right);
}

/** a time as its numbers read (7:45 → 745; 12:15 → 1215; "3:00 PM" → 300 — the child compares the printed numbers) */
const numValue = (t) => { const p = /(\d+)(?:\s*(?::|\.|h)\s*(\d\d))?/.exec(String(t)); return +p[1] * 100 + (+p[2] || 0); };
/** the rank of the right time among the options by numeric value: 0 smallest … n-1 largest (ties count below) */
const rankOf = (right, wrongs) => wrongs.filter((w) => numValue(w) < numValue(right)).length;
/** the ranks for a page of `cards` cards with k options: every rank equally often (±1), in the page's own order */
function rankDeal(rng, cards, k) { const r = rng.shuffle(Array.from({ length: k }, (_, i) => i)); return rng.shuffle(Array.from({ length: cards }, (_, i) => r[i % k])); }

/**
 * 12- and 24-hour forms per locale (Telling Time review 2026-10-14, MUST-FIX): only en writes "7:00 PM". es-MX writes
 * "7:00 p. m."; the other nine school systems write 24-hour time and say the 12-hour time with a part of the day
 * ("7 Uhr abends", "7 h du soir", "7 illalla") — so their pages draw hours from inside one part of the day (SAFE) and
 * print the day-part word. fr writes "19 h 30", fi "19.30" (also in the add / subtract answers). Self-contained (no
 * closure) — verify() runs the same source in the page.
 */
function convKit() {
  var pad = function (n) { return String(n).padStart(2, '0'); };
  var W = {
    de: { h: '{h} Uhr {w}', hm: '{h}:{mm} Uhr {w}', w: { m: 'morgens', a: 'nachmittags', e: 'abends' } },
    fr: { h: '{h} h {w}', hm: '{h} h {mm} {w}', w: { m: 'du matin', a: "de l'après-midi", e: 'du soir' } },
    it: { h: '{h} {w}', hm: '{h}:{mm} {w}', w: { m: 'di mattina', a: 'del pomeriggio', e: 'di sera' } },
    pt: { h: '{h}h {w}', hm: '{h}h{mm} {w}', w: { m: 'da manhã', a: 'da tarde', e: 'da noite' } },
    nl: { h: '{h} uur {w}', hm: '{h}:{mm} uur {w}', w: { m: "'s ochtends", a: "'s middags", e: "'s avonds" } },
    sv: { h: '{h} {w}', hm: '{h}:{mm} {w}', w: { m: 'på morgonen', a: 'på eftermiddagen', e: 'på kvällen' } },
    da: { h: '{h} {w}', hm: '{h}:{mm} {w}', w: { m: 'om morgenen', a: 'om eftermiddagen', e: 'om aftenen' } },
    no: { h: '{h} {w}', hm: '{h}:{mm} {w}', w: { m: 'om morgenen', a: 'om ettermiddagen', e: 'om kvelden' } },
    fi: { h: '{h} {w}', hm: '{h}.{mm} {w}', w: { m: 'aamulla', a: 'iltapäivällä', e: 'illalla' } },
  };
  var SAFE = { m: [6, 7, 8], a: [14, 15, 16], e: [19, 20] };
  var band = function (h24) { return h24 < 12 ? 'm' : h24 < 18 ? 'a' : 'e'; };
  var fill = function (t, o) { return t.replace(/\{(\w+)\}/g, function (_, k) { return o[k]; }); };
  /** the 12-hour form with an explicit part of the day (h12 1..12) */
  var word12 = function (loc, h12, m, b) { var L = W[loc]; return fill(m ? L.hm : L.h, { h: h12, mm: pad(m), w: L.w[b] }); };
  var ap = function (loc, pm) { return loc === 'es' ? (pm ? 'p. m.' : 'a. m.') : (pm ? 'PM' : 'AM'); };
  return {
    W: W, SAFE: SAFE, band: band, word12: word12, ap: ap,
    dayParts: function (loc) { return !!W[loc]; },
    conv12: function (loc, h24, m) { var h12 = (h24 % 12) || 12; return W[loc] ? word12(loc, h12, m, band(h24)) : h12 + ':' + pad(m) + ' ' + ap(loc, h24 >= 12); },
    conv24: function (loc, h24, m) { return loc === 'fr' ? (m ? h24 + ' h ' + pad(m) : h24 + ' h') : loc === 'fi' ? h24 + '.' + pad(m) : pad(h24) + ':' + pad(m); },
    /** an add / subtract answer (a clock time 1:00-12:59) */
    clockTime: function (loc, h, m) { return loc === 'fr' ? (m ? h + ' h ' + pad(m) : h + ' h') : loc === 'fi' ? h + '.' + pad(m) : h + ':' + pad(m); },
  };
}
