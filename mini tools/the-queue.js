    newState: function (size, pick) {
      var n = this.size(size), r = pick || Math.random, pool = FORMS.slice(), out = [], i, j;
      /* every member distinct: a queue whose members cannot be told
         apart cannot be asked "which one" */
      for (i = 0; i < n; i++) {
        j = Math.floor(r() * pool.length);
        out.push(FORMS.indexOf(pool[j]));
        pool.splice(j, 1);
      }
      return { members: out, end: null, k: 0 };
    },

    _st: function (st) { return st || this.st; },

    n: function (st) { return this._st(st).members.length; },

