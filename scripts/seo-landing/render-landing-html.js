const LANDING_LOCALES = ['en', 'de', 'es', 'sv', 'nl', 'da', 'it', 'no', 'fr', 'pt', 'fi'];

const _fileCache = {};
function loadFile(locale) {
  if (locale in _fileCache) return _fileCache[locale];
  let data = null;
  if (LANDING_LOCALES.includes(locale)) {
    for (const dir of LANDING_DIRS) {
      const p = path.join(dir, `${locale}.json`);
      if (fs.existsSync(p)) { data = JSON.parse(fs.readFileSync(p, 'utf8')); break; }
    }
  }
  _fileCache[locale] = data;
  return data;
}
function getAllLandings(locale) { const f = loadFile(locale); return f ? f.landings : []; }
function getLandingBySlug(locale, slug) {
  const f = loadFile(locale);
  return f ? (f.landings.find((l) => l.slug === slug) || null) : null;
}

/* ============================== lib/seo/url.ts ============================== */

const CANONICAL_HOST = 'https://www.lessoncraftstudio.com';
function canonicalUrl(p) {
  const stripped = p.replace(/\/+$/, '');
  const clean = stripped === '' ? '/' : stripped;
  return new URL(clean, CANONICAL_HOST).toString();
}
function localePath(locale, ...segments) {
  const tail = segments.filter(Boolean).join('/');
  return tail ? `/${locale}/${tail}` : `/${locale}`;
}

