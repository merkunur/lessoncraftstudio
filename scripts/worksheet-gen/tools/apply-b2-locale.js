#!/usr/bin/env node
/**
 * apply-b2-locale.js <locale|all> [--dry-run]
 *
 * Merges a validated nt20-B locale draft (i18n/.draft-b2-<loc>.json) into
 * every surface the batch needs:
 *
 *   i18n/strings.<loc>.json                 20 × {title, instruction}
 *   i18n/skill-sentences.<loc>.json         17 × {full, short}
 *   frontend/config/topics-taxonomy.json    axes['exercise-type'].<fam>.slug/name.<loc>
 *   frontend/messages/<loc>.json            topicMeta.<fam> ×17
 *   data/color-words.js                     +orange/purple/brown/pink for <loc>
 *   data/b2/{sentences,word-classes,shop-frames,wp-muldiv-frames,labels,figure-names}.js
 *                                           the <loc> block (module rewritten as GENERATED)
 *   data/b2/calendar-frames.js              the <loc> frames + optional name overrides
 *   data/b2/articles-overrides.js           {refuse, note} for <loc> when the panel set them
 *
 * Runs tools/validate-b2-draft.js first; refuses on any error, so a bad draft
 * cannot leave half the surfaces patched. Idempotent: re-applying the same
 * draft is a no-op. The en blocks in the data modules are preserved verbatim.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { validate } = require('./validate-b2-draft.js');

const WG = path.join(__dirname, '..');
const ROOT = path.join(WG, '..', '..');
const ALL = ['de', 'es', 'fr', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
const FAMILIES = ['word-tracing', 'dot-to-dot', 'grid-copy', 'singular-plural', 'articles', 'read-and-color', 'number-of-the-day', 'write-the-word', 'alphabetical-order', 'number-walls', 'doubles-halves', 'sentence-building', 'capitals-punctuation', 'word-classes', 'calendar', 'picture-writing', 'grid-coordinates'];
const TYPE_IDS = ['K-284', 'K-285', 'K-286', 'K-287', 'K-288', 'G1-242', 'G1-243', 'G1-244', 'G1-245', 'G1-246', 'G1-247', 'G1-248', 'G1-249', 'G2-274', 'G2-275', 'G2-276', 'G2-277', 'G2-278', 'G2-279', 'G3-370'];

const [, , which, flag] = process.argv;
const DRY = flag === '--dry-run';
if (!which) { console.error('usage: apply-b2-locale.js <locale|all> [--dry-run]'); process.exit(1); }
const LOCALES = which === 'all' ? ALL : [which];

const writeJson = (p, o, indent) => fs.writeFileSync(p, JSON.stringify(o, null, indent) + '\n');

/** Rewrite a data module as `header + const NAME = <json>; module.exports = { NAME }`. */
function writeModule(file, name, obj, header) {
  const src = `${header}\n'use strict';\n\nconst ${name} = ${JSON.stringify(obj, null, 2)};\n\nmodule.exports = { ${name} };\n`;
  fs.writeFileSync(file, src);
}
function loadModule(file, name, fallback) {
  if (!fs.existsSync(file)) return fallback;
  delete require.cache[require.resolve(file)];
  return require(file)[name];
}

const drafts = {};
for (const loc of LOCALES) {
  const file = path.join(WG, 'i18n', `.draft-b2-${loc}.json`);
  if (!fs.existsSync(file)) { console.error(`ABORT: no draft ${file}`); process.exit(1); }
  const draft = JSON.parse(fs.readFileSync(file, 'utf8'));
  const errs = validate(loc, draft);
  if (errs.length) { errs.forEach((e) => console.error(` - [${loc}] ${e}`)); console.error(`ABORT: ${errs.length} validation error(s) in ${loc}`); process.exit(1); }
  drafts[loc] = draft;
}
if (DRY) { console.log(`dry-run ok: ${LOCALES.join(',')} — ${TYPE_IDS.length} types, ${FAMILIES.length} families each`); process.exit(0); }

const taxPath = path.join(ROOT, 'frontend', 'config', 'topics-taxonomy.json');
const tax = JSON.parse(fs.readFileSync(taxPath, 'utf8'));

const GEN = (what) => `/**\n * ${what} — GENERATED by tools/apply-b2-locale.js from i18n/.draft-b2-<loc>.json.\n * Edit the drafts (or the en block via the source module's own header), never\n * this file by hand; the next apply rewrites it wholesale. Contract: see the\n * en block and docs/worksheet-gen/b2-design-specs.md.\n */`;

for (const loc of LOCALES) {
  const d = drafts[loc];
  // strings
  const sp = path.join(WG, 'i18n', `strings.${loc}.json`);
  const strings = JSON.parse(fs.readFileSync(sp, 'utf8'));
  for (const id of TYPE_IDS) strings[id] = { title: d.types[id].title, instruction: d.types[id].instruction };
  writeJson(sp, strings, 2);
  // skills
  const kp = path.join(WG, 'i18n', `skill-sentences.${loc}.json`);
  const skills = JSON.parse(fs.readFileSync(kp, 'utf8'));
  for (const fam of FAMILIES) skills[fam] = { full: d.skills[fam].full, short: d.skills[fam].short };
  writeJson(kp, skills, 2);
  // topicMeta
  const mp = path.join(ROOT, 'frontend', 'messages', `${loc}.json`);
  const msgs = JSON.parse(fs.readFileSync(mp, 'utf8'));
  for (const fam of FAMILIES) msgs.topicMeta[fam] = d.topicMeta[fam];
  writeJson(mp, msgs, 2);
  // taxonomy
  for (const fam of FAMILIES) {
    tax.axes['exercise-type'][fam].slug[loc] = d.families[fam].slug;
    tax.axes['exercise-type'][fam].name[loc] = d.families[fam].name;
  }
  // colour words (module keeps its hand-written header; only the object is rewritten)
  {
    const file = path.join(WG, 'data', 'color-words.js');
    const cw = loadModule(file, 'COLOR_WORDS');
    cw[loc] = { ...cw[loc], orange: d.colorWords.orange, purple: d.colorWords.purple, brown: d.colorWords.brown, pink: d.colorWords.pink };
    const src = fs.readFileSync(file, 'utf8');
    const start = src.indexOf('const COLOR_WORDS = {'), end = src.indexOf('};', start) + 2;
    const body = 'const COLOR_WORDS = {\n' + Object.entries(cw).map(([k, v]) => `  ${k}: ${JSON.stringify(v).replace(/"([a-z]+)":/g, '$1: ').replace(/,/g, ', ').replace(/"/g, "'")},`).join('\n') + '\n};';
    fs.writeFileSync(file, src.slice(0, start) + body + src.slice(end));
  }
  // data modules
  const mods = [
    ['sentences.js', 'SENTENCES', 'sentences', 'nt20-B sentence bank ×11'],
    ['word-classes.js', 'WORD_CLASSES', 'wordClasses', 'nt20-B word-class lists ×11'],
    ['shop-frames.js', 'SHOP_FRAMES', 'shopFrames', 'nt20-B shopping-math frames ×11'],
    ['wp-muldiv-frames.js', 'WP_MULDIV', 'wpMulDiv', 'nt20-B ×/÷ word-problem frames ×11'],
    ['labels.js', 'LABELS', 'labels', 'nt20-B label tables ×11'],
    ['figure-names.js', 'FIGURE_NAMES', 'figureNames', 'nt20-B figure names ×11'],
  ];
  for (const [file, name, key, what] of mods) {
    const p = path.join(WG, 'data', 'b2', file);
    const obj = loadModule(p, name, {});
    obj[loc] = d[key];
    writeModule(p, name, obj, GEN(what));
  }
  // calendar frames (+ optional name overrides)
  {
    const p = path.join(WG, 'data', 'b2', 'calendar-frames.js');
    const obj = loadModule(p, 'CALENDAR_FRAMES', {});
    obj[loc] = { frames: d.calendar.frames, ...(d.calendar.weekStart != null ? { weekStart: d.calendar.weekStart } : {}), ...(d.calendar.dayAbbr ? { dayAbbr: d.calendar.dayAbbr } : {}), ...(d.calendar.dayPlural ? { dayPlural: d.calendar.dayPlural } : {}), ...(d.calendar.dayNames ? { dayNames: d.calendar.dayNames } : {}), ...(d.calendar.monthNames ? { monthNames: d.calendar.monthNames } : {}), ...(d.calendar.ordinalStyle ? { ordinalStyle: d.calendar.ordinalStyle } : {}) };
    writeModule(p, 'CALENDAR_FRAMES', obj, GEN('nt20-B calendar frames + per-locale overrides'));
  }
  if (d.articles) {
    const p = path.join(WG, 'data', 'b2', 'articles-overrides.js');
    const obj = loadModule(p, 'ARTICLE_OVERRIDES', {});
    obj[loc] = d.articles;
    writeModule(p, 'ARTICLE_OVERRIDES', obj, GEN('nt20-B article-page overrides (refuse / chips notes)'));
  }
  console.log(`${loc}: 20 types, 17 skills, 17 topicMeta, 17 taxonomy slugs, colour words, ${mods.length + 1} data modules`);
}
writeJson(taxPath, tax, 2);
console.log(`applied ${LOCALES.length} locale(s)`);
