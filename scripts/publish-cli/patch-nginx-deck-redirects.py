#!/usr/bin/env python3
# Wire the old->new deck-slug 301 map into the Hetzner nginx server block.
# Backs up the live config to /root/nginx-backups/, installs the generated map
# file, prepends map-hash sizing (top of file, before any map), inserts a
# `map $uri $deck_redirect` block + an `if ($deck_redirect) return 301` at the
# top of the deck-serving location, then `nginx -t` and reload.
# AUTO-ROLLBACK on any test failure (with a diagnostic dump). Idempotent.
import subprocess, shutil, time, sys, os

CONF = '/etc/nginx/sites-enabled/lessoncraftstudio'
MAP_SRC = '/opt/lessoncraftstudio/old-slug-redirects.map'
MAP_DST = '/etc/nginx/old-slug-redirects.map'
BKDIR = '/root/nginx-backups'

os.makedirs(BKDIR, exist_ok=True)
stamp = time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())
bk = os.path.join(BKDIR, 'lessoncraftstudio.' + stamp)
shutil.copy2(CONF, bk)
print('backup:', bk)

shutil.copy2(MAP_SRC, MAP_DST)
print('map installed:', MAP_DST, sum(1 for _ in open(MAP_DST)), 'lines')

src = open(CONF).read()
changed = False

# 1. map-hash sizing at the VERY TOP (before any map block). ~8781 entries +
#    long URI keys need max_size > entry count and a bigger bucket.
if 'map_hash_max_size' not in src:
    src = 'map_hash_max_size 65536;\nmap_hash_bucket_size 128;\n\n' + src
    changed = True
    print('prepended map-hash sizing')
else:
    print('map-hash sizing already present (left as-is)')

# 2 + 3. deck redirect map + the in-location 301.
if 'deck_redirect' not in src:
    MAPBLOCK = (
        '# Native-slug-migration: 301 old English-token deck URLs -> native slug.\n'
        '# Body generated by scripts/publish-cli/gen-old-slug-redirects.js (~8781 entries).\n'
        'map $uri $deck_redirect {\n'
        '    default "";\n'
        '    include /etc/nginx/old-slug-redirects.map;\n'
        '}\n\n'
    )
    a = 'upstream nextjs {'
    assert src.count(a) == 1, 'anchor A (upstream nextjs) count != 1'
    src = src.replace(a, MAPBLOCK + a, 1)

    b = ('location ~ ^/(en|de|fr|es|pt|it|nl|sv|da|no|fi)/decks/(.+?)/$ {\n'
         '        alias /var/www/lcs-media/decks/$1/$2/;')
    assert src.count(b) == 1, 'anchor B (deck location) count != 1'
    src = src.replace(
        b,
        'location ~ ^/(en|de|fr|es|pt|it|nl|sv|da|no|fi)/decks/(.+?)/$ {\n'
        '        if ($deck_redirect) { return 301 $deck_redirect; }\n'
        '        alias /var/www/lcs-media/decks/$1/$2/;',
        1)
    changed = True
    print('inserted deck map + in-location 301')
else:
    print('deck_redirect already present (left as-is)')

if changed:
    open(CONF, 'w').write(src)

t = subprocess.run(['nginx', '-t'], capture_output=True, text=True)
print('nginx -t rc=' + str(t.returncode))
print((t.stderr or '').strip())
if t.returncode != 0:
    print('--- diagnostic: map_hash / deck_redirect lines in patched file ---')
    subprocess.run(['grep', '-nE', 'map_hash|deck_redirect', CONF])
    print('TEST FAILED -> restoring backup')
    shutil.copy2(bk, CONF)
    sys.exit(1)
r = subprocess.run(['systemctl', 'reload', 'nginx'], capture_output=True, text=True)
print('reload rc=' + str(r.returncode) + ' ' + (r.stderr or '').strip())
sys.exit(r.returncode)
