#!/usr/bin/env node
/**
 * Writes what the site shows of the unit checks of a language (Daily Teaching System, Part 7.1):
 * frontend/content/assessments/checks.<loc>.json, from what build-checks.js built (out/assessments/<loc>/checks.json).
 *
 * A check on the site is: its unit, its parts (the lesson each belongs to and how many tasks it has), the lessons
 * that are not in it, the page count of its forms, and a fingerprint of every card of both forms (so the gate can
 * prove on any machine that no card of form A is a card of form B). The PDFs are not in the repository: they are
 * built by build-checks.js and build-teacher-pages.js and uploaded with the Teacher-only files.
 *
 *   node scripts/assessments/assemble.js --loc=en [--check]
 *
 * (Stage C-2, 2026-11-22) The checks of the year:
 *   node scripts/assessments/assemble.js --loc=en --unit-tasks [--check]
 *     → scripts/assessments/year/unit-tasks.<loc>.json: the print of every box of every unit check (lib/task-print.js),
 *       from the text listings (out/assessments/<loc>/<unit>/dump.json) of the build that IS the committed checks file
 *       (a unit whose build is not the committed check stops it). build-checks.js --year keeps every check of the year
 *       clear of them, and gates.js proves it. Run it before the year build, and again whenever a unit check is rebuilt.
 *   node scripts/assessments/assemble.js --loc=en --year [--check]
 *     → frontend/content/assessments/year.<loc>.json, from out/assessments/<loc>/year/checks.json (build-checks.js --year);
 *       a check's status is kept on a rebuild (a new one starts as 'pilot'; it goes live by hand, after review)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { taskPrint } = require('./lib/task-print');
const REPO = path.join(__dirname, '..', '..');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : d; };
const loc = arg('loc', 'en');
const has = (k) => process.argv.includes('--' + k);

/** writes a generated file, or with --check says whether the committed one is today's */
function emit(out, text, what) {
  if (has('check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) { console.log('FAIL  ' + path.relative(REPO, out) + ' is not the build of today'); process.exit(1); }
    console.log(loc + ': ' + what + ' file is current');
  } else {
    fs.writeFileSync(out, text);
    console.log(loc + ': ' + what + ' → ' + path.relative(REPO, out));
  }
}
/** the fingerprint of the two forms of a committed unit check: a print list made from another build is refused */
const formsHash = (c) => crypto.createHash('sha1').update(JSON.stringify([c.forms.A.cards, c.forms.B.cards])).digest('hex').slice(0, 16);

if (has('unit-tasks')) {
  const committed = JSON.parse(fs.readFileSync(path.join(REPO, 'frontend', 'content', 'assessments', 'checks.' + loc + '.json'), 'utf8')).checks;
  const built = new Map(JSON.parse(fs.readFileSync(path.join(REPO, 'out', 'assessments', loc, 'checks.json'), 'utf8')).checks.map((c) => [c.unit, c]));
  const units = {}, bad = [];
  for (const c of committed) {
    const b = built.get(c.unit), dumpFile = path.join(REPO, 'out', 'assessments', loc, c.unit, 'dump.json');
    if (!b || !fs.existsSync(dumpFile)) { bad.push(c.unit + ': not built on this PC'); continue; }
    if (JSON.stringify([b.forms.A.sigs, b.forms.B.sigs]) !== JSON.stringify([c.forms.A.cards, c.forms.B.cards])) { bad.push(c.unit + ': the build in out/ is not the committed check'); continue; }
    const d = JSON.parse(fs.readFileSync(dumpFile, 'utf8'));
    // (a box that is a drawing only is printed by its type and its fingerprint in the checks file: lib/task-print.js)
    if (d.parts.length !== c.parts.length || d.parts.some((p, i) => p.type !== c.parts[i].type || p.formA.length !== c.forms.A.cards[i].length || p.formB.length !== c.forms.B.cards[i].length)) { bad.push(c.unit + ': its text listing does not have the boxes of the check'); continue; }
    const prints = (k) => d.parts.map((p, i) => p['form' + k].map((b, j) => taskPrint(b, { type: c.parts[i].type, sig: c.forms[k].cards[i][j] })));
    const A = prints('A'), B = prints('B');
    units[c.unit] = { of: formsHash(c), A, B };
  }
  if (bad.length) { for (const b of bad) console.log('FAIL  ' + b); process.exit(1); }
  emit(path.join(__dirname, 'year', 'unit-tasks.' + loc + '.json'), JSON.stringify({ $comment: 'GENERATED by scripts/assessments/assemble.js --unit-tasks from the text listings of the unit checks. The print of every box of both forms of every unit check (lib/task-print.js: the same text, pictures and answer is the same task); `of` fingerprints the forms of the committed check it was made from (gates.js: a stale list fails).', locale: loc, units }, null, 1) + '\n', 'unit-tasks');
} else if (has('placement')) {
  // (Stage C-3) the placement checks: frontend/content/assessments/placement.<loc>.json, from out/assessments/<loc>/placement/
  // checks.json (build-checks.js --placement); a check's status is kept on a rebuild (a new one starts as 'pilot')
  const src = path.join(REPO, 'out', 'assessments', loc, 'placement', 'checks.json');
  const out = path.join(REPO, 'frontend', 'content', 'assessments', 'placement.' + loc + '.json');
  if (!fs.existsSync(src)) { console.error('no ' + path.relative(REPO, src) + ' (run build-checks.js --placement first)'); process.exit(1); }
  const built = JSON.parse(fs.readFileSync(src, 'utf8')).checks;
  const before = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, 'utf8')).checks : [];
  const gradeOf = (u) => (u.startsWith('k-') ? 'K' : (/^g(\d)-/.exec(u) || [])[1]);
  const checks = built.map((c) => ({
    id: c.unit, path: c.year.path, subject: c.year.subject, slug: c.year.page, grades: c.year.grades,
    status: (before.find((x) => x.id === c.unit) || {}).status || 'pilot',
    // (fix round 2026-11-23) a step whose "start at" is another lesson carries it (unit, its page, lesson, title, grade, reason)
    steps: c.sections.map((s) => Object.assign({ step: s.part, slot: s.lesson, unit: s.unit, unitSlug: s.unitSlug, lesson: s.unitLesson, key: s.lessonKey, title: s.lessonTitle, type: s.type, grade: gradeOf(s.unit), tasks: s.cards }, s.startAt ? { startAt: { unit: s.startAt.unit, unitSlug: s.startAt.unitSlug, lesson: s.startAt.n, key: s.startAt.lesson, title: s.startAt.title, grade: s.startAt.grade } } : {})),
    ...(c.notBuilt && c.notBuilt.length ? { notBuilt: c.notBuilt } : {}),
    ...(c.writing ? { writing: { part: c.writing.part, type: c.writing.type, level: c.writing.level, taskA: c.writing.taskA, taskB: c.writing.taskB, points: c.writing.points.map((p) => ({ id: p.id, kind: p.kind, max: p.max })) } } : {}),
    forms: Object.fromEntries(['A', 'B'].map((k) => [k, { pages: c.forms[k].pages, cards: c.forms[k].sigs, tasks: c.forms[k].tasks, more: c.forms[k].more || [], pos: c.forms[k].pos, kinds: c.forms[k].kinds, sizes: c.forms[k].mags }])),
  }));
  emit(out, JSON.stringify({ $comment: 'GENERATED by scripts/assessments/assemble.js --placement from the build of scripts/assessments/build-checks.js --placement (blueprint: scripts/assessments/placement/' + loc + '.json). Do not edit by hand; a placement check goes live by its status here (kept on a rebuild), and its page shows only a live check.', locale: loc, checks }, null, 1) + '\n', 'placement checks');
} else if (has('year')) {
  const src = path.join(REPO, 'out', 'assessments', loc, 'year', 'checks.json');
  const out = path.join(REPO, 'frontend', 'content', 'assessments', 'year.' + loc + '.json');
  if (!fs.existsSync(src)) { console.error('no ' + path.relative(REPO, src) + ' (run build-checks.js --year first; the PC builds, the server only reads the committed file)'); process.exit(1); }
  const built = JSON.parse(fs.readFileSync(src, 'utf8')).checks;
  const before = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, 'utf8')).checks : [];
  const checks = built.map((c) => ({
    id: c.unit, grade: c.grade, subject: c.subject, time: c.year.time, slug: c.year.page, plan: c.year.plan,
    status: (before.find((x) => x.id === c.unit) || {}).status || 'pilot',
    parts: c.sections.map((s) => ({ part: s.part, slot: s.lesson, unit: s.unit, unitSlug: s.unitSlug, lesson: s.unitLesson, key: s.lessonKey, title: s.lessonTitle, type: s.type, tasks: s.cards })),
    ...(c.notBuilt && c.notBuilt.length ? { notBuilt: c.notBuilt } : {}),
    forms: Object.fromEntries(['A', 'B'].map((k) => [k, { pages: c.forms[k].pages, cards: c.forms[k].sigs, tasks: c.forms[k].tasks, more: c.forms[k].more || [], pos: c.forms[k].pos, kinds: c.forms[k].kinds, sizes: c.forms[k].mags }])),
  }));
  emit(out, JSON.stringify({ $comment: 'GENERATED by scripts/assessments/assemble.js --year from the build of scripts/assessments/build-checks.js --year (blueprint: scripts/assessments/year/' + loc + '.json). Do not edit by hand; a check of the year goes live by its status here (kept on a rebuild), and its page shows only live checks.', locale: loc, checks }, null, 1) + '\n', 'year checks');
} else {
  const src = path.join(REPO, 'out', 'assessments', loc, 'checks.json');
  const out = path.join(REPO, 'frontend', 'content', 'assessments', 'checks.' + loc + '.json');
  if (!fs.existsSync(src)) { console.error('no ' + path.relative(REPO, src) + ' (run build-checks.js first; the PC builds, the server only reads the committed file)'); process.exit(1); }
  const built = JSON.parse(fs.readFileSync(src, 'utf8')).checks;
  const before = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, 'utf8')).checks : [];
  const checks = built.map((c) => ({
    unit: c.unit, slug: c.slug, status: (before.find((x) => x.unit === c.unit) || {}).status || 'pilot',
    parts: c.sections.map((s) => ({ part: s.part, lesson: s.lesson, title: s.lessonTitle, type: s.type, tasks: s.cards })),
    notCovered: c.notCovered,
    forms: Object.fromEntries(['A', 'B'].map((k) => [k, { pages: c.forms[k].pages, cards: c.forms[k].sigs, pos: c.forms[k].pos, kinds: c.forms[k].kinds, sizes: c.forms[k].mags }])),
    // (Wave 4) the writing part of a writing unit: its place, its tasks and the ids and kinds of its points (2 each). The
    // rubric itself (what each level shows, the examples, what next) stays in the Teacher-only teacher pages.
    ...(c.writing ? { writing: { part: c.writing.part, type: c.writing.type, level: c.writing.level, taskA: c.writing.taskA, taskB: c.writing.taskB, points: c.writing.points.map((p) => ({ id: p.id, kind: p.kind, max: p.max })) } } : {}),
  }));
  const text = JSON.stringify({ $comment: 'GENERATED by scripts/assessments/assemble.js from the build of scripts/assessments/build-checks.js. Do not edit by hand; a check goes live by its status here (kept on a rebuild).', locale: loc, checks }, null, 1) + '\n';
  if (has('check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) { console.log('FAIL  ' + path.relative(REPO, out) + ' is not the build of today'); process.exit(1); }
    console.log(loc + ': checks file is current');
  } else {
    fs.writeFileSync(out, text);
    console.log(loc + ': ' + checks.length + ' check(s) → ' + path.relative(REPO, out));
  }
}
