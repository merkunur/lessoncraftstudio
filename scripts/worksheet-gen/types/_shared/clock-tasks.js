/**
 * Factory for the telling-time family (class 6):
 *  - 'read-circle':  clock → circle the digital time (G1-148 o'clock,
 *                    G1-149 half past, G2-249 five minutes, G2-250 quarter,
 *                    G3-354 to-the-minute — stepM differs)
 *  - 'match':        clocks ↔ digital times, draw lines (G1-150)
 *  - 'elapsed':      start + end clocks → write elapsed hours (G3-344)
 *  - 'convert-24h':  12h/24h conversion → circle the matching form (G3-355)
 *  - 'time-arith':   start clock + add/subtract a duration → write end time (G3-356)
 *  - 'draw':         digital time chip + EMPTY clock face → the child DRAWS
 *                    the hands (G1-212 — the production direction the read
 *                    modes lack; language-free digital prompt by design)
 *
 * Level Set (walk #64, 2026-10-14) — levels, screens, answer keys:
 *  Level 2 of every face is its published config, untouched: every knob below is read only when present, and the
 *  published pages build byte-identically (HEAD vs tree, all 87 per locale). Levels 1 / 3 live in FACE_LEVELS and are
 *  reached through levelsFor(id, D) — ⚠ the G1-233..237 variation files were generated by tools/gen-var-specs.js; they
 *  now call levelsFor, and a re-run of the generator would flatten them back to {1: D, 2: D, 3: D}.
 *  Knobs (stamped on the page as data-lcs-tt / data-lcs-tq, re-checked by verify()):
 *    ls        a Level Set config (the page carries the stamps; the published d2 never has it)
 *    opts      options per clock (read-circle) — 2 / 3 / 4
 *    foils     the wrong options, by kind (FOIL below): never "always one hour later" (the right time would then be the
 *              earliest option on every card — a rank tell); adj / grid go one hour up OR down
 *    numerals / minuteMarks / minuteRing / preset   clock-face options (primitives/clock.js)
 *    sameHour  times come in pairs that share their hour (7:15 / 7:45)
 *    pairs     match: the number of clock ↔ time pairs; sameHour: 7:00 / 7:30 / 6:30 on one page
 *    durMax / cross12   elapsed: the longest duration / how many cards pass 12 o'clock
 *    quarters  time-arith: starts and durations in quarter hours, every card crossing an hour
 *  Screens (ctx.interactive): tap the time (read / convert / match), type the hours (elapsed), type hours + minutes
 *  (time-arith), drag the hands (draw — the set-clock runtime). Keys (ctx.answerKey): the right time ringed, the
 *  numbers written in, the hands drawn.
 */
