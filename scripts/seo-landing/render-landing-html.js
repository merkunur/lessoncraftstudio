/**
 * render-landing-html.js — static-HTML generator for the tier-3 deck LANDING pages.
 *
 * THE ARCHITECTURAL FIX (2026-07-05 build incident, plan rev 4): the ~30k
 * /[locale]/worksheets/[slug] landings are pure content — a deterministic function of
 * content/seo-landing/<locale>.json + topics-taxonomy.json + maker-content — yet they
 * lived inside the Next.js webpack graph, which made every cold `next build` a
 * 35-50GB / 60-90min monster (the recurring all-day build crises). This script moves
 * them to the platform's PROVEN content model (§15.7/§17.8: the 28k deck pages —
 * static HTML generated by script, served by nginx, SEO baked at generate time).
 *
 * It is a FAITHFUL PORT of frontend/app/[locale]/worksheets/[slug]/page.tsx
 * (the 673-line route) + its lib helpers:
 *   lib/seo/{landing-content,url,hreflang,breadcrumb-schema,embed-snippet}.ts,
 *   lib/{taxonomy,target-language,img-host,schema-generator(ogLocaleMap)}.ts,
 *   lib/seo/maker-content.ts, components/worksheets/EmbedWorksheet.tsx (→ vanilla JS).
 * The SEO surface (title/meta/robots/canonical/hreflang/OG/twitter/JSON-LD/h1/
 * internal links) is intended to be semantically identical to the Next render;
 * verify with:  node render-landing-html.js --locale=en --slug=<slug> --stdout
 * and diff the <head> + JSON-LD against the live route.
 *
 * Usage (on Hetzner, repo at /opt/lessoncraftstudio):
 *   node scripts/seo-landing/render-landing-html.js --locales=en,de --out=/var/www/lcs-media/landings
 *   node scripts/seo-landing/render-landing-html.js --locale=en --slug=addition-find-addend-animals --stdout
 *   node scripts/seo-landing/render-landing-html.js               (all locales → default out dir)
 * Zero npm dependencies. Idempotent (atomic tmp+rename per file).
 */
