#!/usr/bin/env node
/**
 * "What a unit could use" (Daily Teaching System, Part 1 step 3): for every teaching point, in teaching order, what
 * a language really has — printable faces, pages with a screen version, Level Sets, the maker, tools, live
 * activities and planned ones.
 *
 *   node scripts/teaching-graph/report.js
 *     → out/teaching-graph/unit-could-use.<loc>.md ×11     the full list, one line per point (generated, not committed)
 *     → docs/daily-teaching-system/graph/COVERAGE.md        the summary a planner reads (committed)
 *
 * Reads only the committed graph (points.json, tools.json, assets/<loc>.json). A point counts as "has a printable"
 * in a language when at least one page of one of its types is published there.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.join(__dirname, '..', '..');
const DIR = path.join(REPO, 'frontend', 'content', 'teaching-graph');
const OUT = path.join(REPO, 'out', 'teaching-graph');
const LOCALES = ['en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'sv', 'da', 'no', 'fi'];
const GRADES = ['K', '1', '2', '3'];
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const sum = (a) => a[0] + a[1] + a[2];

/** what one point has in one language */
function pointIn(p, a, toolsByPoint) {
  const faces = p.types.filter((id) => a.types[id] && sum(a.types[id].p) > 0);
  return {
    faces: faces.length,
    pages: faces.reduce((n, id) => n + sum(a.types[id].p), 0),
    screens: faces.filter((id) => sum(a.types[id].s) > 0).length,
    sets: faces.filter((id) => a.types[id].set).length,
    setsWithScreen: faces.filter((id) => a.types[id].set && sum(a.types[id].s) >= 2).length,
    landings: faces.filter((id) => a.types[id].landing).length,
    makers: [...new Set(p.types.map((id) => a.types[id] && a.types[id].maker).filter(Boolean))],
    tools: (toolsByPoint.get(p.id) || []).filter((k) => a.tools[k]),
    activities: p.activities.filter((id) => a.activities[id]),
    planned: p.planned,
  };
}

function build() {
  const points = readJson(path.join(DIR, 'points.json')).points;
  const tools = readJson(path.join(DIR, 'tools.json')).tools;
  const toolsByPoint = new Map();
  for (const [k, t] of Object.entries(tools)) for (const id of t.points || []) { if (!toolsByPoint.has(id)) toolsByPoint.set(id, []); toolsByPoint.get(id).push(k); }
  const subjects = [...new Set(points.map((p) => p.subject))];
  const per = {}, summary = {};
  for (const loc of LOCALES) {
    const a = readJson(path.join(DIR, 'assets', loc + '.json'));
    const L = ['# What a unit could use — ' + loc, '', 'One line per teaching point, in teaching order. faces = worksheet types with a published page here · screen = of those, with an on-screen version · sets = Level Sets · then the maker, the tools, the live activities and the planned activity numbers.', ''];
    summary[loc] = {};
    for (const s of subjects) {
      const S = summary[loc][s] = { points: 0, printable: 0, screen: 0, set: 0, setScreen: 0, maker: 0, tool: 0, activity: 0, byGrade: {} };
      L.push('## ' + s, '');
      for (const g of GRADES) {
        const ps = points.filter((p) => p.subject === s && p.grade === g);
        if (!ps.length) continue;
        const G = S.byGrade[g] = { points: ps.length, printable: 0, screen: 0 };
        L.push('### grade ' + g, '');
        for (const p of ps) {
          const x = pointIn(p, a, toolsByPoint);
          S.points++;
          if (x.faces) { S.printable++; G.printable++; }
          if (x.screens) { S.screen++; G.screen++; }
          if (x.sets) S.set++;
          if (x.setsWithScreen) S.setScreen++;
          if (x.makers.length) S.maker++;
          if (x.tools.length) S.tool++;
          if (x.activities.length) S.activity++;
          L.push('- ' + (x.faces ? '' : '**NOTHING HERE** ') + p.id + ' — ' + x.faces + ' of ' + p.types.length + ' faces (' + x.pages + ' pages), ' + x.screens + ' screen, ' + x.sets + ' sets'
            + (x.makers.length ? ' · maker: ' + x.makers.join(', ') : '') + (x.tools.length ? ' · tools: ' + x.tools.join(', ') : '')
            + (x.activities.length ? ' · activities: ' + x.activities.length : '') + (x.planned.length ? ' · planned: #' + x.planned.join(' #') : ''));
        }
        L.push('');
      }
    }
    per[loc] = L.join('\n');
  }
  return { per, summary, subjects, points };
}

if (require.main === module) {
  const r = build();
  fs.mkdirSync(OUT, { recursive: true });
  for (const loc of LOCALES) fs.writeFileSync(path.join(OUT, 'unit-could-use.' + loc + '.md'), r.per[loc]);
  const M = ['# Content graph — what each language has, by subject', '',
    'Generated by `node scripts/teaching-graph/report.js` from the committed graph (`frontend/content/teaching-graph/`). The full list per language, one line per teaching point, is written to `out/teaching-graph/unit-could-use.<loc>.md`.', '',
    'A cell reads **points that have it / points of the subject**. "printable" = at least one page of one of the point\'s worksheet types is published in that language. "screen" = one of those types has a page with a Check button. "Level Set" = a type with two or more pages; "playable set" = with at least two on-screen pages. "maker" = a maker template for one of its types is built in that language.', ''];
  for (const s of r.subjects) {
    M.push('## ' + s, '', '| language | printable | screen | Level Set | playable set | maker | tool | live activity |', '|---|---|---|---|---|---|---|---|');
    for (const loc of LOCALES) { const S = r.summary[loc][s]; const c = (n) => n + ' / ' + S.points; M.push('| ' + loc + ' | ' + [c(S.printable), c(S.screen), c(S.set), c(S.setScreen), c(S.maker), c(S.tool), c(S.activity)].join(' | ') + ' |'); }
    M.push('');
    M.push('By grade, points with a printable (en · de · fi shown as the widest, a middle and the narrowest catalogue):', '');
    M.push('| grade | points | ' + ['en', 'de', 'fi'].join(' | ') + ' |', '|---|---|---|---|---|');
    for (const g of GRADES) { const e = r.summary.en[s].byGrade[g]; if (!e) continue; M.push('| ' + g + ' | ' + e.points + ' | ' + ['en', 'de', 'fi'].map((l) => r.summary[l][s].byGrade[g].printable).join(' | ') + ' |'); }
    M.push('');
  }
  fs.writeFileSync(path.join(REPO, 'docs', 'daily-teaching-system', 'graph', 'COVERAGE.md'), M.join('\n'));
  const en = r.summary.en;
  console.log('report: ' + r.points.length + ' points × 11 languages → docs/daily-teaching-system/graph/COVERAGE.md; en math ' + en.math.printable + '/' + en.math.points + ' printable, literacy ' + en.literacy.printable + '/' + en.literacy.points);
}
module.exports = { build, pointIn };
